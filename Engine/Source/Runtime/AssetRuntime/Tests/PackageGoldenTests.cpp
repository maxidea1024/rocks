// 고정 장면이다: A(1700) 대표 에셋(값·문자열·Hard → B 대표 에셋·Soft·bulk·EditorOnly
// 값·bulk·Hard)과 하위 객체 Part(bulk), B(1701) 대표 에셋.
struct Golden {
    explicit Golden(Allocator& allocator) noexcept : pixels(allocator), data(allocator) {
    }

    RootRef<Package> a;
    RootRef<Package> b;
    Array<uint8> pixels;
    Array<uint8> data;
    TestBulkSource bulk;
};

bool MakeGolden(ObjectRegistry& registry, Golden& golden) noexcept {
    const ObjectAccessContext access = registry.OwnerAccess();
    auto a = NewPackage(registry, access, FixedId(1700), PackageKind::Editor);
    auto b = NewPackage(registry, access, FixedId(1701), PackageKind::Editor);
    if (!a || !b) {
        return false;
    }

    golden.a = Move(a.Value());
    golden.b = Move(b.Value());
    const ObjectHandle bAsset = Make<TestAsset>(registry, TestAssetType(), golden.b.Handle(), "");
    const ObjectHandle asset = Make<TestAsset>(registry, TestAssetType(), golden.a.Handle(), "");
    const ObjectHandle part = Make<TestPart>(registry, TestPartType(), asset, "Part");
    TestAsset* pointer = Pointer<TestAsset>(registry, asset);
    if (bAsset.IsNull() || part.IsNull() || pointer == nullptr) {
        return false;
    }

    FillCompressible(golden.pixels, 3000, 17);
    FillIncompressible(golden.data, 32, 17);
    pointer->value = 1700;
    pointer->pixels = golden.bulk.Add(1, golden.pixels.View());
    pointer->source = golden.bulk.Add(2, golden.data.View());
    Pointer<TestPart>(registry, part)->index = 3;
    Pointer<TestPart>(registry, part)->data = golden.bulk.Add(3, golden.data.View());
    return pointer->label.TryAssign("golden").IsOk() && pointer->note.TryAssign("note").IsOk() &&
           pointer->soft.TryAssign(FixedId(1702), "Sub").IsOk() &&
           registry.SetReference(access, asset, pointer->hard, bAsset).IsOk() &&
           registry.SetReference(access, asset, pointer->editorRef, bAsset).IsOk();
}

// 풍부한 장면의 커스텀 버전 표(id 오름차순)와 Build 의존이다(DependencyDeclarer가 줄 목록
// — 16.2절).
const PackageCustomVersion GoldenCustomVersions[] = {{Guid{0x601D, 1}, 2}, {Guid{0x601D, 2}, 7}};
const PackageDependencyEntry GoldenBuildDependencies[] = {
    {FixedId(1703), PackageDependencyKind::Build, TypeId{}, false}};

// 풍부한 에디터 장면의 ImportRecord·Tags Record byte다(Tags 키 엄격 오름차순).
struct GoldenRecords {
    explicit GoldenRecords(Allocator& allocator) noexcept
        : importRecord(allocator), tags(allocator) {
    }

    Array<uint8> importRecord;
    Array<uint8> tags;
};

bool MakeGoldenRecords(Allocator& allocator, GoldenRecords& records) noexcept {
    const uint8 importerVersion[4] = {3, 0, 0, 0};
    const uint8 value[4] = {1, 2, 3, 4};
    RecordBuilder importRecord(allocator, Guid{0x601D, 0x1EC0}, 1);
    RecordBuilder tags(allocator, Guid{0x601D, 0x7A65}, 1);
    if (!importRecord.AddField(Guid{0x601D, 0x11}, WireType::U32, importerVersion) ||
        !tags.AddField(Guid{1, 1}, WireType::U32, value) ||
        !tags.AddField(Guid{1, 2}, WireType::U32, value)) {
        return false;
    }

    auto builtImport = importRecord.Build();
    auto builtTags = tags.Build();
    if (!builtImport || !builtTags) {
        return false;
    }

    records.importRecord = Move(builtImport.Value());
    records.tags = Move(builtTags.Value());
    return true;
}

// 풍부한 에디터 옵션이다: import(B 대표 에셋 Hard·EditorOnly Hard)·Zstd 블록 bulk·커스텀 버전·
// ImportRecord·Tags·Build 의존.
PackageWriteOptions RichEditorOptions(Golden& golden, const GoldenRecords& records) noexcept {
    PackageWriteOptions options = EditorOptions();
    options.bulkSource = &golden.bulk;
    options.bulkCodec = BulkCodec::Zstd;
    options.customVersions = GoldenCustomVersions;
    options.importRecord = records.importRecord.View();
    options.tags = records.tags.View();
    options.extraDependencies = GoldenBuildDependencies;
    return options;
}

// digest의 소문자 16진 표기다.
String HexOf(Allocator& allocator, Span<const uint8> bytes) noexcept {
    constexpr char Digits[] = "0123456789abcdef";
    String text(allocator);
    for (uint8 value : bytes) {
        const char pair[2] = {Digits[value >> 4], Digits[value & 0xF]};
        (void)text.TryAppend(StringView(pair, 2));
    }

    return text;
}

// 출력 SHA-256이 기대와 같은지 본다(다르면 실제 값을 실패 문구로 남긴다).
bool SameDigest(Allocator& allocator, Span<const uint8> file, StringView expected) noexcept {
    const Sha256Digest digest = Sha256::Hash(file);
    String actual = HexOf(allocator, Span<const uint8>(digest.bytes, Sha256Digest::Bytes));
    if (actual.View() == expected) {
        return true;
    }

    test::RecordFailure(actual.CStr(), __FILE__, __LINE__);
    return false;
}

