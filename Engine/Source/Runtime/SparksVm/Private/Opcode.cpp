const OpcodeInfo& InfoOf(Opcode op) noexcept {
    const usize index = static_cast<usize>(op);
    if (index >= static_cast<usize>(Opcode::Count)) {
        platform::Fatal("Sparks opcode out of range");
    }

    return OpcodeInfos[index];
}

const char* ScalarKindName(ScalarKind kind) noexcept {
    const usize index = static_cast<usize>(kind);
    return index < sizeof(ScalarKindNames) / sizeof(ScalarKindNames[0]) ? ScalarKindNames[index]
                                                                        : "?";
}

