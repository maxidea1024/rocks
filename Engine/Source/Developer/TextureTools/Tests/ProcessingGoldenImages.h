inline constexpr unsigned MipCaseCount = sizeof(MipCases) / sizeof(MipCases[0]);

// 입력 평면 수다(Volume 깊이, 그 밖 slice 수).
inline constexpr unsigned PlaneCount(const MipCase& one) {
    return one.slices;
}

inline constexpr unsigned Hash(unsigned seed, unsigned a, unsigned b, unsigned c) {
    unsigned h = seed * 0x9E3779B1u + a * 0x85EBCA77u + b * 0xC2B2AE3Du + c * 0x27D4EB2Fu;
    h ^= h >> 15;
    h *= 0x2C1B3C6Du;
    h ^= h >> 12;
    h *= 0x297A2D39u;
    h ^= h >> 15;
    return h;
}

// golden이 출력 byte 대신 담는 해시다(FNV-1a 64 — 큰 경우는 해시만 담는다).
inline unsigned long long Fnv1a64(const unsigned char* data, unsigned long long size) {
    unsigned long long hash = 0xcbf29ce484222325ull;
    for (unsigned long long index = 0; index < size; ++index) {
        hash ^= data[index];
        hash *= 0x100000001b3ull;
    }

    return hash;
}

// golden이 출력 float 전부를 담는 경우의 상한이다(넘으면 mip마다 해시만).
inline constexpr unsigned FullDataFloats = 2048;

// texels에 sizeX × sizeY × slices × RGBA float를 쓴다(평면마다 행 우선).
inline void Generate(const MipCase& one, float* texels) {
    const unsigned planes = PlaneCount(one);
    for (unsigned plane = 0; plane < planes; ++plane) {
        for (unsigned y = 0; y < one.sizeY; ++y) {
            for (unsigned x = 0; x < one.sizeX; ++x) {
                float* out = texels + ((plane * one.sizeY + y) * one.sizeX + x) * 4;
                const unsigned position = (plane * 4096u + y) * 4096u + x;
                for (unsigned channel = 0; channel < 4; ++channel) {
                    const unsigned h = Hash(one.seed, position, channel, plane);
                    int milli = 0;
                    if (one.pattern == Noise) {
                        milli = channel == 3 ? static_cast<int>(h % 1001u)
                                             : static_cast<int>(h % 1301u) - 100;
                    } else if (one.pattern == Smooth) {
                        const int base =
                            static_cast<int>((x * 1000u) / one.sizeX + (y * 500u) / one.sizeY) /
                            (channel + 1);
                        milli = base + static_cast<int>(h % 61u) - 30;
                        if (channel == 3) {
                            const int dx =
                                static_cast<int>(2 * x + 1) - static_cast<int>(one.sizeX);
                            const int dy =
                                static_cast<int>(2 * y + 1) - static_cast<int>(one.sizeY);
                            const int r =
                                (dx * dx + dy * dy) * 1000 /
                                static_cast<int>(one.sizeX * one.sizeX + one.sizeY * one.sizeY);
                            milli = 1000 - r + static_cast<int>(h % 101u) - 50;
                            milli = milli < 0 ? 0 : (milli > 1000 ? 1000 : milli);
                        }
                    } else {
                        milli = channel == 3 ? 450 + static_cast<int>(h % 101u)
                                             : static_cast<int>(h % 1001u);
                    }

                    out[channel] = static_cast<float>(milli) / 1000.0f;
                }
            }
        }
    }
}

