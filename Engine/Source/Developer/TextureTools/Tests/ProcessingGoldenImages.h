// 차원이다(UE 빌드 설정 bCubemap·bVolume·bTextureArray 조합).
enum Dimension : unsigned {
    Flat,
    Volume,
    Cube,
    CubeArray,
    Array,
};

// 값은 UE·Rocks 공통 enum 값이다(TextureMipGenSettings·TextureCompressionSettings·TextureAddress).
enum MipGen : unsigned {
    SimpleAverage = 1,
    Sharpen0 = 2,
    Sharpen5 = 7,
    Sharpen10 = 12,
    NoMipmaps = 13,
    Blur1 = 15,
    Blur3 = 17,
    Blur5 = 19,
    Unfiltered = 20,
};

enum Compression : unsigned {
    Default = 0,
    Normalmap = 1,
    Masks = 2,
};

enum Address : unsigned {
    Wrap = 0,
    Clamp = 1,
    Mirror = 2,
    Border = 3,
};

// 그림 종류다.
enum Pattern : unsigned {
    // 채널마다 독립 해시 — [−0.1, 1.2](범위 밖 값으로 자르지 않음을 본다), 알파 [0, 1].
    Noise,
    // 부드러운 기울기 + 작은 해시, 알파는 가운데가 높은 원.
    Smooth,
    // 알파만 임계값 근처(0.45–0.55)에 몰린 그림 — coverage 경계.
    AlphaNearHalf,
};

struct MipCase {
    const char* name;
    Pattern pattern;
    unsigned seed;
    Dimension dimension;
    unsigned sizeX;
    unsigned sizeY;
    // Volume 깊이, Cube 6, CubeArray 6의 배수, Array slice 수, 그 밖 1.
    unsigned slices;
    MipGen mipGen;
    Compression compression;
    bool useNewMipFilter;
    // alpha coverage 임계값(천분율, 넷 모두 0이면 끔).
    unsigned thresholdMilli[4];
    bool preserveBorder;
    Address addressX;
    Address addressY;
    // 0이면 사슬 전체, 그 밖은 최대 크기(단계 경로 — 이 크기 이하가 될 때까지 한 mip씩).
    unsigned maxSize;
};

