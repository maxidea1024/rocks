using System.Globalization;
using System.Text;

namespace Rocks.MetaCompiler;

internal static class CppEmitter
{
    private static string GuidValue(string? id) => id is null ? "Guid{}" : $"Guid{{0x{id[..16]}ull, 0x{id[16..]}ull}}";

    private static readonly UTF8Encoding Utf8 = new(false, true);

    // 읽을 수 있는 UTF-8은 그대로 남긴다. 제어 바이트는 정확히 세 자리 8진수로 출력하여
    // 뒤 문자가 숫자·16진수여도 escape에 흡수되지 않게 한다. Span 길이는 항상 UTF-8 바이트다.
    private static string Label(string text)
    {
        _ = Utf8.GetBytes(text); // 잘못된 surrogate를 대체 문자로 바꾸지 않고 거부한다.
        StringBuilder result = new("\"");
        foreach (Rune rune in text.EnumerateRunes())
        {
            if (rune.Value == '"')
            {
                result.Append("\\\"");
            }
            else if (rune.Value == '\\')
            {
                result.Append("\\\\");
            }
            else if (rune.Value == '\n')
            {
                result.Append("\\n");
            }
            else if (rune.Value == '\r')
            {
                result.Append("\\r");
            }
            else if (rune.Value == '\t')
            {
                result.Append("\\t");
            }
            else if (Rune.GetUnicodeCategory(rune) is UnicodeCategory.Control or UnicodeCategory.Format or
                     UnicodeCategory.LineSeparator or UnicodeCategory.ParagraphSeparator)
            {
                foreach (byte value in Utf8.GetBytes(rune.ToString()))
                {
                    result.Append('\\').Append(Convert.ToString(value, 8).PadLeft(3, '0'));
                }
            }
            else
            {
                result.Append(rune.ToString());
            }
        }

        return result.Append('"').ToString();
    }

    private static string View(string text) => $"Span<const char>({Label(text)}, {Utf8.GetByteCount(text)})";

    // 등록 함수의 이름이다. public 타입은 RegisterModuleTypes, private 헤더의 타입은 RegisterPrivateModuleTypes가 등록한다.
    private static string RegistrationFunction(bool privateTypes) => privateTypes ? "RegisterPrivateModuleTypes" : "RegisterModuleTypes";

    // 등록 함수의 서명이다. 모듈 생성 헤더의 선언과 모듈 생성 소스의 정의가 이 한 곳에서 나오므로 둘이 어긋나지 않는다(뒤에 모듈 API
    // 매크로를 붙일 때도 이 자리만 고친다 — Docs/Design/ReflectionGeneratedSources.ko.md 5.5절). 기본 인자는 선언에만 둔다. 모듈 이름이
    // rocks의 이름(Result 등)을 가리지 않도록 모든 이름을 ::rocks::로 한정한다.
    private static string RegistrationSignature(bool privateTypes, bool declaration) =>
        $"::rocks::Result<void> {RegistrationFunction(privateTypes)}(::rocks::ModuleRegistration& registration, " +
        $"const ::rocks::ModuleLease& module{(declaration ? " = {}" : "")}) noexcept";

    // 이 모듈 자신의 타입만(public 다음 private, 의존 모듈 없이) 등록하는 함수의 서명이다(Docs/Design/ModuleLoader.ko.md 3.10절). 모듈
    // 로더가 진입 기술의 registerTypes로 부르며 lease는 로더가 발급한 이 모듈의 것이다. 진입점 매크로(ROCKS_IMPLEMENT_MODULE,
    // ROCKS_MODULE_TYPES=1)가 같은 서명으로 스스로 선언하므로 기본 인자를 두지 않는다.
    private static string OwnTypesSignature() =>
        "::rocks::Result<void> RegisterModuleOwnTypes(::rocks::ModuleRegistration& registration, const ::rocks::ModuleLease& module) noexcept";

    // 모듈 생성 헤더다(Docs/Design/ReflectionGeneratedSources.ko.md 5.5절). 등록 함수의 선언만 담는다 — 타입별 생성 헤더와 의존 모듈의
    // 헤더를 include하지 않으므로 등록만 하는 번역 단위가 모듈의 모든 생성 코드를 끌어오지 않는다. 정의는 모듈 생성 소스
    // (EmitModuleSource)에 한 번 있다. public 헤더는 RegisterModuleTypes, private 헤더(private 리플렉션 헤더가 있는 모듈만)는
    // RegisterPrivateModuleTypes를 선언한다.
    public static string EmitModuleHeader(string module, bool privateTypes)
    {
        StringBuilder output = new();
        void Line(string text = "") => output.Append(text).Append('\n');
        Line("// Generated by Rocks MetaCompiler. Do not edit by hand. Declares the function that registers the module's " +
            (privateTypes ? "private " : "") + "reflection types.");
        Line("// The definition is in the module generated source (<Module>.module.generated.cpp), compiled once by the owning module.");
        Line("// Include the generated header of a type (<Module/Type.generated.h>) to use its GeneratedType.");
        Line("#pragma once");
        Line("#include <Object/ModuleRegistration.h>");
        // 모듈 API 매크로는 빌드가 정의 헤더로 넣는다. 빌드 밖에서 이 헤더를 컴파일하는 도구(시험)는 빈 값을 쓴다(Monolithic과 같다).
        if (!privateTypes)
        {
            Line($"#ifndef {ApiMacro(module)}");
            Line($"#define {ApiMacro(module)}");
            Line("#endif");
        }

        Line($"namespace rocks::generated::{module} {{");
        // public 등록 함수는 다른 모듈(의존 모듈의 등록·호스트)이 부르므로 모듈 API 매크로로 export한다(Docs/Design/BuildTargets 3.8절 BS8d2).
        // private 등록 함수는 그 모듈 안에서만 부른다.
        Line((privateTypes ? "" : ApiMacro(module) + " ") + RegistrationSignature(privateTypes, declaration: true) + ";");
        // public·private 헤더 모두 같은 선언을 둔다(어느 쪽만 있는 모듈도 있다 — 같은 선언의 반복은 허용된다).
        Line("// Registers only this module's own types (public, then private) without dependency modules; the module loader calls it.");
        Line(OwnTypesSignature() + ";");
        Line($"}} // namespace rocks::generated::{module}");
        return output.ToString();
    }

    // 모듈 생성 소스다(Docs/Design/ReflectionGeneratedSources.ko.md 5.5절). 모듈마다 하나이고 그 모듈의 번역 단위로 한 번만 컴파일된다.
    // 이 모듈의 모듈 생성 헤더, 의존 모듈(import)의 public 모듈 생성 헤더, 이 모듈의 타입별 생성 헤더(public·private)를 include하고 두 등록
    // 함수를 정의한다. public 함수는 의존 모듈의 RegisterModuleTypes를 먼저 부르고 이 모듈 타입을 enum → struct(쓰는 struct 먼저 —
    // 순위·이름 순) → 클래스(base 먼저) 순으로 등록한다(같은 ID·같은 native 타입이 이미 있으면 건너뛴다). 실패하면 이 호출이 등록한
    // 것을 역순으로 해제한다. private 함수는 public 함수를(public 헤더가 없으면 의존 모듈의 함수를 직접) 먼저 부른 뒤 private 타입을
    // 등록한다. 파일 지역 이름과 매크로는 정의하지 않는다(다른 생성 소스와 한 번역 단위로 묶여도 충돌하지 않는다).
    public static string EmitModuleSource(string module, SchemaModel schema, IReadOnlyList<ModuleInput> inputs,
        IReadOnlyList<string> importedModules)
    {
        StringBuilder output = new();
        void Line(string text = "") => output.Append(text).Append('\n');
        bool hasPublic = inputs.Any(input => !input.Private);
        bool hasPrivate = inputs.Any(input => input.Private);
        string[] dependencies = importedModules.Order(StringComparer.Ordinal).ToArray();
        Line("// Generated by Rocks MetaCompiler. Do not edit by hand. Defines the functions that register the module's reflection types.");
        Line("// Compiled once as a translation unit of the owning module.");
        if (hasPublic)
        {
            Line($"#include <{CompilerOptions.AggregateSpelling(module, false)}>");
        }

        if (hasPrivate)
        {
            Line($"#include <{CompilerOptions.AggregateSpelling(module, true)}>");
        }

        foreach (string dependency in dependencies)
        {
            Line($"#include <{CompilerOptions.AggregateSpelling(dependency, false)}>");
        }

        foreach (bool privateTypes in new[] { false, true })
        {
            foreach (ModuleInput input in inputs.Where(input => input.Private == privateTypes).OrderBy(input => input.Include, StringComparer.Ordinal))
            {
                Line($"#include <{CompilerOptions.GeneratedSpelling(input.Include)}>");
            }
        }

        Line("#include <Object/ModuleRegistration.h>");
        Line($"namespace rocks::generated::{module} {{");
        if (hasPublic)
        {
            EmitRegistration(module, schema, dependencies, privateTypes: false, viaPublic: false, Line);
        }

        if (hasPrivate)
        {
            EmitRegistration(module, schema, hasPublic ? [] : dependencies, privateTypes: true, viaPublic: hasPublic, Line);
        }

        EmitOwnTypesRegistration(schema, Line);
        Line($"}} // namespace rocks::generated::{module}");
        return output.ToString();
    }

    // 등록 함수 하나의 정의다. dependencies는 이 함수가 먼저 부를 의존 모듈이고, viaPublic이면 그에 앞서 이 모듈의 public 함수를 부른다.
    private static void EmitRegistration(string module, SchemaModel schema, IReadOnlyList<string> dependencies, bool privateTypes,
        bool viaPublic, Action<string> line)
    {
        line(RegistrationSignature(privateTypes, declaration: false) + " {");
        // 의존 그래프의 여러 경로로 다시 불려도 registration마다 모듈을 한 번만 등록한다(호출이 경로 수만큼 늘지 않게). 이 함수의
        // 정의는 프로그램에 하나(이 모듈 생성 소스)이므로 정적 지역 객체의 주소도 하나이고, 그 주소가 모듈 키다.
        line("// This function has one definition in the program (this module generated source), so the address of the static below is");
        line("// unique and serves as the module key: a registration enters each module once however many dependency paths reach it.");
        line("static constexpr char moduleKey = 0;");
        line("const ::rocks::usize mark = registration.Size();");
        line("auto entered = registration.EnterModule(&moduleKey);");
        line("if (!entered) return ::rocks::Result<void>::Failure(entered.Error());");
        line("if (!entered.Value()) return ::rocks::Result<void>::Success();");
        line("auto fail = [&](::rocks::ErrorCode error) noexcept { static_cast<void>(registration.UnregisterFrom(mark)); return ::rocks::Result<void>::Failure(error); };");
        if (viaPublic)
        {
            line($"if (auto dependencies = ::rocks::generated::{module}::RegisterModuleTypes(registration, module); !dependencies) return fail(dependencies.Error());");
        }

        foreach (string dependency in dependencies)
        {
            line($"if (auto dependency = ::rocks::generated::{dependency}::RegisterModuleTypes(registration, module); !dependency) return fail(dependency.Error());");
        }

        EmitTypeRegistrations(schema, privateTypes, line);
        line("(void)fail;");
        line("return ::rocks::Result<void>::Success();");
        line("}");
    }

    // 이 모듈 타입의 등록 줄이다(enum → struct → 클래스 — schema.Ordered 순서). 재귀 등록 함수와 자기 타입 함수가 같은 줄을 쓴다.
    private static void EmitTypeRegistrations(SchemaModel schema, bool privateTypes, Action<string> line)
    {
        foreach (ClassModel type in schema.Ordered.Where(type => type.Private == privateTypes))
        {
            if (type.IsEnum)
            {
                line($"if (auto added = registration.RegisterEnumIfAbsent(::rocks::GeneratedType<::{type.NativeName}>::Schema(), ::rocks::RuntimeEnumOps{{::rocks::NativeTypeKey<::{type.NativeName}>(), module}}); !added) return fail(added.Error());");
                continue;
            }

            if (type.IsStruct)
            {
                // Binds 미러는 실제 타입의 GeneratedType이다(NativeName).
                line($"if (auto added = registration.RegisterStructIfAbsent(::rocks::GeneratedType<::{type.NativeName}>::Schema(), ::rocks::GeneratedType<::{type.NativeName}>::Ops(module)); !added) return fail(added.Error());");
                continue;
            }

            line($"if (auto added = registration.RegisterIfAbsent(::rocks::GeneratedType<::{type.Name}>::Schema(), ::rocks::GeneratedType<::{type.Name}>::Ops(module)); !added) return fail(added.Error());");
        }
    }

    // 자기 타입만 등록하는 함수의 정의다(OwnTypesSignature). 모듈 키(EnterModule)·의존 모듈 호출이 없다 — 로더가 의존 모듈을 먼저
    // 등록하고, 등록기가 모듈마다 따로 둔 ModuleRegistration에 부른다. 실패하면 이 호출이 등록한 것을 되돌린다.
    private static void EmitOwnTypesRegistration(SchemaModel schema, Action<string> line)
    {
        line(OwnTypesSignature() + " {");
        line("const ::rocks::usize mark = registration.Size();");
        line("auto fail = [&](::rocks::ErrorCode error) noexcept { static_cast<void>(registration.UnregisterFrom(mark)); return ::rocks::Result<void>::Failure(error); };");
        line("static_cast<void>(module);");
        EmitTypeRegistrations(schema, privateTypes: false, line);
        EmitTypeRegistrations(schema, privateTypes: true, line);
        line("(void)fail;");
        line("return ::rocks::Result<void>::Success();");
        line("}");
    }

    // 원본 선언 위치 주석이다(생성 소스의 타입·필드 블록 앞 — Docs/Design/ReflectionGeneratedSources.ko.md 5.4절). 컴파일 오류가 난 줄에서
    // 원본 선언을 바로 찾게 한다. 철자는 리플렉션 헤더의 include 철자라 호스트 경로가 들어가지 않는다. import한 타입은 줄을 모르므로
    // (descriptor에 없다) 헤더와 이름만 적는다.
    private static string SiteComment(string header, int line, string symbol) =>
        line > 0 ? $"// {header}:{line.ToString(CultureInfo.InvariantCulture)} {symbol}" : $"// {header} {symbol}";

    private static string FieldComment(SchemaModel schema, FieldModel field)
    {
        ClassModel owner = schema.Find(field.Owner);
        return SiteComment(owner.Header, owner.Imported ? 0 : field.Site.Line, field.Owner + "::" + field.Name);
    }

    // 입력 헤더 하나의 생성 헤더와 생성 소스다(Docs/Design/ReflectionGeneratedSources.ko.md 5절). 생성 헤더는 GeneratedType 특수화의 클래스
    // 정의다: 선언, 컴파일 타임 형질(constexpr), 작은 inline 함수(Id·enum IsDeclared·Trace)만 담는다. include 목록은 본문을 헤더에 두던
    // 때와 같다(소비 코드가 이 헤더가 끌어오는 include에 기대도 깨지지 않는다 — GSD5 보류). 생성 소스는 자기 생성 헤더를 첫 include로
    // 두고 나머지 멤버(스키마 표·연산 표·등록·복사·검증·정적 검사)를 한정된 이름으로 정의한다. 파일 지역 이름과 매크로를 정의하지
    // 않으므로 다른 생성 소스와 한 번역 단위로 묶여도 충돌하지 않는다. 소유 모듈이 번역 단위로 한 번 컴파일한다.
    public static (string Header, string Source) Emit(SchemaModel schema, ModuleInput input, string module)
    {
        string include = input.Include;
        if (include.Length == 0 || include.IndexOfAny(['\r', '\n', '"', '\\', '<', '>']) >= 0)
        {
            throw new MetadataException("--include must use a safe forward-slash header spelling", "RMC1000",
                "Pass the logical generated include with forward slashes and no quotes or line breaks.");
        }

        StringBuilder header = new();
        StringBuilder source = new();
        void Line(string text = "") => header.Append(text).Append('\n');
        void Body(string text = "") => source.Append(text).Append('\n');
        Line("// Generated by Rocks MetaCompiler. Do not edit by hand. Stable IDs are kept from the source annotations.");
        Line("// Declarations, compile-time traits and the inline Trace of the reflected types. Schemas, operation tables, registration");
        Line("// and generated checks are defined in the generated source of this header, compiled once by the owning module.");
        Line("#pragma once");
        Line($"#include <{include}>");
        // 모듈 API 매크로는 빌드가 정의 헤더로 넣는다. 빌드 밖에서 이 헤더를 컴파일하는 도구(시험)는 빈 값을 쓴다(Monolithic과 같다).
        // 클래스·struct·enum 모두 매크로를 쓴다(NativeKey·out-of-line 정적 멤버 — BS8d2·BS8d4).
        if (schema.Ordered.Any(type => type.Header == include))
        {
            Line($"#ifndef {ApiMacro(module)}");
            Line($"#define {ApiMacro(module)}");
            Line("#endif");
        }

        Line("#include <Base/TypeTraits.h>");
        Line("#include <Meta/GeneratedType.h>");
        Line("#include <Object/GeneratedFieldAccess.h>");
        Line("#include <Object/GeneratedFieldCodec.h>");
        // 경로 접근 thunk 템플릿(PathClassField·PathStructMember — Docs/Design/ReflectionFoundations.ko.md 7.1절)이다. 생성 소스의
        // 함수표가 인스턴스화한다(헤더가 include해 두어 생성 소스는 자기 생성 헤더만 include한다).
        Line("#include <Object/GeneratedPathAccess.h>");
        // Binds 미러의 순서 대조(ROCKS_OFFSET_OF)는 Base 매크로를 쓴다(__builtin은 Base 헤더 밖에서 쓰지 않는다).
        if (schema.Ordered.Any(type => type.Header == include && type.Binds.Length != 0))
        {
            Line("#include <Base/Compiler.h>");
        }
        // 다른 헤더(같은 모듈·다른 모듈)에 선언된 리플렉션 enum·struct를 필드(상속 필드·배열 원소 포함)나 NATIVE 멤버의
        // 직접 타입으로 쓰면 그 타입의 GeneratedType이 먼저 보여야 한다(생성 접근기가 GeneratedType<T>::Id·IsDeclared·
        // ContainsStrongReference로 알아보고, StructRefArray<S>::Trace가 GeneratedType<S>::Trace를 인스턴스화한다). 같은
        // 특수화를 두 번 정의하지 않도록 그 타입의 생성 헤더를 include한다. 클래스 대상(참조의 기대 타입·ClassRef의 Base)은
        // NativeTypeKey만 쓰므로 헤더에서는 include하지 않는다(ClassRef<Self>·파생 클래스를 Base로 두어도 include 순환이 생기지 않는다 —
        // 그 키가 필요한 생성 소스가 따로 include한다).
        ClassModel[] own = schema.Ordered.Where(type => type.Header == include).ToArray();
        IEnumerable<string> valueHeaders = own.SelectMany(type => type.Fields)
            .Where(field => field.TargetKind is "Enum" or "Struct" or "InstancedStruct" && field.Reference is not null)
            .Select(field => field.Reference!)
            .Concat(own.SelectMany(type => type.Fields).Where(field => field.KeyKind == "Enum" && field.KeyReference is not null)
                .Select(field => field.KeyReference!))
            .Concat(own.SelectMany(type => type.NativeMembers).Where(native => native.Struct is not null).Select(native => native.Struct!))
            .Concat(own.Where(type => type.IsStruct && type.Base.Length != 0).Select(type => type.Base))
            // 상속 bitfield bool 필드(리플렉션 B9m)는 선언 타입의 생성 접근자를 쓴다.
            .Concat(own.SelectMany(type => type.Fields).Where(field => field.Bitfield).Select(field => field.Owner))
            .Select(name => schema.Find(name).Header)
            .Where(header => header != include)
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal);
        foreach (string valueHeader in valueHeaders)
        {
            Line($"#include <{CompilerOptions.GeneratedSpelling(valueHeader)}>");
        }

        // bitfield bool 필드(리플렉션 B9m)의 접근자 판 함수표 템플릿이다.
        if (own.Any(type => type.Fields.Any(field => field.Bitfield)))
        {
            Line("#include <Object/GeneratedBitfieldAccess.h>");
        }

        // 설정 struct의 GeneratedType<S>::Settings()가 쓴다(Docs/Design/ConfigSystem.ko.md 7절).
        if (own.Any(type => type.IsSettings))
        {
            Line("#include <Meta/SettingsSchema.h>");
        }

        // NATIVE 멤버 static_assert와 struct 특수화의 멤버 형질 대조(IsNativeStrongReference·RegistryContainer)가 쓴다.
        if (own.Any(type => type.NativeMembers.Count != 0 || type.IsStruct))
        {
            Line("#include <Object/NativeMemberTraits.h>");
        }

        Body("// Generated by Rocks MetaCompiler. Do not edit by hand. Defines the schemas, operation tables, registration and generated");
        Body($"// checks of the reflected types declared in <{include}>. Compiled once as a translation unit of the owning module.");
        Body("// A comment before a type or field names the reflected declaration as <header>:<line> <Type>::<member>.");
        Body($"#include <{CompilerOptions.GeneratedSpelling(include)}>");
        // 클래스 대상(참조의 기대 타입·ClassRef의 Base·클래스 base)의 NativeTypeKey는 그 타입 생성 .cpp의 키(GeneratedType<T>::NativeKey)를
        // 쓰므로(Docs/Design/BuildTargets 3.8절 BS8b) 생성 소스가 그 생성 헤더를 include한다. 생성 소스는 다른 곳에서 include하지
        // 않는 말단 번역 단위라 헤더와 달리 include 순환이 생기지 않는다.
        // import 타입에서 물려받은 필드의 클래스 대상은 이름 없이 ID만 있다(SchemaValidator.Imports — enum·struct 대상만 이름으로 잇는다).
        Dictionary<string, ClassModel> byId = schema.Classes.Values.Concat(schema.Imported.Values)
            .GroupBy(type => type.Id, StringComparer.Ordinal).ToDictionary(group => group.Key, group => group.First(), StringComparer.Ordinal);
        IEnumerable<FieldModel> ownFields = own.SelectMany(type => type.Fields).ToArray();
        IEnumerable<string> targetHeaders = ownFields
            .SelectMany(field => new[] { field.Reference, field.KeyReference })
            .Concat(own.Where(type => type.Base.Length != 0).Select(type => type.Base))
            .Where(name => name is not null && (schema.Classes.ContainsKey(name) || schema.Imported.ContainsKey(name)))
            .Select(name => schema.Find(name!).Header)
            .Concat(ownFields.SelectMany(field => new[] { field.ReferenceId, field.KeyReferenceId })
                .Where(id => id is not null && byId.ContainsKey(id)).Select(id => byId[id!].Header))
            .Where(header => header != include && !valueHeaders.Contains(header, StringComparer.Ordinal))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal);
        foreach (string targetHeader in targetHeaders)
        {
            Body($"#include <{CompilerOptions.GeneratedSpelling(targetHeader)}>");
        }

        Line("namespace rocks {");
        Body("namespace rocks {");
        // 특수화는 schema.Ordered 순서다: enum, struct(PROPERTY·NATIVE로 쓰는 struct 먼저), 클래스(base 먼저). 같은 헤더 안에서도 쓰는
        // 타입의 특수화가 먼저 나온다.
        foreach (ClassModel type in own)
        {
            Body(SiteComment(type.Header, type.Site.Line, type.Name));
            if (type.IsEnum)
            {
                EmitEnum(type, module, Line, Body);
                continue;
            }

            if (type.IsStruct)
            {
                EmitStruct(schema, type, module, Line, Body);
                continue;
            }

            EmitClass(schema, type, module, Line, Body);
        }

        Line("} // namespace rocks");
        Body("} // namespace rocks");
        return (header.ToString(), source.ToString());
    }

    // 검사 전용 멤버 VerifyGenerated()다(Docs/Design/ReflectionGeneratedSources.ko.md 5.3절). 생성 메타데이터가 지금의 C++ 선언과 맞는지
    // 보는 static_assert 묶음을 담는다. 호출하지 않는다 — 생성 소스의 정의가 컴파일될 때 평가된다. GeneratedType의 멤버 함수라
    // ROCKS_GENERATED_BODY의 friend 선언으로 private 멤버 형식에도 닿는다. 소비 번역 단위는 선언만 보므로 이 형질들을 인스턴스화하지
    // 않는다.
    private static void EmitVerifyGenerated(string self, IReadOnlyList<string> checks, Action<string> Line, Action<string> Body)
    {
        Line("static void VerifyGenerated() noexcept;");
        Body($"void {self}::VerifyGenerated() noexcept {{");
        foreach (string check in checks)
        {
            Body(check);
        }

        Body("}");
    }

    // 리플렉션 클래스의 GeneratedType 특수화다. 헤더: Id(constexpr), Trace(inline — GC와 native 파생의 Trace 사슬이 직접 부른다),
    // 나머지 멤버의 선언. 생성 소스: bitfield 접근자, 정적 검사, Schema, ReferenceLayout, Ops, Register.
    private static void EmitClass(SchemaModel schema, ClassModel type, string module, Action<string> Line, Action<string> Body)
    {
        Line = ExportingLine(module, Line);
        string native = "::" + type.NativeName;
        string self = $"GeneratedType<{native}>";
        string? baseId = type.Base == "rocks::Object" ? null : schema.Find(type.Base).Id;
        List<string> checks = [];
        Line($"template <> struct GeneratedType<{native}> {{");
        EmitBitfieldAccessors(type, native, Line, Body);
        // ROCKS_NATIVE 멤버는 스키마에 넣지 않는다. 생성 static_assert는 직접 타입의 강한 참조 래퍼(ObjectRef·RootRef·
        // ObjectRefArray·StructRefArray와 그것을 가리키는 포인터·참조 — RMC2205)와 WorldOnly 소유자 형질(RMC2206)만 컴파일러가
        // 한 번 더 확인한다. Object 파생 타입을 가리키는 raw 포인터·참조는 대상의 완전성이 TU마다 달라 형질로 보지 않고
        // MetaCompiler의 탐침(NativeMemberProbe — 자신의 번역 단위 하나에서 Clang이 판정)이 거부한다(GeneratedType은
        // GENERATED_BODY로 private 멤버에도 접근한다).
        foreach (NativeMemberModel member in type.NativeMembers)
        {
            string memberType = $"decltype({native}::{member.Name})";
            checks.Add($"static_assert(!IsNativeStrongReference<{memberType}>, \"ROCKS_NATIVE member {type.Name}::{member.Name} must not hold a strong object reference (RMC2205)\");");
            if (!type.WorldOnly)
            {
                checks.Add($"static_assert(!RequiresWorldOnlyOwner<{memberType}>, \"ROCKS_NATIVE member {type.Name}::{member.Name} requires a WorldOnly owner (RMC2206)\");");
            }

            EmitNativeStructAsserts(schema, type, member, !type.WorldOnly, checks.Add);
        }

        // WorldOnly가 아닌 클래스는 struct 필드·struct 원소 배열(상속 포함)의 생성 형질을 직접 확인한다(import flags를
        // 믿지 않는다).
        if (!type.WorldOnly)
        {
            foreach (string structure in type.Fields.Where(field => field.StructTarget).Select(field => field.Reference!).Distinct(StringComparer.Ordinal))
            {
                checks.Add($"static_assert(!GeneratedType<::{schema.Find(structure).NativeName}>::RequiresWorldOnlyOwner, \"struct {structure} requires a WorldOnly owner; {type.Name} is not WorldOnly (RMC2206)\");");
            }
        }

        EmitElementStructAsserts(schema, type, checks.Add);
        if (baseId is not null)
        {
            // nativeBaseType은 상속 Resolve의 포인터 변환 근거다. 오래된 생성물이나 잘못된 base 선언이 조용히 컴파일되지 않도록
            // C++ 상속을 컴파일 시 확인한다.
            checks.Add($"static_assert(::rocks::IsBaseOfV<::{type.Base}, {native}>, \"reflected base must be a C++ base\");");
        }

        Line($"static constexpr TypeId Id() noexcept {{ return {GuidValue(type.Id)}; }}");
        Line("static const TypeSchema& Schema() noexcept;");
        EmitNativeKey(module, self, Line, Body);
        EmitVerifyGenerated(self, checks, Line, Body);
        Body($"const TypeSchema& {self}::Schema() noexcept {{");
        EmitFieldSchemas(type, Body);
        string fieldSpan = type.Fields.Count == 0 ? "Span<const FieldSchema>{}" : $"Span<const FieldSchema>(fields, {type.Fields.Count})";
        Body($"static const TypeSchema schema{{Id(), {type.Version}, {fieldSpan}, {View(type.Name)}, {GuidValue(baseId)}, {type.Flags}u, {View(type.EffectiveToolName)}, {GuidValue(type.WithinId)}}};");
        Body("return schema;");
        Body("}");
        // 클래스 생성 Trace다(Docs/Design/ReflectionFoundations.ko.md 9.1절 B8a). 상속 필드를 포함한 모든 참조·struct·배열
        // 필드를 방문하고 ops.trace는 이것을 감싼다. 리플렉션 base를 둔 native 파생(RegisterNativeClass)의 Trace 사슬이
        // 리플렉션 조상에서 이 함수를 부르고 멈춘다(ROCKS_CLASS는 손 Trace를 금지하므로 이중 방문·누락이 없다). Transient는
        // 영속성 정책이며 strong edge의 GC 도달성에는 영향을 주지 않는다. struct 필드는 모든 struct가 내는 Trace를 부른다(참조
        // 없는 struct는 빈 본문 — 비템플릿 함수라 if constexpr로 가를 수 없다). 배열 필드(상속한 import 필드 포함)는 모두
        // TraceArrayField를 부른다 — 실제 C++ 타입이 오버로드를 고르므로 컨테이너를 descriptor에서 잘못 추론해도 Trace가 빠지지
        // 않는다. 방문할 필드가 없으면 매개변수 이름 없는 빈 본문이다(사용하지 않는 매개변수 경고를 피한다). 헤더에 inline으로
        // 남긴다 — GC 경로가 직접 부르므로 LTO 없는 구성에서도 inline이 되어야 한다(ReflectionGeneratedSources 5.2절).
        FieldModel[] traced = type.Fields.Where(field => field.IsReference || field.IsStruct || field.IsArray || field.IsStaticArray || field.IsMap).ToArray();
        if (traced.Length == 0)
        {
            Line($"static void Trace(const {native}&, TraceVisitor&) noexcept {{}}");
        }
        else
        {
            Line($"static void Trace(const {native}& value, TraceVisitor& visitor) noexcept {{");
            foreach (FieldModel field in traced)
            {
                Line(TraceStatement(schema, field, "value", $"::{field.Owner}"));
            }

            Line("}");
        }

        // 클래스 생성 참조 위치 함수다(M3, Docs/Design/GarbageCollectionScale.ko.md 3.4절). Trace와 같은 필드를 같은 순서로
        // 돌며 강한 간선 칸(ObjectRef·ObjectRefArray)의 위치를 알린다. Registry가 타입마다 첫 객체에서 표를 만들고 GC marker가
        // trace 대신 표로 handle을 읽는다. 표로 나타낼 수 없는 필드(StructRefArray·ObjectRefMap·참조 struct)는 Unsupported로
        // 그 타입을 trace에 남긴다(오버로드는 실제 C++ 타입이 고른다). 등록할 때 한 번 쓰므로 생성 소스에 둔다.
        Line($"static void ReferenceLayout(const {native}& value, detail::ReferenceLayoutBuilder& layout) noexcept;");
        if (traced.Length == 0)
        {
            Body($"void {self}::ReferenceLayout(const {native}&, detail::ReferenceLayoutBuilder&) noexcept {{}}");
        }
        else
        {
            Body($"void {self}::ReferenceLayout(const {native}& value, detail::ReferenceLayoutBuilder& layout) noexcept {{");
            // struct 필드만 있으면 value를 쓰지 않는다(LayoutStructField는 형질만 본다).
            Body("(void)value;");
            foreach (FieldModel field in traced)
            {
                Body(LayoutStatement(schema, field, "value", $"::{field.Owner}"));
            }

            Body("}");
        }

        EmitVisitFields(schema, type, native, $"::{{0}}", Line);
        Line("static RuntimeTypeOps Ops(ModuleLease module = {}) noexcept;");
        Body($"RuntimeTypeOps {self}::Ops(ModuleLease module) noexcept {{");
        Body($"auto ops = MakeRuntimeTypeOps<{native}, {(type.Abstract ? "true" : "false")}>(Move(module));");
        if (type.Fields.Count != 0)
        {
            Body("static const RuntimeFieldOps fields[] = {");
            foreach (FieldModel field in type.Fields)
            {
                Body(FieldComment(schema, field));
                if (field.Bitfield)
                {
                    // bitfield bool(리플렉션 B9m)은 멤버 포인터 대신 생성 접근자로 read·write·writeStaged·codec·경로를 낸다.
                    Body($"detail::BitfieldFieldOps<{native}, {BitfieldAccessors(schema, field)}, {(field.Spec.ReadOnly ? "true" : "false")}>({GuidValue(field.Id)}),");
                    continue;
                }

                string member = $"&::{field.Owner}::{field.Name}";
                Body($"{{{GuidValue(field.Id)},");
                if (field.IsMap || field.IsSet)
                {
                    // Map·Set 필드(리플렉션 B9f2)는 FieldValue로 표현할 수 없으므로 read·write·writeStaged가 없고 codec, 값·원소
                    // Enum·Struct의 native 키(없으면 nullptr), key 단계 경로 thunk(리플렉션 B9f3), readStaged 없음과 키 enum의
                    // native 키를 싣는다(Docs/Design/ReflectionExtensions.ko.md 7.2·7.3절).
                    Body("nullptr, {}, nullptr,");
                    string mapValueNative = ValueNativeType(schema, field);
                    string keyNative = field.KeyKind == "Enum" ? $", nullptr, NativeTypeKey<::{schema.Find(field.KeyReference!).NativeName}>()" : "";
                    EmitClassCodec(native, member, (mapValueNative.Length == 0 ? ", nullptr" : mapValueNative) + ClassPathThunk(native, member, field) + keyNative, Body);
                    continue;
                }

                if (field.IsAggregate)
                {
                    // struct·배열·Optional<값 struct> 필드는 FieldValue로 표현할 수 없으므로 read·write·writeStaged가
                    // 없고(통째 쓰기는 Unsupported) codec, struct native 키(배열이면 원소, Optional이면 내부 Enum·Struct의
                    // native 키, 그 밖은 nullptr을 명시)와 경로 접근 thunk를 싣는다(Docs/Design/ReflectionFoundations.ko.md
                    // 4.6·5.6·7.1절, ReflectionExtensions.ko.md 6절). 멤버·원소 단위 접근은 경로 thunk가 한다.
                    Body("nullptr, {}, nullptr,");
                    string valueNative = ValueNativeType(schema, field);
                    EmitClassCodec(native, member, (valueNative.Length == 0 ? ", nullptr" : valueNative) + ClassPathThunk(native, member, field), Body);
                    continue;
                }

                Body("+[](ObjectRegistry& registry, const ObjectAccessContext& access, ObjectHandle object, FieldValue& out) noexcept -> Result<void> {");
                Body($"return detail::ReadGeneratedField<{native}>(registry, access, object, {member}, out); }},");
                Body("+[](ObjectRegistry& registry, const ObjectAccessContext& access, ObjectHandle object, const FieldValue& value) noexcept -> Result<void> {");
                if (field.Spec.ReadOnly)
                {
                    Body("(void)value;");
                    Body($"auto borrowed = registry.Resolve<{native}>(access, object);");
                    Body("if (!borrowed) return Result<void>::Failure(borrowed.Error());");
                    Body("auto valid = borrowed.Value().Get();");
                    Body("if (!valid) return Result<void>::Failure(valid.Error());");
                    Body("return Result<void>::Failure(ErrorCode::Unsupported);");
                }
                else
                {
                    Body($"return detail::WriteGeneratedField<{native}>(registry, access, object, {member}, value);");
                }

                Body("},");
                Body("+[](ConstructionContext& construction, ObjectHandle object, const FieldValue& value) noexcept -> Result<void> {");
                Body($"return detail::WriteGeneratedStagedField<{native}>(construction, object, {member}, value); }},");
                // Enum 필드(Optional<enum> 포함)는 정적 thunk의 enum native 키를 싣는다(등록이 대상 enum 레코드와 대조한다). 단일 값
                // 필드도 경로 접근 thunk를 싣는다(리플렉션 B9i3c0 — staged 객체의 경로 연산과 Detach·Attach가 쓴다. 게시된 객체의
                // 최상위 단일 값 읽기·쓰기는 그래도 read·write 한 경로다).
                string scalarNative = field.TargetKind == "Enum" ? $", NativeTypeKey<::{schema.Find(field.Reference!).NativeName}>()" : ", nullptr";
                EmitClassCodec(native, member, scalarNative + ClassPathThunk(native, member, field), Body);
            }

            Body("};");
            Body($"ops.fields = Span<const RuntimeFieldOps>(fields, {type.Fields.Count});");
        }

        if (baseId is not null)
        {
            Body($"ops.nativeBaseType = NativeTypeKey<::{type.Base}>();");
        }

        Body("ops.completeFieldLayout = true;");
        Body("ops.parallelTraceSafe = true;");
        // 방문할 필드가 없는 클래스는 잎 타입이다(GC marker가 trace를 부르지 않는다 — Docs/Design/GarbageCollectionScale.ko.md M2).
        if (traced.Length == 0)
        {
            Body("ops.hasStrongReferences = false;");
        }

        Body($"ops.trace = +[](const Object& object, TraceVisitor& visitor) noexcept {{ Trace(static_cast<const {native}&>(object), visitor); }};");
        Body($"ops.referenceLayout = +[](const Object& object, detail::ReferenceLayoutBuilder& layout) noexcept {{ ReferenceLayout(static_cast<const {native}&>(object), layout); }};");
        Body("return ops;");
        Body("}");
        Line("static Result<TypeRegistrationToken> Register(TypeRegistry& registry, ModuleLease module = {}) noexcept;");
        Body($"Result<TypeRegistrationToken> {self}::Register(TypeRegistry& registry, ModuleLease module) noexcept {{");
        Body("return registry.Register(Schema(), Ops(Move(module)));");
        Body("}");
        Line("};");
    }

    // 필드 방문 함수다(Docs/Design/LoggingSystem.ko.md 14.1.6절 LG16 — 로그 구조체 펼치기 `{@Obj}`가 registry·할당 없이
    // 값을 읽는다). 상속 필드를 포함한 모든 필드를 선언 순서(DeclarationOrder)로 visitor.Field("이름", 값)으로 부른다. 이름은 C++
    // 멤버 이름의 문자열 리터럴(정적 저장소)이고 값은 멤버 포인터로 직접 읽은 const 참조다(Trace와 같은 철자 — 클래스는 선언
    // 클래스의 멤버 포인터, struct는 자기 타입). bitfield bool은 참조를 만들 수 없으므로 생성 접근자(Get_)의 bool 값이다.
    // 등록·함수표가 없는 constexpr 템플릿이라 쓰지 않으면 인스턴스화되지 않는다. ownerFormat은 멤버 포인터 클래스 철자다({0}은
    // 필드의 Owner).
    private static void EmitVisitFields(SchemaModel schema, ClassModel type, string native, string ownerFormat, Action<string> Line)
    {
        if (type.Fields.Count == 0)
        {
            Line($"template <class Visitor> static constexpr void VisitFields(const {native}&, Visitor&) noexcept {{}}");
            return;
        }

        Line($"template <class Visitor> static constexpr void VisitFields(const {native}& value, Visitor& visitor) noexcept {{");
        foreach (FieldModel field in DeclarationOrder(schema, type))
        {
            // bitfield는 멤버 포인터를 만들 수 없어 헤더 안에서 직접 읽는다. Get_ 정의는 생성 소스에 있어(GS2) 다른 모듈이
            // VisitFields를 인스턴스화하면 export되지 않은 모듈 밖 함수를 부르게 된다. 상속한 bitfield는 선언 타입으로 바꿔
            // 읽는다(ROCKS_GENERATED_BODY가 모든 GeneratedType을 friend로 두므로 base의 private 멤버도 읽을 수 있다).
            string read = field.Bitfield && field.Owner == type.Name
                ? $"static_cast<bool>(value.{field.Name} != 0)"
                : field.Bitfield
                ? $"static_cast<bool>(static_cast<const ::{schema.Find(field.Owner).NativeName}&>(value).{field.Name} != 0)"
                : $"value.*(&{string.Format(CultureInfo.InvariantCulture, ownerFormat, field.Owner)}::{field.Name})";
            Line($"visitor.Field({Label(field.Name)}, {read});");
        }

        Line("}");
    }

    // 필드의 선언 순서다: 가장 먼 리플렉션 base의 필드부터, 같은 선언 타입 안에서는 그 타입의 선언 순서(OwnFields)다. 스키마 필드
    // 배열(안정 ID 순)과 달리 로그 출력이 소스 선언 순서로 읽히게 한다. 선언 순서를 모르는 필드(import한 타입의 필드 등)는 같은 선언
    // 타입 안 끝에 스키마 순서로 둔다. 같은 입력이면 늘 같은 순서다.
    private static IEnumerable<FieldModel> DeclarationOrder(SchemaModel schema, ClassModel type)
    {
        List<string> chain = [];
        ClassModel? current = type;
        while (current is not null && !chain.Contains(current.Name, StringComparer.Ordinal))
        {
            chain.Add(current.Name);
            string next = current.Base;
            current = schema.Classes.TryGetValue(next, out ClassModel? own) ? own : schema.Imported.TryGetValue(next, out ClassModel? imported) ? imported : null;
        }

        int Rank(FieldModel field)
        {
            int index = chain.IndexOf(field.Owner);
            return index < 0 ? chain.Count : chain.Count - 1 - index;
        }

        int Position(FieldModel field)
        {
            ClassModel? owner = schema.Classes.TryGetValue(field.Owner, out ClassModel? own) ? own : schema.Imported.TryGetValue(field.Owner, out ClassModel? imported) ? imported : null;
            int index = owner is null ? -1 : owner.OwnFields.FindIndex(declared => declared.Name == field.Name);
            return index < 0 ? int.MaxValue : index;
        }

        return type.Fields.Select((field, schemaIndex) => (field, schemaIndex))
            .OrderBy(item => Rank(item.field))
            .ThenBy(item => Position(item.field))
            .ThenBy(item => item.schemaIndex)
            .Select(item => item.field);
    }

    // 자기 bitfield bool 필드(리플렉션 B9m — Docs/Design/ReflectionExtensions.ko.md 14절)의 생성 접근자다. bitfield는 멤버
    // 포인터·참조를 만들 수 없으므로 함수표 템플릿(detail::BitfieldFieldOps·BitfieldStructFieldOps)이 이 정적 함수를 받는다.
    // GeneratedType은 ROCKS_GENERATED_BODY의 friend라 private 멤버도 읽고 쓴다. 파생 타입은 base의 접근자를 그대로 쓴다. 헤더에는
    // 선언만, 정의는 생성 소스에 둔다(함수표 안에서만 쓴다).
    private static void EmitBitfieldAccessors(ClassModel type, string native, Action<string> Line, Action<string> Body)
    {
        foreach (FieldModel field in type.OwnFields.Where(field => field.Bitfield))
        {
            Line($"static bool Get_{field.Name}(const {native}& value) noexcept;");
            Line($"static void Set_{field.Name}({native}& value, bool bit) noexcept;");
            Body($"bool GeneratedType<{native}>::Get_{field.Name}(const {native}& value) noexcept {{ return value.{field.Name} != 0; }}");
            Body($"void GeneratedType<{native}>::Set_{field.Name}({native}& value, bool bit) noexcept {{ if (bit) {{ value.{field.Name} = 1; }} else {{ value.{field.Name} = 0; }} }}");
        }
    }

    // bitfield bool 필드의 접근자 인자 둘이다(선언 타입 — 상속 필드면 base — 의 GeneratedType 정적 함수).
    private static string BitfieldAccessors(SchemaModel schema, FieldModel field)
    {
        string owner = $"GeneratedType<::{schema.Find(field.Owner).NativeName}>";
        return $"&{owner}::Get_{field.Name}, &{owner}::Set_{field.Name}";
    }

    // struct 필드·배열 필드 함수표의 valueNativeType 인자다: struct 필드는 그 struct, 배열은 원소가 Enum·Struct면 그
    // 원소의 native 키(Binds 미러는 실제 타입), 그 밖은 ""다(뒤에 path 칸이 오므로 호출하는 쪽이 ", nullptr"을 명시한다).
    private static string ValueNativeType(SchemaModel schema, FieldModel field) => field.TargetKind switch
    {
        "Struct" => $", NativeTypeKey<::{schema.Find(field.Reference!).NativeName}>()",
        "Enum" => $", NativeTypeKey<::{schema.Find(field.Reference!).NativeName}>()",
        _ => ""
    };

    // 클래스 Struct·Array·Optional<값 struct>·Map·Set 필드 함수표의 path 칸(valueNativeType 뒤)이다(Docs/Design/ReflectionFoundations.ko.md 7.1절
    // MetaCompiler). 소유자 Owner는 함수표를 내는 클래스(파생 — 함수표가 실제 타입 레코드에서 온다)이고 멤버 포인터는 선언
    // 클래스의 것이다(상속 import 필드 포함). 대상 종류는 FieldModel.TargetKind(배열이면 원소 종류)를 명시한다 — C++ 멤버
    // 형식과 다르면 TargetValueCheck static_assert가 컴파일을 실패시킨다(requires 탐지를 쓰지 않는다). 단일 값 필드도 path를
    // 싣는다(리플렉션 B9i3c0 — 게시된 객체의 최상위 단일 값 읽기·쓰기는 read·write 한 경로, thunk는 staged·Detach·Attach용).
    private static string ClassPathThunk(string native, string member, FieldModel field) =>
        ", +[](const ::rocks::RuntimeFieldOps&, ::rocks::detail::PathCursor& cursor) noexcept -> ::rocks::Result<void> { " +
        $"return ::rocks::detail::PathClassField<{native}, ::rocks::ValueKind::{field.TargetKind}>(cursor, {member}); }}";

    // struct 멤버 함수표다(Docs/Design/ReflectionFoundations.ko.md 4.6·7.1절): codec과 경로 접근 thunk(모든 멤버 — struct
    // 멤버의 단일 값도 경로가 이 thunk로 접근한다). Binds 미러는 실제 타입(native)의 멤버 포인터를 쓴다.
    private static string StructMemberOps(string native, FieldModel field)
    {
        string member = $"&{native}::{field.Name}";
        // Map·Set 멤버(리플렉션 B9f2)의 대상 종류는 값·원소 종류다(key 단계 경로 연산 — 리플렉션 B9f3). 값·키 native 키는
        // StructFieldOps가 멤버 형식으로 채운다.
        // 소유 struct를 명시한다(리플렉션 B9k — base 멤버의 멤버 포인터도 파생 값으로 캐스트한 뒤 쓴다).
        return $"detail::StructFieldOps<{native}, {member}>({GuidValue(field.Id)}, &detail::PathStructMember<{native}, {member}, ValueKind::{field.TargetKind}>),";
    }

    // 클래스·참조 struct Trace의 필드 한 줄이다(owner는 Trace 매개변수 value, ownerType은 멤버 포인터의 클래스 철자). ObjectRef는
    // Visit, struct 필드는 그 struct의 생성 Trace, 배열은 TraceArrayField(Array<E>는 아무것도 하지 않고 ObjectRefArray·
    // StructRefArray는 원소를 방문한다), Map은 TraceMapField(OrderedMap은 아무것도 하지 않고 ObjectRefMap은 값을 방문한다 — 리플렉션
    // B9f4)다. 실제 C++ 타입이 오버로드를 고르므로 모델이 컨테이너를 잘못 추론해도 Trace가 빠지지 않는다.
    private static string TraceStatement(SchemaModel schema, FieldModel field, string owner, string ownerType)
    {
        string member = $"{owner}.*(&{ownerType}::{field.Name})";
        if (field.IsArray || field.IsStaticArray)
        {
            return $"detail::TraceArrayField({member}, visitor);";
        }

        if (field.IsMap)
        {
            return $"detail::TraceMapField({member}, visitor);";
        }

        return field.IsStruct
            ? $"GeneratedType<::{schema.Find(field.Reference!).NativeName}>::Trace({member}, visitor);"
            : $"visitor.Visit({member});";
    }

    // 참조 위치 함수(M3)의 필드 한 줄이다. TraceStatement와 같은 필드·같은 순서이고, ObjectRef는 칸을 알리고(ReportLayout) 배열·
    // Map은 LayoutArrayField·LayoutMapField 오버로드가, struct는 LayoutStructField가 고른다.
    private static string LayoutStatement(SchemaModel schema, FieldModel field, string owner, string ownerType)
    {
        string member = $"{owner}.*(&{ownerType}::{field.Name})";
        if (field.IsArray || field.IsStaticArray)
        {
            return $"detail::LayoutArrayField({member}, layout);";
        }

        if (field.IsMap)
        {
            return $"detail::LayoutMapField({member}, layout);";
        }

        return field.IsStruct
            ? $"detail::LayoutStructField<::{schema.Find(field.Reference!).NativeName}>(layout);"
            : $"({member}).ReportLayout(layout);";
    }

    // struct 원소 배열 필드(상속 포함)의 원소 struct 형질을 컨테이너와 대조한다(Docs/Design/ReflectionFoundations.ko.md
    // 5.6절): Array<S>는 S가 강한 참조를 담지 않고, StructRefArray<S>는 S가 참조 struct이며 Registry 컨테이너를 담지
    // 않는다. 컨테이너는 원소 종류와 원소 struct 형질로 정해지는 파생 컨테이너다(이 모듈 필드는 C++ 철자와 같다 —
    // 다르면 RMC2304). 생성 static_assert가 import flags를 믿지 않고 원소 struct의 생성 형질로 다시 확인한다.
    private static void EmitElementStructAsserts(SchemaModel schema, ClassModel type, Action<string> Line)
    {
        // Optional<S>의 S는 값 struct다(리플렉션 B9e — RMC2306). import flags를 믿지 않고 생성 형질로 다시 확인한다.
        foreach (FieldModel field in type.Fields.Where(field => field.IsOptional && field.StructTarget))
        {
            string inner = $"GeneratedType<::{schema.Find(field.Reference!).NativeName}>";
            Line($"static_assert(!{inner}::ContainsStrongReference, \"Optional field {field.Owner}::{field.Name} holds reference struct {field.Reference}; regenerate metadata (RMC2306)\");");
        }

        // Map 값 struct도 값 struct다(리플렉션 B9f2 — RMC2305).
        foreach (FieldModel field in type.Fields.Where(field => field.IsMap && field.StructTarget))
        {
            string value = $"GeneratedType<::{schema.Find(field.Reference!).NativeName}>";
            Line($"static_assert(!{value}::ContainsStrongReference, \"Map field {field.Owner}::{field.Name} holds reference struct {field.Reference}; regenerate metadata (RMC2305)\");");
        }

        // 정적 배열의 원소 struct는 Registry 컨테이너를 담지 않는다(리플렉션 B9g — RMC2307, 참조 struct 원소는 받는다).
        foreach (FieldModel field in type.Fields.Where(field => field.IsStaticArray && field.StructTarget))
        {
            string element = $"GeneratedType<::{schema.Find(field.Reference!).NativeName}>";
            Line($"static_assert(!{element}::ContainsReferenceArray, \"static array field {field.Owner}::{field.Name} holds element struct {field.Reference} with reference containers; regenerate metadata (RMC2307)\");");
        }

        foreach (FieldModel field in type.Fields.Where(field => field.IsArray && field.StructTarget))
        {
            string element = $"GeneratedType<::{schema.Find(field.Reference!).NativeName}>";
            string symbol = $"{field.Owner}::{field.Name}";
            if (field.ContainerOf(schema.Find) == ArrayRules.StructRefArray)
            {
                Line($"static_assert({element}::ContainsStrongReference && !{element}::ContainsReferenceArray, \"StructRefArray field {symbol} needs a reference struct element without reference arrays; regenerate metadata (RMC2304)\");");
            }
            else
            {
                Line($"static_assert(!{element}::ContainsStrongReference, \"Array field {symbol} holds reference struct {field.Reference}; use StructRefArray and regenerate metadata (RMC2304)\");");
            }
        }
    }

    // 클래스 필드의 그래프 저장·복원 codec 두 thunk와 함수표 끝이다(Docs/Design/ReflectionFoundations.ko.md 6.4절).
    // 문맥이 참조 wire·진단·예산을 맡으므로 그래프 형식이 바뀌어도 이 코드를 다시 만들지 않는다. tail은 decode 뒤의
    // 칸이다: valueNativeType(Enum 단일 값 필드는 ", NativeTypeKey<T>()", 없으면 ", nullptr")과 경로 접근
    // thunk(ClassPathThunk — 모든 필드), Map·Set은 그 뒤에 키 enum native 키다.
    private static void EmitClassCodec(string native, string member, string tail, Action<string> Line)
    {
        Line("+[](const RuntimeFieldOps&, ObjectRegistry& registry, const ObjectAccessContext& access, ObjectHandle object, ArchiveWriter& payload, FieldEncodeContext& context) noexcept -> Result<uint32> {");
        Line($"return detail::EncodeGeneratedField<{native}>(registry, access, object, {member}, payload, context); }},");
        Line("+[](const RuntimeFieldOps&, ConstructionContext* construction, ObjectHandle object, const FieldView& field, FieldDecodeContext& context) noexcept -> Result<void> {");
        Line($"return detail::DecodeGeneratedField<{native}>(construction, object, {member}, field, context); }}{tail} }},");
    }

    // NATIVE 멤버의 직접 타입이 리플렉션 struct면 그 struct의 생성 형질로 RMC2205(·worldOnlyCheck면 RMC2206)를
    // 컴파일 시 한 번 더 확인한다(NativeMemberTraits는 직접 타입의 형질만 본다 — GeneratedType 탐지 특수화를 두면
    // 생성 헤더가 없을 때 조용히 거짓이 되는 ODR 위반이라 생성 코드가 확인한다).
    private static void EmitNativeStructAsserts(SchemaModel schema, ClassModel type, NativeMemberModel member, bool worldOnlyCheck, Action<string> Line)
    {
        if (member.Struct is null)
        {
            return;
        }

        string structure = schema.Find(member.Struct).NativeName;
        Line($"static_assert(!GeneratedType<::{structure}>::ContainsStrongReference, \"ROCKS_NATIVE member {type.Name}::{member.Name} holds reference struct {member.Struct} (RMC2205)\");");
        if (worldOnlyCheck)
        {
            Line($"static_assert(!GeneratedType<::{structure}>::RequiresWorldOnlyOwner, \"ROCKS_NATIVE member {type.Name}::{member.Name} requires a WorldOnly owner (RMC2206)\");");
        }
    }

    // 필드의 C++ 형식 철자를 생성 코드에서 쓸 수 있게 다듬는다(한정 이름은 전역 한정 ::을 붙인다).
    private static string CppType(string spelling) =>
        spelling.Contains("::", StringComparison.Ordinal) && !spelling.StartsWith("::", StringComparison.Ordinal) && !spelling.Contains(' ', StringComparison.Ordinal)
            ? "::" + spelling : spelling;

    // Binds 미러와 실제 타입의 대조다(Docs/Design/ReflectionFoundations.ko.md 4.6절 Binds). 비템플릿 함수 안이라 항상
    // 검사된다: 멤버마다 실제 타입의 같은 이름 멤버가 같은 형식이고 실제 타입에 직접 선언되었는지(base에 있으면 멤버
    // 포인터가 T Base::*라 멤버 thunk가 base를 소유자로 본다), 구조적 바인딩으로 공개 데이터 멤버의 개수(private 데이터·
    // union·base 분할도 컴파일 실패)와 위치별 형식, standard layout과 offset 증가 사슬로 선언 순서(같은 형식 멤버끼리
    // 바뀐 순서 포함)를 확인한다. 생성·소멸 noexcept는 MakeRuntimeStructOps가 실제 타입에 건다. sizeof는 대조하지
    // 않는다(꼬리 패딩에 숨은 멤버를 놓친다 — 숨은 멤버는 구조적 바인딩 개수가 잡는다). 검사 전용 멤버다: 헤더에 선언만 두고
    // 정의는 생성 소스에 둔다(호출하지 않는다 — 정의가 컴파일될 때 평가된다, ReflectionGeneratedSources 5.3절).
    private static void EmitBindsChecks(ClassModel type, string native, Action<string> Line, Action<string> Body)
    {
        string names = string.Join(", ", type.OwnFields.Select((_, index) => $"m{index}"));
        Line($"static void VerifyBinds(const {native}& value) noexcept;");
        Body($"void GeneratedType<{native}>::VerifyBinds(const {native}& value) noexcept {{");
        Body($"using BoundType = {native};");
        Body($"static_assert(::rocks::IsStandardLayoutV<BoundType>, \"Binds target {type.Binds} must be a standard-layout type\");");
        Body($"[[maybe_unused]] const auto& [{names}] = value;");
        for (int index = 0; index < type.OwnFields.Count; ++index)
        {
            FieldModel field = type.OwnFields[index];
            string member = CppType(field.NativeSpelling);
            Body($"static_assert(::rocks::IsSameV<decltype(BoundType::{field.Name}), {member}>, \"Binds mirror {type.Name}::{field.Name} must have the type of {type.Binds}::{field.Name}\");");
            Body($"static_assert(::rocks::IsSameV<decltype(&BoundType::{field.Name}), {member} (BoundType::*)>, \"Binds mirror {type.Name}::{field.Name} must be declared directly in {type.Binds}, not in a base\");");
            Body($"static_assert(::rocks::IsSameV<::rocks::RemoveCvT<decltype(m{index})>, {member}>, \"Binds mirror {type.Name}: member {index} of {type.Binds} must be {field.Name} with the mirror's type (same count and order)\");");
            if (index != 0)
            {
                Body($"static_assert(ROCKS_OFFSET_OF(BoundType, {type.OwnFields[index - 1].Name}) < ROCKS_OFFSET_OF(BoundType, {field.Name}), \"Binds mirror {type.Name}: {type.OwnFields[index - 1].Name} must come before {field.Name} as in {type.Binds}\");");
            }
        }

        Body("}");
    }

    // 리플렉션 struct의 GeneratedType 특수화다(Docs/Design/ReflectionFoundations.ko.md 4.6절): 형질
    // (ContainsStrongReference·RequiresWorldOnlyOwner)과 중첩 깊이, Id, Schema(base 없는 TypeSchema — flags는 struct
    // 플래그 Atomic 16뿐이다, Docs/Design/ReflectionExtensions.ko.md 3.1절),
    // Trace(모든 struct — 참조 없는 struct는 빈 본문), Ops(RuntimeStructOps — 멤버 codec 함수표, 참조 struct만 trace,
    // Migrate가 있으면 migrate), Register. 형질과 깊이는 모델 값을 내되 직접 멤버의 생성 값을 포함하는지
    // static_assert로 대조한다(import descriptor의 flags를 믿지 않는다). Binds 미러는 실제 타입(NativeName)의
    // 특수화를 내고 멤버 thunk·Trace·생성·소멸이 모두 실제 타입을 쓰며, 스키마 이름만 미러 이름이다.
    // struct가 InstancedStruct 값(단일·원소 배열·정적 배열·Map 값)을 (중첩 struct·원소·Optional·Map 값 struct까지) 담는지다(리플렉션
    // B9j — 런타임 등록 형질 StructView::ContainsInstancedStruct와 같은 규칙, Transient 멤버도 센다).
    private static bool ContainsInstancedStruct(SchemaModel schema, ClassModel type) =>
        type.Fields.Any(field => field.TargetKind == "InstancedStruct" ||
            (field.StructTarget && ContainsInstancedStruct(schema, schema.Find(field.Reference!))));

    // struct가 Required 멤버를 (중첩 struct·원소 struct까지, Transient 멤버 아래는 빼고) 담는지다(리플렉션 B9j — 런타임 등록 형질
    // StructView::ContainsRequired와 같은 규칙).
    private static bool ContainsRequired(SchemaModel schema, ClassModel type) =>
        type.Fields.Any(field => !field.Spec.Transient &&
            (field.Spec.Required || (field.StructTarget && ContainsRequired(schema, schema.Find(field.Reference!)))));

    // 모듈 API 매크로 이름이다(Docs/Design/BuildTargets 3.8절 BD27 — 빌드가 모듈 정의 헤더에 정의한다).
    internal static string ApiMacro(string module) => "ROCKS_" + module.ToUpperInvariant() + "_API";

    // 생성 헤더의 out-of-line 정적 멤버 선언(본문이 생성 소스에 있는 `static ... noexcept;` — ValidateTree·CopyValue·ReferenceLayout·비트
    // 필드 접근·Binds 검사 등)에 모듈 API 매크로를 붙이는 줄 출력이다(Docs/Design/BuildTargets 3.8절 BS8d2). 다른 모듈의 생성 코드·
    // 헤더 템플릿이 이 정적 멤버를 부르므로 Modular에서 export해야 한다. inline 정의(`{`)·constexpr·이미 매크로가 있는 선언은 그대로 둔다.
    // 클래스 단위로 붙이지 않는 것은 NativeKey처럼 멤버에 이미 붙인 선언과 겹치면 안 되기 때문이다.
    // 선언 줄에 본문({…} — 마지막 닫는 괄호 뒤의 {)이 있는가다. 기본 인자의 {}(`ModuleLease module = {}`)는 괄호 안이라 본문이 아니다.
    private static bool HasBody(string declaration)
    {
        int lastParen = declaration.LastIndexOf(')');
        return declaration.IndexOf('{', lastParen < 0 ? 0 : lastParen) >= 0;
    }

    private static Action<string> ExportingLine(string module, Action<string> Line)
    {
        string macro = ApiMacro(module);
        bool afterTemplate = false;
        return text =>
        {
            string trimmed = text.TrimStart();
            // 멤버 템플릿(앞 줄이 template <...>)은 쓰는 쪽에서 인스턴스가 생기므로 붙이지 않는다(BD27).
            bool outOfLine = !afterTemplate && trimmed.StartsWith("static ", StringComparison.Ordinal) &&
                !trimmed.StartsWith("static constexpr", StringComparison.Ordinal) && trimmed.EndsWith(';') && !HasBody(trimmed) &&
                !trimmed.Contains(macro, StringComparison.Ordinal);
            // template 머리만 있는 줄(`template <...>`)이다. 머리와 선언이 한 줄인 템플릿(`template <class V> static ... {}`)은 다음 줄과 무관하다.
            afterTemplate = trimmed.StartsWith("template", StringComparison.Ordinal) && trimmed.TrimEnd().EndsWith('>');
            Line(outOfLine ? text[..(text.Length - trimmed.Length)] + "static " + macro + " " + trimmed["static ".Length..] : text);
        };
    }

    // 리플렉션 클래스·struct·enum(Binds 미러면 실제 타입)의 native 키다(Docs/Design/BuildTargets 3.8절 BS8b·BS8d4). 헤더는 모듈 API
    // 매크로로 export한 선언만 두고, 생성 소스가 const가 아닌 정적 지역 저장소의 주소로 정의한다(소유 모듈에 하나 — 공유 라이브러리
    // 사이에서도 같은 키).
    private static void EmitNativeKey(string module, string self, Action<string> Line, Action<string> Body)
    {
        Line($"static {ApiMacro(module)} const void* NativeKey() noexcept;");
        Body($"const void* {self}::NativeKey() noexcept {{");
        Body("// Not const: identical read-only constants may be folded together by the linker (ICF).");
        Body("static unsigned char key = 0;");
        Body("return &key;");
        Body("}");
    }

    private static void EmitStruct(SchemaModel schema, ClassModel type, string module, Action<string> Line, Action<string> Body)
    {
        Line = ExportingLine(module, Line);
        string native = "::" + type.NativeName;
        string self = $"GeneratedType<{native}>";
        string True(bool value) => value ? "true" : "false";
        // 정적 검사는 생성 소스의 VerifyGenerated()에 모은다(ReflectionGeneratedSources 5.3절). 클래스 범위 이름(Depth·형질)은 멤버 함수
        // 안에서도 그대로 보인다.
        List<string> checks = [];
        Line($"template <> struct GeneratedType<{native}> {{");
        EmitBitfieldAccessors(type, native, Line, Body);
        Line($"static constexpr bool ContainsStrongReference = {True(type.ContainsStrongReference)};");
        Line($"static constexpr bool RequiresWorldOnlyOwner = {True(type.RequiresWorldOnlyOwner)};");
        Line($"static constexpr bool ContainsReferenceArray = {True(type.ContainsReferenceArray)};");
        // InstancedStruct 담기 조건의 생성 형질이다(리플렉션 B9j — InstancedStruct::Emplace<S>의 static_assert가 쓴다).
        Line($"static constexpr bool ContainsInstancedStruct = {True(ContainsInstancedStruct(schema, type))};");
        Line($"static constexpr bool ContainsRequired = {True(ContainsRequired(schema, type))};");
        Line($"static constexpr uint32 Depth = {type.Depth}u;");
        EmitNativeKey(module, self, Line, Body);
        checks.Add($"static_assert(Depth <= ::rocks::MaxStructDepth, \"ROCKS_STRUCT {type.Name} nesting depth exceeds MaxStructDepth (RMC2303)\");");
        // struct 상속(리플렉션 B9k): 리플렉션 base는 C++ base여야 하고, 비리플렉션 base는 필드가 없고 다형적이지 않아야 한다.
        if (type.Base.Length != 0)
        {
            checks.Add($"static_assert(::rocks::IsBaseOfV<::{type.Base}, {native}>, \"ROCKS_STRUCT {type.Name}: reflected base {type.Base} must be a C++ base (RMC2301)\");");
        }

        foreach (string empty in type.EmptyBases)
        {
            string emptyType = "::" + empty.TrimStart(':');
            checks.Add($"static_assert(::rocks::IsEmptyV<{emptyType}> && !::rocks::IsPolymorphicV<{emptyType}>, \"ROCKS_STRUCT {type.Name}: non-reflected base {empty} must have no fields and no virtual functions (RMC2301)\");");
        }

        if (type.Binds.Length != 0)
        {
            EmitBindsChecks(type, native, Line, Body);
            // Binds 실제 타입은 ObjectRuntime 목록에 있어야 NativeTypeKey가 생성 헤더 없는 쓰임을 잡는다(BuildTargets 3.8절 BS8d4).
            checks.Add($"static_assert(::rocks::BoundCoreValueV<{native}>, \"Binds target {type.Binds} must be listed in Object/BoundCoreValues.h (ROCKS_BOUND_CORE_VALUE) so that its key needs this generated header\");");
        }

        // 멤버 struct와 원소 struct는 깊이(원소 배열 멤버는 원소 깊이 + 1)와 형질을 포함해야 한다.
        foreach (string structure in type.Fields.Where(field => field.StructTarget).Select(field => field.Reference!).Distinct(StringComparer.Ordinal))
        {
            string member = $"GeneratedType<::{schema.Find(structure).NativeName}>";
            checks.Add($"static_assert({member}::Depth < Depth, \"ROCKS_STRUCT {type.Name} nests {structure} deeper than recorded; regenerate metadata (RMC2303)\");");
            checks.Add($"static_assert(ContainsStrongReference || !{member}::ContainsStrongReference, \"ROCKS_STRUCT {type.Name} holds reference struct {structure}; regenerate metadata\");");
            checks.Add($"static_assert(RequiresWorldOnlyOwner || !{member}::RequiresWorldOnlyOwner, \"ROCKS_STRUCT {type.Name} holds struct {structure} that requires a WorldOnly owner; regenerate metadata\");");
        }

        foreach (string structure in type.Fields.Where(field => field.IsStruct).Select(field => field.Reference!).Distinct(StringComparer.Ordinal))
        {
            checks.Add($"static_assert(ContainsReferenceArray || !GeneratedType<::{schema.Find(structure).NativeName}>::ContainsReferenceArray, \"ROCKS_STRUCT {type.Name} holds struct {structure} with reference arrays; regenerate metadata\");");
        }

        EmitElementStructAsserts(schema, type, checks.Add);

        // 모델 형질을 C++ 멤버 타입과 직접 대조한다(encode 고정이 ContainsReferenceArray에 기대므로 틀린 모델 값이 고정
        // 누락이 되지 않게 — Docs/Design/ReflectionFoundations.ko.md 5.6절). 직접 타입만 본다(struct 멤버는 위의 생성 형질).
        // Binds 미러는 생략한다: VerifyBinds가 실제 타입의 멤버마다 ::rocks::IsSameV<decltype(Real::m), 미러 필드 형식>을 확인하고 모델
        // 형질은 그 미러 필드 형식으로만 계산되므로 같은 보장이 이미 있다.
        foreach (FieldModel field in type.Binds.Length == 0 ? type.Fields : [])
        {
            string memberType = $"decltype({native}::{field.Name})";
            checks.Add($"static_assert(ContainsStrongReference || !::rocks::IsNativeStrongReference<{memberType}>, \"ROCKS_STRUCT {type.Name}::{field.Name} holds a strong object reference; regenerate metadata\");");
            checks.Add($"static_assert(ContainsReferenceArray || !::rocks::detail::RegistryContainer<{memberType}>::value, \"ROCKS_STRUCT {type.Name}::{field.Name} is a reference array; regenerate metadata\");");
        }

        // NATIVE 멤버는 스키마에 넣지 않는다. 강한 참조 금지(RMC2205)를 직접 타입에 대해 한 번 더 확인하고, WorldOnly
        // 소유자 형질은 struct에서는 오류가 아니라 RequiresWorldOnlyOwner로 전파되었는지 확인한다.
        foreach (NativeMemberModel member in type.NativeMembers)
        {
            string memberType = $"decltype({native}::{member.Name})";
            checks.Add($"static_assert(!IsNativeStrongReference<{memberType}>, \"ROCKS_NATIVE member {type.Name}::{member.Name} must not hold a strong object reference (RMC2205)\");");
            checks.Add($"static_assert(RequiresWorldOnlyOwner || !::rocks::RequiresWorldOnlyOwner<{memberType}>, \"ROCKS_NATIVE member {type.Name}::{member.Name} requires a WorldOnly owner; regenerate metadata\");");
            EmitNativeStructAsserts(schema, type, member, false, checks.Add);
            if (member.Struct is not null)
            {
                checks.Add($"static_assert(RequiresWorldOnlyOwner || !GeneratedType<::{schema.Find(member.Struct).NativeName}>::RequiresWorldOnlyOwner, \"ROCKS_NATIVE member {type.Name}::{member.Name} requires a WorldOnly owner; regenerate metadata\");");
            }
        }

        Line($"static constexpr TypeId Id() noexcept {{ return {GuidValue(type.Id)}; }}");
        Line("static const TypeSchema& Schema() noexcept;");
        Body($"const TypeSchema& {self}::Schema() noexcept {{");
        EmitFieldSchemas(type, Body);
        string fieldSpan = type.Fields.Count == 0 ? "Span<const FieldSchema>{}" : $"Span<const FieldSchema>(fields, {type.Fields.Count})";
        string? structBaseId = type.Base.Length == 0 ? null : schema.Find(type.Base).Id;
        Body($"static const TypeSchema schema{{Id(), {type.Version}, {fieldSpan}, {View(type.Name)}, {GuidValue(structBaseId)}, {type.Flags}u, {View(type.EffectiveToolName)}}};");
        Body("return schema;");
        Body("}");
        if (type.IsSettings)
        {
            EmitSettingsSchema(type, self, Line, Body);
        }

        // 참조 struct는 직접 ObjectRef 멤버(Transient 포함 — GC는 추적한다)를 Visit하고 멤버 struct의 Trace를, 모든 배열
        // 멤버에 TraceArrayField를, 모든 Map 멤버에 TraceMapField를 부른다(인라인 struct 안 ObjectRefArray·StructRefArray·
        // ObjectRefMap). 참조 없는 struct는 빈 본문이다(그 형질은 정적 검사가 C++ 멤버 타입과 대조한다). 헤더에 inline으로 남긴다 —
        // 소유 클래스의 Trace와 배열 보조 함수가 원소마다 직접 부른다(ReflectionGeneratedSources 5.2절).
        FieldModel[] traced = type.ContainsStrongReference ? type.Fields.Where(field => field.IsReference || field.IsStruct || field.IsArray || field.IsStaticArray || field.IsMap).ToArray() : [];
        if (traced.Length == 0)
        {
            Line($"static void Trace(const {native}&, TraceVisitor&) noexcept {{}}");
        }
        else
        {
            Line($"static void Trace(const {native}& value, TraceVisitor& visitor) noexcept {{");
            foreach (FieldModel field in traced)
            {
                Line(TraceStatement(schema, field, "value", native));
            }

            Line("}");
        }

        EmitVisitFields(schema, type, native, native, Line);
        string? baseNative = type.Base.Length == 0 ? null : "::" + schema.Find(type.Base).NativeName;
        EmitValueCopy(type, native, baseNative, Line, Body);
        EmitValidateTree(type, native, baseNative, checks, Line, Body);
        Line("static RuntimeStructOps Ops(ModuleLease module = {}) noexcept;");
        Body($"RuntimeStructOps {self}::Ops(ModuleLease module) noexcept {{");
        Body($"auto ops = MakeRuntimeStructOps<{native}>(Move(module));");
        Body("if constexpr (ValueCopyable) {");
        Body($"ops.copy = +[](void* destination, const void* source, Allocator& allocator) noexcept -> Result<void> {{ return CopyValue(*static_cast<{native}*>(destination), *static_cast<const {native}*>(source), allocator); }};");
        Body("}");
        if (type.Fields.Count != 0)
        {
            Body("static const RuntimeStructFieldOps fields[] = {");
            foreach (FieldModel field in type.Fields)
            {
                Body(FieldComment(schema, field));
                Body(field.Bitfield
                    ? $"detail::BitfieldStructFieldOps<{native}, {BitfieldAccessors(schema, field)}>({GuidValue(field.Id)}),"
                    : StructMemberOps(native, field));
            }

            Body("};");
            Body($"ops.fields = Span<const RuntimeStructFieldOps>(fields, {type.Fields.Count});");
        }

        if (type.ContainsStrongReference)
        {
            Body($"ops.trace = +[](const void* value, TraceVisitor& visitor) noexcept {{ Trace(*static_cast<const {native}*>(value), visitor); }};");
        }

        // struct가 선언한 Migrate를 타입 마이그레이션으로 연결한다. 시그니처·noexcept가 StructMigration과 다르거나
        // 접근할 수 없으면(private인데 GENERATED_BODY 없음) 컴파일 오류다 — 조용히 마이그레이션 없이 등록되지 않는다.
        if (type.HasMigrate)
        {
            Body($"ops.migrate = &{native}::Migrate;");
        }

        // 검증 hook(Docs/Design/CurveData.ko.md 9.1절): 트리에 hook이 있으면 validateTree, 자기 Validate가 있으면 validate.
        Body("if constexpr (HasValidateTree) {");
        Body($"ops.validateTree = +[](const void* value) noexcept -> Result<void> {{ return ValidateTree(*static_cast<const {native}*>(value)); }};");
        Body("}");
        Body("if constexpr (HasValidateSelf) {");
        Body($"ops.validate = +[](const void* value) noexcept -> Result<void> {{ return ValidateSelf(*static_cast<const {native}*>(value)); }};");
        Body("}");

        Body("ops.requiresWorldOnlyOwner = RequiresWorldOnlyOwner;");
        Body("return ops;");
        Body("}");
        Line("static Result<TypeRegistrationToken> Register(TypeRegistry& registry, ModuleLease module = {}) noexcept;");
        Body($"Result<TypeRegistrationToken> {self}::Register(TypeRegistry& registry, ModuleLease module) noexcept {{");
        Body("return registry.RegisterStruct(Schema(), Ops(Move(module)));");
        Body("}");
        EmitVerifyGenerated(self, checks, Line, Body);
        Line("};");
        // 다른 값(Array<S>·Map 값·Optional<S>·멤버 S)의 깊은 복사가 이 struct의 CopyValue를 쓰게 잇는다(Object/ValueCopy.h). 형질 값과 한 줄
        // 전달 함수라 헤더에 둔다(컴파일 중에 읽힌다).
        Line($"template <> struct detail::ValueCopy<{native}> {{");
        Line($"static constexpr bool Supported = GeneratedType<{native}>::ValueCopyable;");
        Line($"static Result<void> Copy({native}& destination, const {native}& source, Allocator& allocator) noexcept {{ return GeneratedType<{native}>::CopyValue(destination, source, allocator); }}");
        Line("};");
        // 다른 값(Array<S>·Map 값·Optional<S>·멤버 S·InstancedStruct 내용)의 검증이 이 struct의 ValidateTree를 쓰게 잇는다(Object/ValueCopy.h).
        Line($"template <> struct detail::ValueValidate<{native}> {{");
        Line($"static constexpr bool HasHook = GeneratedType<{native}>::HasValidateTree;");
        Line($"static Result<void> Run(const {native}& value) noexcept {{ return GeneratedType<{native}>::ValidateTree(value); }}");
        Line("};");
    }

    // struct 값 트리의 검증이다(Docs/Design/CurveData.ko.md 9.1절 — RuntimeStructOps::validateTree). HasValidateTree는 자기 Validate·base·
    // PROPERTY 멤버 형식(detail::ValueValidate<멤버>::HasHook) 중 하나라도 hook을 담을 수 있는지다. ValidateTree는 base 하위 객체, PROPERTY
    // 멤버 순서(bitfield bool 제외 — hook이 없다), 마지막에 자기 Validate 순으로 안쪽부터 검증하고 첫 거부에서 멈춘다. NATIVE 멤버는
    // 리플렉션 경로가 바꾸지 않으므로 보지 않는다. 자기 Validate는 시그니처를 static_assert로 대조하고, hook struct는 통째로 복사할 수
    // 있어야 한다(리플렉션 쓰기가 사본에 적용해 검증한 뒤 게시한다 — ValueCopyable). 형질(HasValidateTree·HasValidateSelf)은 헤더의
    // constexpr이고, 두 함수의 본문과 static_assert는 생성 소스다.
    private static void EmitValidateTree(ClassModel type, string native, string? baseNative, List<string> checks, Action<string> Line,
        Action<string> Body)
    {
        string self = $"GeneratedType<{native}>";
        IEnumerable<FieldModel> ownFields = baseNative is null ? type.Fields : type.OwnFields;
        string[] members = ownFields.Where(field => !field.Bitfield).Select(field => field.Name).ToArray();
        string hasHook = (type.HasValidate ? "true" : "false") +
            (baseNative is null ? "" : $" || GeneratedType<{baseNative}>::HasValidateTree") +
            string.Concat(members.Select(member => $" || ::rocks::detail::ValueValidate<decltype({native}::{member})>::HasHook"));
        Line($"static constexpr bool HasValidateTree = {hasHook};");
        // 자기 수준의 hook(RuntimeStructOps::validate — decode가 값을 다 채운 뒤 부른다)은 base 사슬의 Validate 다음 자기 Validate다. base의
        // hook을 물려받은 struct도 참조 없는 값이어야 한다(가져온 base는 C# 모델이 모르므로 static_assert로 본다).
        string selfHook = (type.HasValidate ? "true" : "false") + (baseNative is null ? "" : $" || GeneratedType<{baseNative}>::HasValidateSelf");
        Line($"static constexpr bool HasValidateSelf = {selfHook};");
        checks.Add($"static_assert(!HasValidateSelf || (!ContainsStrongReference && ValueCopyable), \"{type.Name} has a Validate hook (its own or a base's) and must be a deep-copyable value without strong references: reflected writes validate a copy before publishing it\");");
        // Binds 미러(CurveData CV9)의 hook은 미러 struct의 static Validate(const 실제 타입&)다(실제 Core 타입에는 hook을 둘 수 없다).
        string hookOwner = type.Binds.Length != 0 ? "::" + type.Name : native;
        if (type.HasValidate)
        {
            checks.Add($"static_assert(::rocks::IsSameV<decltype(&{hookOwner}::Validate), ::rocks::Result<void> (*)(const {native}&) noexcept>, \"{type.Name}::Validate must be declared as static rocks::Result<void> Validate(const {(type.Binds.Length != 0 ? type.Binds : type.Name)}&) noexcept\");");
        }

        Line($"static Result<void> ValidateSelf(const {native}& value) noexcept;");
        Body($"Result<void> {self}::ValidateSelf([[maybe_unused]] const {native}& value) noexcept {{");
        if (baseNative is not null)
        {
            Body($"if constexpr (GeneratedType<{baseNative}>::HasValidateSelf) {{");
            Body($"if (auto checked = GeneratedType<{baseNative}>::ValidateSelf(static_cast<const {baseNative}&>(value)); !checked) {{ return checked; }}");
            Body("}");
        }

        Body(type.HasValidate
            ? $"return ::rocks::detail::StructValidationResult({hookOwner}::Validate(value));"
            : "return Result<void>::Success();");
        Body("}");

        Line($"static Result<void> ValidateTree(const {native}& value) noexcept;");
        Body($"Result<void> {self}::ValidateTree([[maybe_unused]] const {native}& value) noexcept {{");
        if (baseNative is not null)
        {
            Body($"if constexpr (GeneratedType<{baseNative}>::HasValidateTree) {{");
            Body($"if (auto checked = GeneratedType<{baseNative}>::ValidateTree(static_cast<const {baseNative}&>(value)); !checked) {{ return checked; }}");
            Body("}");
        }

        foreach (string member in members)
        {
            Body($"if constexpr (::rocks::detail::ValueValidate<decltype({native}::{member})>::HasHook) {{");
            Body($"if (auto checked = ::rocks::detail::ValueValidate<decltype({native}::{member})>::Run(value.{member}); !checked) {{ return checked; }}");
            Body("}");
        }

        Body(type.HasValidate
            ? $"return ::rocks::detail::StructValidationResult({hookOwner}::Validate(value));"
            : "return Result<void>::Success();");
        Body("}");
    }

    // 설정 struct의 설정 메타데이터다(Docs/Design/ConfigSystem.ko.md 7절 — Meta/SettingsSchema.h): branch·섹션 이름과 설정 지정자가 있는 직접
    // 멤버(스키마 필드 순서)의 필드 ID·SettingsFieldFlags 비트·콘솔 이름. 설정 계층이 GeneratedType<S>::Settings()로 읽는다. 정적 표라
    // 생성 소스에 한 벌만 둔다.
    private static void EmitSettingsSchema(ClassModel type, string self, Action<string> Line, Action<string> Body)
    {
        FieldModel[] fields = type.Fields.Where(field => field.Spec.HasSettings).ToArray();
        Line("static const SettingsSchema& Settings() noexcept;");
        Body($"const SettingsSchema& {self}::Settings() noexcept {{");
        if (fields.Length != 0)
        {
            Body("static const SettingsFieldSchema settingsFields[] = {");
            foreach (FieldModel field in fields)
            {
                Body($"{{{GuidValue(field.Id)}, {field.Spec.SettingsFlags}u, {View(field.Spec.ConsoleName)}}},");
            }

            Body("};");
        }

        string span = fields.Length == 0 ? "Span<const SettingsFieldSchema>{}" : $"Span<const SettingsFieldSchema>(settingsFields, {fields.Length})";
        Body($"static const SettingsSchema settings{{{View(type.SettingsBranch)}, {View(type.SettingsSection)}, {span}}};");
        Body("return settings;");
        Body("}");
    }

    // struct 값의 깊은 복사다(리플렉션 B9i3c0 — Docs/Design/ReflectionExtensions.ko.md 10.2절, UE UScriptStruct::CopyScriptStruct 대응).
    // MetaCompiler는 struct의 모든 비정적 멤버에 PROPERTY 또는 NATIVE를 요구하므로 두 목록이 struct의 멤버 전부다: 멤버마다
    // detail::TryCopyValue로 새 값을 다 만든 뒤 이동 대입 한 번으로 넣는다(실패하면 destination 그대로). 한 멤버라도 복사할 수
    // 없으면(ObjectRef·Registry 컨테이너·복사 의미가 없는 NATIVE 타입) ValueCopyable이 거짓이고 CopyValue는 Unsupported다 — 멤버를
    // 조용히 빠뜨리지 않는다. trivially copyable struct는 대입 한 번이다. 리플렉션 base가 있는 struct(리플렉션 B9k)는 base 하위 객체를
    // base의 CopyValue로 먼저 복사하고 자기 멤버만 복사한다 — base의 NATIVE 멤버(파생 모델·import descriptor에 없다)와 상속 필드를 base가
    // 책임진다.
    // 배치(ReflectionGeneratedSources 5.4절): ValueCopyable은 헤더의 constexpr이다. CopyValue는 헤더에 선언하는 비템플릿 함수이고, 복사할
    // 수 없는 분기가 컴파일되지 않게 하는 템플릿 본문은 다른 이름의 멤버 템플릿 CopyValueImpl이다 — 생성 소스에서 정의하고 CopyValue가 한
    // 번 인스턴스화한다. 같은 이름으로 두면 과부하 해석이 정의 없는 템플릿을 고를 수 있다.
    private static void EmitValueCopy(ClassModel type, string native, string? baseNative, Action<string> Line, Action<string> Body)
    {
        string self = $"GeneratedType<{native}>";
        IEnumerable<FieldModel> ownFields = baseNative is null ? type.Fields : type.OwnFields;
        string[] members = ownFields.Select(field => field.Name).Concat(type.NativeMembers.Select(member => member.Name)).ToArray();
        string supported = (baseNative is null ? "" : $" && GeneratedType<{baseNative}>::ValueCopyable") +
            string.Concat(members.Select(member => $" && ::rocks::detail::ValueCopy<decltype({native}::{member})>::Supported"));
        Line($"static constexpr bool ValueCopyable = ::rocks::detail::IsPlainCopyV<{native}> || (::rocks::IsNothrowMoveAssignableV<{native}>{supported});");
        Line($"static Result<void> CopyValue({native}& destination, const {native}& source, Allocator& allocator) noexcept;");
        Line("template <class Self>");
        Line("static Result<void> CopyValueImpl(Self& destination, const Self& source, Allocator& allocator) noexcept;");
        Body("template <class Self>");
        Body($"Result<void> {self}::CopyValueImpl(Self& destination, const Self& source, Allocator& allocator) noexcept {{");
        Body("if constexpr (::rocks::detail::IsPlainCopyV<Self>) {");
        Body("(void)allocator;");
        Body("destination = source;");
        Body("return Result<void>::Success();");
        Body("} else if constexpr (ValueCopyable) {");
        Body("Self copy = ::rocks::detail::MakeAllocatedValue<Self>(allocator);");
        if (baseNative is not null)
        {
            Body($"if (auto copied = GeneratedType<{baseNative}>::CopyValue(static_cast<{baseNative}&>(copy), static_cast<const {baseNative}&>(source), allocator); !copied) {{ return copied; }}");
        }

        // bitfield(PROPERTY bitfield bool·NATIVE 정수 bitfield — 리플렉션 B9m)는 참조를 만들 수 없으므로 대입한다(정수라 깊은 복사다).
        HashSet<string> bitfields = type.Fields.Where(field => field.Bitfield).Select(field => field.Name)
            .Concat(type.NativeMembers.Where(member => member.Bitfield).Select(member => member.Name)).ToHashSet(StringComparer.Ordinal);
        foreach (string member in members)
        {
            Body(bitfields.Contains(member)
                ? $"copy.{member} = source.{member};"
                : $"if (auto copied = ::rocks::detail::TryCopyValue(copy.{member}, source.{member}, allocator); !copied) {{ return copied; }}");
        }

        Body("destination = Move(copy);");
        Body("return Result<void>::Success();");
        Body("} else {");
        Body("(void)destination;");
        Body("(void)source;");
        Body("(void)allocator;");
        Body("return Result<void>::Failure(ErrorCode::Unsupported);");
        Body("}");
        Body("}");
        Body($"Result<void> {self}::CopyValue({native}& destination, const {native}& source, Allocator& allocator) noexcept {{");
        Body($"return CopyValueImpl<{native}>(destination, source, allocator);");
        Body("}");
    }

    // 클래스·struct 스키마의 필드 배열이다(필드가 없으면 내지 않는다). 배열 필드는 value가 {Array, 0}이고 원소 형식
    // element(원소 대상 ID)와 maxElements를 더 싣는다(Docs/Design/ReflectionFoundations.ko.md 5.6절). Optional 필드는 value가
    // {Optional, 0}이고 내부 형식 element와 maxElements 0을 싣는다(ReflectionExtensions.ko.md 6절). Map 필드는 value가 {Map, 0}이고
    // 값 형식 element·maxElements·키 형식 key를, Set 필드는 value가 {Set, 0}이고 원소 형식 element·maxElements를 싣는다(같은 문서
    // 7.2절).
    private static void EmitFieldSchemas(ClassModel type, Action<string> Line)
    {
        if (type.Fields.Count == 0)
        {
            return;
        }

        Line("static const FieldSchema fields[] = {");
        foreach (FieldModel field in type.Fields)
        {
            string? targetId = field.HasTargetType ? field.ReferenceId : null;
            string kind = field.IsObjectReferenceFieldKind ? "ObjectReference" : "Value";
            string head = $"{{{GuidValue(field.Id)}, FieldKind::{kind}, {field.Flags}u, {View(field.Name)}, {{}}, ";
            string labels = $"{View(field.Spec.Category)}, {View(field.Spec.DisplayName)}, {View(field.Spec.ToolName)}";
            string? keyId = field.KeyHasTargetType ? field.KeyReferenceId : null;
            // bundle 목록(에셋 A4e2a)은 FieldSchema의 마지막 칸이라, 있으면 그 앞 칸(element·maxElements·key)을 빈 값으로라도 채운다.
            string bundles = field.Spec.AssetBundles.Length != 0 ? $", {View(field.Spec.AssetBundles)}" : "";
            const string NoType = "{ValueKind::Opaque, Guid{}}";
            string key = field.IsMap ? $", {{ValueKind::{field.KeyKind}, {GuidValue(keyId)}}}" : bundles.Length != 0 ? ", " + NoType : "";
            Line(field.HasElement
                ? $"{head}{{ValueKind::{field.Kind}, Guid{{}}}}, {labels}, {{ValueKind::{field.ElementKind}, {GuidValue(targetId)}}}, {field.MaxElements}u{key}{bundles}}},"
                : bundles.Length != 0
                    ? $"{head}{{ValueKind::{field.Kind}, {GuidValue(targetId)}}}, {labels}, {NoType}, 0u{key}{bundles}}},"
                    : $"{head}{{ValueKind::{field.Kind}, {GuidValue(targetId)}}}, {labels}}},");
        }

        Line("};");
    }

    // 리플렉션 enum의 GeneratedType 특수화다: Id, Schema(EnumSchema), constexpr IsDeclared(쓰기·복원 검증),
    // Register. C++ underlying이 스키마와 같은지 컴파일 시 확인한다.
    // Binds 미러 enum(CurveData CV9 — Core enum)은 실제 enum(NativeName)의 특수화를 내고 열거자 이름·값을 실제 enum과
    // 대조한다(미러가 나열한 열거자만 선언 값이다 — 실제 enum의 다른 열거자는 저장·쓰기에서 거부된다). 스키마 이름은
    // 미러 이름이다. 헤더에는 Id·IsDeclared(둘 다 constexpr로 쓰인다)와 선언만 두고, Schema·Register와 정적 검사는 생성 소스에 둔다.
    private static void EmitEnum(ClassModel type, string module, Action<string> Line, Action<string> Body)
    {
        Line = ExportingLine(module, Line);
        string native = "::" + type.NativeName;
        string self = $"GeneratedType<{native}>";
        List<string> checks = [];
        Line($"template <> struct GeneratedType<{native}> {{");
        checks.Add($"static_assert(::rocks::IsSameV<::rocks::UnderlyingTypeT<{native}>, {EnumRules.NativeType(type.Underlying)}>, \"ROCKS_ENUM {type.Name} underlying type changed; regenerate metadata\");");
        // 스키마의 값이 C++ 값과 같은지 컴파일 시 대조한다(MetaCompiler가 AST에서 읽은 값을 믿지 않는다).
        foreach (EnumeratorModel value in type.Enumerators)
        {
            checks.Add($"static_assert(static_cast<int64>({native}::{value.Name}) == {Int64(value.Value)}, \"ROCKS_ENUM {type.Name}::{value.Name} value changed; regenerate metadata\");");
        }

        Line($"static constexpr TypeId Id() noexcept {{ return {GuidValue(type.Id)}; }}");
        Line("static const EnumSchema& Schema() noexcept;");
        EmitNativeKey(module, self, Line, Body);
        Body($"const EnumSchema& {self}::Schema() noexcept {{");
        Body("static const EnumeratorSchema values[] = {");
        foreach (EnumeratorModel value in type.Enumerators)
        {
            Body($"{{{View(value.Name)}, {View(value.ToolName)}, {View(value.DisplayName)}, {Int64(value.Value)}, {(value.Hidden ? 1 : 0)}u}},");
        }

        Body("};");
        Body($"static const EnumSchema schema{{Id(), {View(type.Name)}, ValueKind::{type.Underlying}, {(type.FlagsEnum ? 1 : 0)}u, Span<const EnumeratorSchema>(values, {type.Enumerators.Count}), {View(type.ToolPrefix)}}};");
        Body("return schema;");
        Body("}");
        // TypeRegistry 없이도(staged 쓰기·복원) 같은 규칙으로 값을 검증한다(IsDeclaredEnumValue와 같다).
        Line("static constexpr bool IsDeclared(int64 value) noexcept {");
        if (type.FlagsEnum)
        {
            ulong mask = type.Enumerators.Aggregate(0UL, (bits, value) => bits | (ulong)value.Value);
            long maximum = EnumRules.Range(type.Underlying)!.Value.Maximum;
            // 상한이 int64 최댓값(UInt64·Int64)이면 상한 비교는 늘 참이므로 내지 않는다(비교가 경고 대상이 되지 않게).
            string upper = maximum == long.MaxValue ? "" : $" && value <= {Int64(maximum)}";
            Line($"return value >= 0{upper} && (static_cast<uint64>(value) & ~0x{mask:x}ull) == 0;");
        }
        else
        {
            Line("switch (value) {");
            foreach (EnumeratorModel value in type.Enumerators)
            {
                Line($"case {Int64(value.Value)}:");
            }

            Line("return true;");
            Line("default:");
            Line("return false;");
            Line("}");
        }

        Line("}");
        Line("static Result<TypeRegistrationToken> Register(TypeRegistry& registry, ModuleLease module = {}) noexcept;");
        Body($"Result<TypeRegistrationToken> {self}::Register(TypeRegistry& registry, ModuleLease module) noexcept {{");
        Body($"return registry.RegisterEnum(Schema(), RuntimeEnumOps{{NativeTypeKey<{native}>(), Move(module)}});");
        Body("}");
        EmitVerifyGenerated(self, checks, Line, Body);
        Line("};");
    }

    // int64 리터럴이다. int64 최솟값은 리터럴로 쓸 수 없으므로(9223372036854775808ll이 int64 밖이다) 식으로 쓴다(int64 enum).
    private static string Int64(long value) =>
        value == long.MinValue ? "(-9223372036854775807ll - 1)" : value.ToString(CultureInfo.InvariantCulture) + "ll";
}
