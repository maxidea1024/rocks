using System.Globalization;
using System.Text;

namespace Rocks.Tooling.Common;

/// <summary>
/// 셰이더 도구 표의 생성 번역 단위를 만든다(Docs/Design/ShaderSystem 9절). 입력은 Engine 루트(<see cref="ThirdPartyManifest.EngineThirdPartyRoot"/>)의
/// <c>kind: binary</c> manifest이고, 출력은 <c>Engine/Source/Developer/ShaderToolTable/Public/ShaderToolTable/ShaderToolTable.h</c>가 선언한
/// <c>rocks::shader::ShaderToolHostKey</c>·<c>ShaderTools</c>의 정의다. 모듈 규칙(ShaderToolTable.Build.cs)이 이 텍스트를
/// <c>NativeModuleInput.GeneratedSources</c>로 넘기고 빌드가 <c>&lt;out&gt;/GeneratedSources/ShaderToolTable/</c>에 쓴다(BuildInfo와 같은 방식).
/// <list type="bullet">
/// <item>표는 메타데이터만 담는다: 이름·버전(system은 최소 버전)·출처·저장소 디렉터리 이름(<see cref="ThirdPartyHost.StoreKey"/>)·
/// 빌드 대상 호스트의 파일(경로·SHA-256·크기·role). 파일을 열거나 저장소를 보지 않는다.</item>
/// <item>호스트는 빌드 대상 하나다. 대상이 개발 호스트가 아니면(Android) <paramref name="hostKey"/>가 null이고 모든 도구의 파일 목록이 빈다.
/// manifest가 그 호스트를 적지 않은 도구도 파일 목록이 빈다(다른 호스트 산출물로 대신하지 않는다).</item>
/// <item>출력은 입력이 같으면 byte 단위로 같다(도구 이름 ordinal 순, 파일은 manifest 순, 호스트 경로 없음).</item>
/// </list>
/// 사용 예(모듈 규칙): <c>new NativeGeneratedSource(ShaderToolTableSource.FileName, ShaderToolTableSource.Generate(context.RootDirectory, "windows-x64"))</c>.
/// </summary>
public static class ShaderToolTableSource
{
    /// <summary>생성 번역 단위의 파일 이름이다.</summary>
    public const string FileName = "ShaderToolTable.Generated.cpp";

    /// <summary>
    /// 생성 번역 단위 텍스트를 만든다.
    /// </summary>
    /// <param name="repositoryRoot">저장소 루트.</param>
    /// <param name="hostKey">빌드 대상 호스트 키(<see cref="ThirdPartyManifest.HostKeys"/>). 개발 호스트가 아닌 대상은 null.</param>
    /// <returns>C++ 원문(ASCII, 줄 끝 <c>\n</c>).</returns>
    /// <exception cref="FormatException">manifest 오류, 모르는 호스트 키, C 문자열로 옮길 수 없는 이름·경로(출력 가능한 ASCII가 아님).</exception>
    public static string Generate(string repositoryRoot, string? hostKey)
    {
        if (hostKey is not null && !ThirdPartyManifest.HostKeys.Contains(hostKey, StringComparer.Ordinal))
        {
            throw new FormatException($"unknown binary host key '{hostKey}' (known: {string.Join(", ", ThirdPartyManifest.HostKeys)})");
        }

        string engineRoot = Path.Combine(Path.GetFullPath(repositoryRoot), ThirdPartyManifest.EngineThirdPartyRoot);
        var manifests = new List<ThirdPartyManifest>();
        if (Directory.Exists(engineRoot))
        {
            foreach (string library in Directory.EnumerateDirectories(engineRoot).Order(StringComparer.Ordinal))
            {
                if (!File.Exists(Path.Combine(library, ThirdPartyManifest.FileName)))
                {
                    continue;
                }

                ThirdPartyManifest manifest = ThirdPartyManifest.Read(library);
                if (manifest.Kind == ThirdPartyKind.Binary)
                {
                    manifests.Add(manifest);
                }
            }
        }

        manifests.Sort((left, right) => string.CompareOrdinal(left.Name, right.Name));
        var text = new StringBuilder();
        text.Append("// Generated by Rocks.Build from Engine/Source/ThirdParty binary manifests for host ")
            .Append(hostKey ?? "<none>").Append(". Do not edit.\n");
        text.Append("#include <ShaderToolTable/ShaderToolTable.h>\n\n");
        text.Append("namespace rocks::shader {\n\n");
        text.Append("namespace {\n\n");
        var fileArrays = new List<string?>();
        foreach (ThirdPartyManifest manifest in manifests)
        {
            ThirdPartyBinary binary = manifest.Binary!;
            if (hostKey is null || !binary.Hosts.TryGetValue(hostKey, out ThirdPartyHost? host))
            {
                fileArrays.Add(null);
                continue;
            }

            string array = manifest.Name + "Files";
            fileArrays.Add(array);
            text.Append("constexpr ShaderToolFile ").Append(array).Append("[] = {\n");
            foreach (ThirdPartyHostFile file in host.Files)
            {
                text.Append("    {").Append(Literal(file.Path)).Append(", ").Append(Digest(file.Sha256)).Append(", ")
                    .Append((file.Size ?? 0).ToString(CultureInfo.InvariantCulture)).Append("u, ShaderToolFileRole::").Append(file.Role)
                    .Append(", ").Append(file.Sha256 is null ? "false" : "true").Append("},\n");
            }

            text.Append("};\n\n");
        }

        text.Append("constexpr ShaderTool Tools[] = {\n");
        if (manifests.Count == 0)
        {
            text.Append("    {nullptr, nullptr, ShaderToolOrigin::System, nullptr, nullptr, 0u},\n");
        }

        for (int index = 0; index < manifests.Count; ++index)
        {
            ThirdPartyManifest manifest = manifests[index];
            ThirdPartyBinary binary = manifest.Binary!;
            string? array = fileArrays[index];
            string? storeKey = array is null ? null : binary.Hosts[hostKey!].StoreKey;
            text.Append("    {").Append(Literal(manifest.Name)).Append(", ").Append(Literal(manifest.Version))
                .Append(", ShaderToolOrigin::").Append(binary.Origin).Append(", ")
                .Append(storeKey is null ? "nullptr" : Literal(storeKey)).Append(", ")
                .Append(array ?? "nullptr").Append(", ")
                .Append(array is null ? "0u" : $"sizeof({array}) / sizeof({array}[0])").Append("},\n");
        }

        text.Append("};\n\n");
        text.Append("} // namespace\n\n");
        text.Append("const char* ShaderToolHostKey() noexcept {\n    return ").Append(Literal(hostKey ?? "")).Append(";\n}\n\n");
        text.Append("Span<const ShaderTool> ShaderTools() noexcept {\n    return Span<const ShaderTool>(Tools, ")
            .Append(manifests.Count.ToString(CultureInfo.InvariantCulture)).Append("u);\n}\n\n");
        text.Append("} // namespace rocks::shader\n");
        return text.ToString();
    }

    // 64자 소문자 hex를 Sha256Digest 초기화식으로 바꾼다. 없으면(system) 0이다.
    private static string Digest(string? hex)
    {
        if (hex is null)
        {
            return "Sha256Digest{}";
        }

        var text = new StringBuilder("Sha256Digest{{");
        for (int index = 0; index < hex.Length; index += 2)
        {
            text.Append(index == 0 ? "0x" : ", 0x").Append(hex, index, 2);
        }

        return text.Append("}}").ToString();
    }

    // 출력 가능한 ASCII만 받는다(manifest 이름·버전·경로 규칙 안의 값). 따옴표·역슬래시·물음표(trigraph 경고 방지)는 escape한다.
    private static string Literal(string value)
    {
        var text = new StringBuilder("\"");
        foreach (char character in value)
        {
            if (character < 0x20 || character > 0x7E)
            {
                throw new FormatException($"'{value}' cannot be written to the shader tool table (printable ASCII only)");
            }

            if (character is '"' or '\\' or '?')
            {
                text.Append('\\');
            }

            text.Append(character);
        }

        return text.Append('"').ToString();
    }
}
