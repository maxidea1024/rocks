using System.Text;

namespace Rocks.Build;

/// <summary>
/// 모듈 규칙의 PCH 사용 방식이다(Docs/Design/UnityBuildPch.ko.md 8.1절). <see cref="Auto"/>는 모듈 PCH(<c>PrivatePchHeader</c>)가
/// 있으면 그것을, 없으면 쓸 수 있는 공유 PCH를 쓴다. <see cref="PrivateOnly"/>는 모듈 PCH만 쓰고, <see cref="Off"/>는 쓰지 않는다.
/// 빌드 전체를 끄는 것은 요청의 <see cref="NativeBuildRequest.Pch"/>(명령 옵션 <c>--pch off</c>)다.
/// </summary>
public enum PchUsage
{
    Auto,
    PrivateOnly,
    Off
}

/// <summary>
/// 모듈 정의 헤더다(Docs/Design/UnityBuildPch.ko.md 8.2절). 모듈 정의(전파된 dependency public define과 모듈 public/private define, 모듈
/// 진입점의 <c>ROCKS_MODULE_NAME</c>)를 명령줄 <c>/D</c> 대신 <c>&lt;out&gt;/Definitions/&lt;모듈&gt;.Definitions.h</c>에 쓰고 번역 단위마다
/// 강제 include한다. 정의가 같은 번역 단위끼리만 PCH를 공유할 수 있기 때문이다. 리플렉션 AST 생성(MetaCompiler)도 같은 파일을 강제
/// include해 AST와 native compile의 정의가 갈라지지 않는다. 형식은 머리말 한 줄과 이름 ordinal 순의 <c>#define 이름 값</c> 줄이다.
/// </summary>
public static class ModuleDefinitions
{
    /// <summary>정의 헤더를 두는 출력 아래 디렉터리 이름이다.</summary>
    public const string DirectoryName = "Definitions";

    private const string Header = "// Generated by Rocks.Build. Do not edit.";

    public static string PathOf(string output, string module) => Path.Combine(output, DirectoryName, module + ".Definitions.h");

    /// <summary>
    /// 모듈 하나의 번역 단위가 받는 정의다: 모듈 public·private 정의, 의존 모듈(의존 순서)의 public 정의, 진입점 모듈이면
    /// <c>ROCKS_MODULE_NAME=&lt;이름&gt;</c>. 같은 이름에 다른 값이 있으면 <see cref="ArgumentException"/>이다.
    /// </summary>
    public static string[] Of(NativeModuleInput module, IEnumerable<NativeModuleInput> dependencies, bool entryModule)
    {
        string[] defines = module.PublicDefines.Concat(module.PrivateDefines)
            .Concat(dependencies.SelectMany(value => value.PublicDefines)).Distinct(StringComparer.Ordinal).ToArray();
        foreach (var define in defines.GroupBy(value => value.Split('=')[0], StringComparer.Ordinal))
        {
            if (define.Count() != 1)
            {
                throw new ArgumentException($"Module {module.Name}: conflicting propagated definition {define.Key} ({string.Join(", ", define)}).");
            }
        }

        return entryModule ? [.. defines, ModuleTables.ModuleNameMacro + "=" + module.Name] : defines;
    }

    /// <summary>모듈 진입점을 갖는 모듈 이름이다(이 모듈들의 번역 단위가 <c>ROCKS_MODULE_NAME</c>을 받는다).</summary>
    public static HashSet<string> EntryModules(IEnumerable<NativeModuleInput> modules) =>
        ModuleTables.EntryModules(modules.ToDictionary(module => module.Name, StringComparer.OrdinalIgnoreCase));

    /// <summary>정의 목록(<c>이름</c> 또는 <c>이름=값</c>)의 헤더 내용이다. 값이 없는 정의는 명령줄 <c>-D이름</c>처럼 1이다.</summary>
    public static string Content(IEnumerable<string> defines)
    {
        var text = new StringBuilder(Header).Append('\n');
        foreach (string define in defines.Order(StringComparer.Ordinal))
        {
            int equals = define.IndexOf('=');
            text.Append("#define ").Append(equals < 0 ? define : define[..equals]).Append(' ')
                .Append(equals < 0 ? "1" : define[(equals + 1)..]).Append('\n');
        }

        return text.ToString();
    }
}

/// <summary>
/// 번역 단위가 쓰는 PCH 하나의 계획이다. Action은 PCH를 만드는 action, Files는 그 action이 쓰는 생성 파일(stub 소스), Directory는
/// 변형 디렉터리다. UseArguments는 소비 번역 단위의 물리 인자(PCH 바이너리 사용), LogicalArguments는 논리 명령의 인자(PCH 앞부분·PCH
/// 헤더·추가 정의 헤더의 강제 include), LogicalFiles는 그 헤더들, ConsumerInputs는 소비 action의 key에 드는 입력이다.
/// </summary>
internal sealed record PchPlan(NativeAction Action, IReadOnlyList<PlannedFile> Files, string Directory, string[] UseArguments,
    string[] LogicalArguments, string[] LogicalFiles, string[] ConsumerInputs);

/// <summary>
/// PCH action을 만든다(Docs/Design/UnityBuildPch.ko.md 8절).
/// <list type="bullet">
/// <item>clang-cl: 빈 stub 소스에 <c>/FI&lt;앞부분&gt; /FI&lt;헤더&gt; /Yc&lt;헤더&gt; /Fp&lt;pch&gt; /Fo&lt;stub obj&gt;</c>로 만들고
/// <c>/FI&lt;앞부분&gt; /FI&lt;헤더&gt; /Yu&lt;헤더&gt; /Fp&lt;pch&gt;</c>로 쓴다. stub object는 원자적 게시를 위해 출력으로 선언하지만
/// 링크하지 않는다.</item>
/// <item>clang++: <c>-include &lt;앞부분&gt; -x c++-header &lt;헤더&gt; -o &lt;pch&gt;</c>로 만들고 <c>-include-pch &lt;pch&gt;</c>로 쓴다.</item>
/// <item>공통: <c>-Xclang -fno-pch-timestamp</c>(PCH 바이트 결정성). 낡은 PCH 방지는 clang의 입력 검증이 아니라 action key가 맡는다 —
/// PCH action은 2단 key로 다시 만들고 소비 번역 단위는 PCH의 기록 해시를 입력으로 갖는다.</item>
/// <item>변형: (경로가 아닌 compile 인자 전체, PCH 앞부분 내용, PCH 헤더 철자)의 해시가 다르면 다른 PCH다. 위치는
/// <c>&lt;out&gt;/Pch/&lt;제공 모듈&gt;/&lt;변형 key 12자리&gt;/</c>다.</item>
/// </list>
/// </summary>
internal static class PchBuild
{
    /// <summary>PCH를 두는 출력 아래 디렉터리 이름이다.</summary>
    public const string DirectoryName = "Pch";

    /// <summary>모듈 PCH를 만드는 번역 단위 수 하한의 기본값이다.</summary>
    public const int DefaultMinimumTranslationUnits = 3;

    // 변형 디렉터리 이름에 쓰는 변형 key의 hex 자릿수다.
    private const int VariantHexLength = 12;

    private const string StubContent = "// Generated by Rocks.Build. Do not edit.\n";

    public static PchPlan? Plan(NativeBuildRequest request, NativeModuleInput module, IReadOnlyList<NativeModuleInput> dependencies,
        IReadOnlyList<string> includes, IReadOnlyList<string> defines, List<string> common, string? definitionsHeader, string definitionsContent,
        int users, string[] depfile, IReadOnlyList<string> headers, IReadOnlyList<string> extraInputs, Func<string, string> absolute,
        string output, List<string> notices)
    {
        if (module.PrivatePchHeader is string spelling)
        {
            // 번역 단위가 적으면 PCH를 만드는 비용이 절약분보다 크다.
            if (users < module.PrivatePchMinTus)
            {
                return null;
            }

            string header = absolute(spelling);
            if (!File.Exists(header))
            {
                throw new FileNotFoundException($"Module {module.Name}: PrivatePchHeader does not exist.", header);
            }

            return Create(request, module.Name, header, spelling.Replace('\\', '/'), common, definitionsHeader, definitionsContent, null, depfile,
                headers, extraInputs, output, module.Optimization);
        }

        return null;
    }

    // provider는 PCH 헤더를 제공하는 모듈(모듈 PCH면 자기 자신)이다. prefix는 PCH 앞부분(정의 헤더), extra는 PCH 뒤에 강제 include하는
    // 소비 모듈의 추가 정의 헤더(공유 PCH)다.
    internal static PchPlan Create(NativeBuildRequest request, string provider, string header, string headerSpelling, List<string> common,
        string? prefix, string prefixContent, string? extra, string[] depfile, IReadOnlyList<string> headers, IReadOnlyList<string> extraInputs,
        string output, CodeOptimization optimization)
    {
        bool windows = request.Toolchain.Platform == NativePlatform.Windows;
        string[] Forced(string? file) => file is null ? [] : windows ? ["/FI" + file] : ["-include", file];
        // 변형 key: 경로 인자(include 디렉터리)는 뺀다 — 소비 모듈마다 달라서 넣으면 공유 PCH가 모듈마다 하나가 된다. 포함 관계와
        // shadow는 따로 검사한다(8.4절).
        string key = Fingerprints.Strings([.. common.Where(argument => !argument.StartsWith("/I", StringComparison.Ordinal) &&
            !argument.StartsWith("-I", StringComparison.Ordinal)), "prefix", prefixContent, "header", headerSpelling])[..VariantHexLength];
        string directory = Path.Combine(output, DirectoryName, provider, key);
        string pch = Path.Combine(directory, provider + ".pch");
        string record = pch + DependencyRecord.Extension;
        string id = provider + ":pch:" + key;
        var files = new List<PlannedFile>();
        List<string> arguments = [.. common, .. Forced(prefix)];
        string[] outputs;
        string[] inputs;
        string[] use;
        if (windows)
        {
            string stub = Path.Combine(directory, provider + ".Pch.cpp");
            files.Add(new(stub, StubContent));
            arguments.AddRange(["/FI" + header, "/Yc" + header, "/Fp{OUTPUT0}", "-Xclang", "-fno-pch-timestamp", .. depfile,
                "/c", "/TP", stub, "/Fo{OUTPUT1}"]);
            outputs = [pch, Path.Combine(directory, provider + ".Pch.obj"), record];
            inputs = prefix is null ? [stub, header] : [stub, header, prefix];
            use = [.. Forced(prefix), "/FI" + header, "/Yu" + header, "/Fp" + pch, .. Forced(extra)];
        }
        else
        {
            arguments.AddRange(["-Xclang", "-fno-pch-timestamp", "-fpch-instantiate-templates", .. depfile, "-x", "c++-header", header,
                "-o", "{OUTPUT0}"]);
            outputs = [pch, record];
            inputs = prefix is null ? [header] : [header, prefix];
            use = ["-include-pch", pch, .. Forced(extra)];
        }

        var action = new NativeAction(id, provider, "Pch", request.Toolchain.CompilerPath, arguments, outputs, inputs, headers, extraInputs, [],
            [request.ContextFingerprint, request.Configuration.ToString(), optimization.ToString(), "pch", header], header,
            DependencyRecord: record);
        string[] logicalFiles = new[] { prefix, header, extra }.OfType<string>().ToArray();
        return new(action, files, directory, use, [.. Forced(prefix), .. Forced(header), .. Forced(extra)], logicalFiles,
            new[] { pch, prefix, extra }.OfType<string>().ToArray());
    }
}

/// <summary>
/// 작업 파일 분리(Docs/Design/UnityBuildPch.ko.md 7.2절)에서 묶음에서 뺄 소스를 정한다: 자신이 작업 파일인 소스, 그리고 짝 헤더(첫
/// <c>#include</c>)가 작업 파일이고 그 헤더 이름이 모듈 안에서 유일한 소스다.
/// </summary>
internal static class AdaptiveUnity
{
    public static HashSet<string> Separated(IReadOnlyList<string> candidates, IReadOnlySet<string> working, IEnumerable<string> moduleDirectories,
        string output, string root)
    {
        var separated = new HashSet<string>(NativeToolchains.PathComparer);
        bool workingHeaders = working.Any(path => Fingerprints.HeaderExtensions.Contains(Path.GetExtension(path)) &&
            !Path.GetExtension(path).Equals(".c", StringComparison.Ordinal));
        Dictionary<string, List<string>>? headersByName = null;
        foreach (string source in candidates)
        {
            if (working.Contains(source))
            {
                separated.Add(source);
                continue;
            }

            if (!workingHeaders || FirstIncludeName(File.ReadAllText(source)) is not string name)
            {
                continue;
            }

            if (headersByName is null)
            {
                headersByName = new(NativeToolchains.PathComparer);
                foreach (string directory in moduleDirectories.Distinct(NativeToolchains.PathComparer).Where(Directory.Exists))
                {
                    foreach (string header in Fingerprints.TreeFiles(directory, true, output, root))
                    {
                        if (!headersByName.TryGetValue(Path.GetFileName(header), out List<string>? paths))
                        {
                            headersByName[Path.GetFileName(header)] = paths = [];
                        }

                        if (!paths.Contains(header, NativeToolchains.PathComparer))
                        {
                            paths.Add(header);
                        }
                    }
                }
            }

            if (headersByName.TryGetValue(name, out List<string>? found) && found.Count == 1 && working.Contains(found[0]))
            {
                separated.Add(source);
            }
        }

        return separated;
    }

    /// <summary>첫 <c>#include</c>가 가리키는 파일 이름이다(디렉터리 부분 제외). include가 없으면 null이다.</summary>
    internal static string? FirstIncludeName(string text)
    {
        int index = 0;
        while (index < text.Length)
        {
            int lineEnd = text.IndexOf('\n', index);
            lineEnd = lineEnd < 0 ? text.Length : lineEnd;
            ReadOnlySpan<char> line = text.AsSpan(index, lineEnd - index).Trim();
            if (line.StartsWith("/*", StringComparison.Ordinal))
            {
                int close = text.IndexOf("*/", index, StringComparison.Ordinal);
                if (close < 0)
                {
                    return null;
                }

                index = close + 2;
                continue;
            }

            if (line.Length != 0 && line[0] == '#')
            {
                ReadOnlySpan<char> directive = line[1..].TrimStart();
                if (directive.StartsWith("include", StringComparison.Ordinal))
                {
                    ReadOnlySpan<char> rest = directive["include".Length..].TrimStart();
                    if (rest.Length > 2 && rest[0] is '"' or '<')
                    {
                        int end = rest[1..].IndexOfAny('"', '>');
                        return end < 0 ? null : Path.GetFileName(rest.Slice(1, end).ToString());
                    }

                    return null;
                }
            }

            index = lineEnd + 1;
        }

        return null;
    }
}
