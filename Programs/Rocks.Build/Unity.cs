using System.Buffers.Binary;
using System.Security.Cryptography;
using System.Text;

namespace Rocks.Build;

/// <summary>
/// 모듈 규칙의 유니티 빌드 설정이다(Docs/Design/UnityBuildPch.ko.md 6.1절). <see cref="Default"/>는 빌드의 기본값을 따른다
/// (<see cref="UnityBuild.DefaultOn"/> — 외부 라이브러리 모듈은 언제나 끔). <see cref="On"/>은 이 모듈의 C++ 소스를 묶고,
/// <see cref="Off"/>는 묶지 않는다. 빌드 전체를 끄는 것은 요청의 <see cref="NativeBuildRequest.Unity"/>(명령 옵션 <c>--unity off</c>)다.
/// </summary>
public enum UnityMode
{
    Default,
    On,
    Off
}

/// <summary>
/// 빌드 밖의 도구(정책 검사)가 쓰는 유니티 판정이다. 빌드와 같은 규칙을 쓰도록 여기서 내보낸다.
/// </summary>
public static class UnityRules
{
    /// <summary>
    /// 모듈 규칙이 이 모듈의 손으로 쓴 C++ 소스를 묶게 하는가(요청의 <c>--unity</c>와 무관한 모듈 설정이다). 이런 모듈이 묶음 충돌 정책
    /// 검사의 대상이다(Docs/Design/UnityBuildPch.ko.md 9.2절).
    /// </summary>
    public static bool ModuleEnabled(NativeModuleInput module) =>
        module.Unity == UnityMode.On || (module.Unity == UnityMode.Default && UnityBuild.DefaultOn && !module.ThirdParty);

    /// <summary>첫 <c>#include</c> 앞에 <c>#define</c>이 있는가(그런 파일은 묶지 않는다 — 6.1절).</summary>
    public static bool DefinesBeforeFirstInclude(string text) => UnityBuild.DefinesBeforeFirstInclude(text);
}

/// <summary>
/// 묶음 번역 단위 하나다. File은 묶음 파일(<c>&lt;out&gt;/Unity/&lt;모듈&gt;/&lt;모듈&gt;.Unity.&lt;id&gt;.cpp</c>), Content는 그 내용, Members는
/// 구성원 소스(묶음 안 순서), IncludeRoots는 구성원 철자를 푸는 include 루트다(묶음 TU에만, include 목록 맨 뒤에 붙인다).
/// </summary>
internal sealed record UnityBatch(string File, string Content, IReadOnlyList<string> Members, IReadOnlyList<string> IncludeRoots);

/// <summary>후보 소스 한 무리의 묶음 구성이다. Singles는 묶지 않고 단독 번역 단위로 컴파일하는 소스다.</summary>
internal sealed record UnityGroupPlan(IReadOnlyList<UnityBatch> Batches, IReadOnlyList<string> Singles);

/// <summary>
/// 유니티 묶음의 구성을 정한다(Docs/Design/UnityBuildPch.ko.md 6절). 구성은 후보 목록·경로·크기만의 함수다(결정적).
/// <list type="number">
/// <item>후보를 루트 기준 상대 경로(<c>/</c> 구분, 대소문자 보존)의 ordinal 순서로 정렬한다. 출력 디렉터리 아래 파일(리플렉션 생성
/// 소스)은 출력 기준 상대 경로를 쓴다 — 출력 폴더 이름이 구성에 섞이지 않는다.</item>
/// <item>경로 해시(SHA-256 앞 8 byte)를 구간 기대 파일 수로 나눈 나머지가 0인 파일 앞에서 새 구간을 시작한다. 간격은 고정값이라 파일
/// 하나의 추가·삭제·편집이 그 구간(anchor면 두 구간)만 바꾼다.</item>
/// <item>구간의 실제 바이트 합이 상한을 넘으면 구간을 ⌈합 ÷ 상한⌉개로 파일 수 기준 균등 분할한다(앞쪽 몫이 하나 많다).</item>
/// <item>구성원이 하나뿐이면 묶음 파일 없이 단독 번역 단위다.</item>
/// </list>
/// 묶음 파일의 이름은 순번이 아니라 첫 구성원 경로 해시의 앞 12자리 hex다(앞 묶음이 생기거나 사라져도 밀리지 않는다).
/// </summary>
internal static class UnityBuild
{
    /// <summary>묶음 하나의 구성원 바이트 합 상한 기본값이다(UE NumIncludedBytesPerUnityCPP와 같다).</summary>
    public const int DefaultBatchBytes = 384 * 1024;

    /// <summary>구간의 기대 파일 수 기본값이다(경로 해시를 이 값으로 나눈 나머지가 0인 파일이 구간을 연다).</summary>
    public const int DefaultAnchorFiles = 16;

    /// <summary>묶음 파일을 두는 출력 아래 디렉터리 이름이다.</summary>
    public const string DirectoryName = "Unity";

    /// <summary>
    /// <see cref="UnityMode.Default"/>인 모듈을 묶는가. 기본은 끔이다(UB6 결정, 9.3절): 켠 모듈은 묶음 충돌 정책 검사의 대상이므로,
    /// 충돌을 정리해 검사를 통과한 모듈만 규칙에서 <see cref="UnityMode.On"/>으로 켠다. 게임 모듈도 같다.
    /// </summary>
    internal const bool DefaultOn = false;

    // 묶음 파일 이름에 쓰는 경로 해시 hex 자릿수다.
    private const int IdHexLength = 12;

    // anchor 판정에 쓰는 경로 해시의 앞 byte 수다.
    private const int AnchorHashBytes = 8;

    private const string Header = "// Generated by Rocks.Build. Do not edit.";

    /// <summary>이 모듈의 손으로 쓴 C++ 소스를 묶는가(요청이 유니티를 켰고 모듈 설정이 허용한다).</summary>
    public static bool Enabled(NativeBuildRequest request, NativeModuleInput module) => request.Unity && UnityRules.ModuleEnabled(module);

    public static string DirectoryOf(string output, string module) => Path.Combine(output, DirectoryName, module);

    /// <summary>
    /// 구성원 철자다: 출력 디렉터리 아래면 출력 기준, 아니면 루트 기준 상대 경로(<c>/</c> 구분)와 그 기준 디렉터리다. 둘 다 아니면
    /// null이고 그 소스는 묶지 않는다(묶음 파일이 호스트 경로를 담지 않는다).
    /// </summary>
    public static (string Key, string Base)? Spelling(string source, string root, string output)
    {
        foreach (string directory in new[] { output, root })
        {
            string relative = Path.GetRelativePath(directory, source);
            if (!Path.IsPathRooted(relative) && relative != ".." && !relative.StartsWith(".." + Path.DirectorySeparatorChar, StringComparison.Ordinal) &&
                !relative.StartsWith("../", StringComparison.Ordinal))
            {
                return (relative.Replace('\\', '/'), directory);
            }
        }

        return null;
    }

    /// <summary>
    /// candidates의 묶음 구성이다. 경계는 candidates 전체로 정하고, separated(작업 파일 분리 — 7.2절)에 든 소스는 그 뒤 구성원에서만
    /// 빼서 단독 번역 단위로 돌린다(그 파일이 속한 묶음 하나만 바뀐다). sizeOf는 소스의 실제 바이트 수다.
    /// </summary>
    public static UnityGroupPlan Plan(string module, IReadOnlyList<string> candidates, string root, string output, int anchorFiles, int batchBytes,
        Func<string, long> sizeOf, IReadOnlySet<string>? separated = null)
    {
        ArgumentOutOfRangeException.ThrowIfLessThan(anchorFiles, 1);
        ArgumentOutOfRangeException.ThrowIfLessThan(batchBytes, 1);
        var singles = new List<string>();
        var items = new List<(string Source, string Key, string Base, long Size)>();
        foreach (string source in candidates)
        {
            long size = sizeOf(source);
            if (size > batchBytes || Spelling(source, root, output) is not (string key, string directory))
            {
                singles.Add(source);
                continue;
            }

            items.Add((source, key, directory, size));
        }

        items.Sort((left, right) => string.CompareOrdinal(left.Key, right.Key));
        var segments = new List<List<(string Source, string Key, string Base, long Size)>>();
        foreach (var item in items)
        {
            if (segments.Count == 0 || IsAnchor(item.Key, anchorFiles))
            {
                segments.Add([]);
            }

            segments[^1].Add(item);
        }

        var batches = new List<UnityBatch>();
        foreach (var segment in segments)
        {
            long bytes = segment.Sum(item => item.Size);
            int pieces = bytes > batchBytes ? checked((int)((bytes + batchBytes - 1) / batchBytes)) : 1;
            int start = 0;
            for (int piece = 0; piece < pieces; ++piece)
            {
                int count = segment.Count / pieces + (piece < segment.Count % pieces ? 1 : 0);
                var members = segment.GetRange(start, count).Where(item => separated is null || !separated.Contains(item.Source)).ToList();
                singles.AddRange(segment.GetRange(start, count).Where(item => separated is not null && separated.Contains(item.Source)).Select(item => item.Source));
                start += count;
                if (members.Count == 0)
                {
                    continue;
                }

                if (members.Count == 1)
                {
                    singles.Add(members[0].Source);
                    continue;
                }

                string file = Path.Combine(DirectoryOf(output, module), module + ".Unity." + PathHash(members[0].Key)[..IdHexLength] + ".cpp");
                var content = new StringBuilder(Header).Append('\n');
                foreach (var member in members)
                {
                    content.Append("#include \"").Append(member.Key).Append("\"\n");
                }

                batches.Add(new(file, content.ToString(), members.Select(member => member.Source).ToArray(),
                    members.Select(member => member.Base).Distinct(NativeToolchains.PathComparer).ToArray()));
            }
        }

        return new(batches, singles);
    }

    /// <summary>
    /// 첫 <c>#include</c> 앞에 <c>#define</c>이 있는가(6.1절 — 그런 파일은 헤더 처리 방식을 바꾸는 설정을 하므로 묶으면 조용히 무효가
    /// 된다. 단독 번역 단위로 빼고 PCH도 쓰지 않는다). 토큰 단위 근사다: 주석·문자열·raw 문자열을 건너뛰고, 전처리 조건 안의
    /// <c>#define</c>도 센다. include가 없는 파일은 거짓이다.
    /// </summary>
    public static bool DefinesBeforeFirstInclude(string text)
    {
        bool lineStart = true;
        bool defined = false;
        int index = 0;
        while (index < text.Length)
        {
            char value = text[index];
            if (value == '\n')
            {
                lineStart = true;
                ++index;
            }
            else if (value is ' ' or '\t' or '\r' or '\f' or '\v')
            {
                ++index;
            }
            else if (value == '/' && index + 1 < text.Length && text[index + 1] == '/')
            {
                index = SkipLine(text, index);
            }
            else if (value == '/' && index + 1 < text.Length && text[index + 1] == '*')
            {
                int end = text.IndexOf("*/", index + 2, StringComparison.Ordinal);
                index = end < 0 ? text.Length : end + 2;
            }
            else if (value == '#' && lineStart)
            {
                int name = index + 1;
                while (name < text.Length && text[name] is ' ' or '\t')
                {
                    ++name;
                }

                int nameEnd = name;
                while (nameEnd < text.Length && (char.IsAsciiLetterOrDigit(text[nameEnd]) || text[nameEnd] == '_'))
                {
                    ++nameEnd;
                }

                string directive = text[name..nameEnd];
                if (directive is "include" or "include_next" or "import")
                {
                    return defined;
                }

                defined = defined || directive == "define";

                index = SkipLine(text, nameEnd);
            }
            else if (value == 'R' && index + 1 < text.Length && text[index + 1] == '"')
            {
                // raw 문자열 R"구분자( … )구분자": 안의 줄 시작 '#'을 지시문으로 읽지 않는다.
                int open = text.IndexOf('(', index + 2);
                if (open < 0)
                {
                    break;
                }

                string close = ")" + text[(index + 2)..open] + "\"";
                int end = text.IndexOf(close, open + 1, StringComparison.Ordinal);
                index = end < 0 ? text.Length : end + close.Length;
                lineStart = false;
            }
            else if (value is '"' or '\'')
            {
                index = SkipLiteral(text, index);
                lineStart = false;
            }
            else
            {
                lineStart = false;
                ++index;
            }
        }

        return false;
    }

    // 줄 끝(줄 이음 '\' 뒤 줄 포함)의 다음 위치다. 줄바꿈 문자는 남겨 둔다(호출자가 줄 시작 상태를 갱신한다).
    private static int SkipLine(string text, int index)
    {
        while (index < text.Length && text[index] != '\n')
        {
            if (text[index] == '\\' && index + 1 < text.Length && (text[index + 1] == '\n' ||
                    (text[index + 1] == '\r' && index + 2 < text.Length && text[index + 2] == '\n')))
            {
                index += text[index + 1] == '\n' ? 2 : 3;
                continue;
            }

            ++index;
        }

        return index;
    }

    // 문자열·문자 리터럴의 닫는 따옴표 다음 위치다. 닫히지 않으면 그 줄 끝이다.
    private static int SkipLiteral(string text, int index)
    {
        char quote = text[index];
        ++index;
        while (index < text.Length && text[index] != '\n')
        {
            if (text[index] == '\\')
            {
                index += 2;
                continue;
            }

            if (text[index] == quote)
            {
                return index + 1;
            }

            ++index;
        }

        return Math.Min(index, text.Length);
    }

    private static string PathHash(string key) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(key)));

    private static bool IsAnchor(string key, int anchorFiles) =>
        BinaryPrimitives.ReadUInt64BigEndian(SHA256.HashData(Encoding.UTF8.GetBytes(key)).AsSpan(0, AnchorHashBytes)) % (ulong)anchorFiles == 0;
}
