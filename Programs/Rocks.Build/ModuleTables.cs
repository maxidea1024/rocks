using System.Globalization;
using System.Text;
using Rocks.Build.Descriptors;

namespace Rocks.Build;

/// <summary>
/// 실행 파일마다 모듈 표 TU를 만든다(Docs/Design/ModuleLoader.ko.md 3.2절, Monolithic manifest). 모듈 표 제공 모듈
/// (<see cref="NativeModuleInput.ProvidesModuleTable"/>, 엔진 Core)에 닿는 실행 파일마다 <c>&lt;실행 파일&gt;.ModuleTable.cpp</c>를
/// 그 실행 파일의 생성 소스(<see cref="NativeModuleInput.GeneratedSources"/>)로 더한다. 표는 실행 파일 도달 집합의 진입점 모듈(<see
/// cref="EntryModules"/>)을 의존 순서로 나열하고 행마다 의존 이름·로딩 단계를 싣는다. 모든 <c>RocksModuleEntry_&lt;이름&gt;</c>을 직접
/// 참조하므로 <c>ROCKS_IMPLEMENT_MODULE</c>이 빠진 모듈은 링크 오류다(정적 라이브러리에서 진입점 object가 빠지지도 않는다).
/// 내용은 호스트 경로를 담지 않고, 같은 입력이면 같은 byte다(내용이 같으면 다시 컴파일하지 않는다).
/// </summary>
public static class ModuleTables
{
    /// <summary>생성 TU 파일 이름의 접미사다(<c>&lt;실행 파일&gt;.ModuleTable.cpp</c>).</summary>
    public const string FileSuffix = ".ModuleTable.cpp";

    /// <summary>Modular 호스트 실행 파일의 생성 진입 TU 파일 이름 접미사다(<c>&lt;실행 파일 모듈&gt;.Launcher.cpp</c>, 생성 소스 폴더).</summary>
    public const string LauncherSuffix = ".Launcher.cpp";

    /// <summary>Launch가 export하는 Modular 진입 함수다(좁은 문자 — POSIX <c>main</c>, Docs/Design/ModuleLoader.ko.md 3.14절).</summary>
    public const string ModularLaunchSymbol = "RocksLaunchModularApplication";

    /// <summary>Launch가 export하는 Modular 넓은 문자 진입 함수다(Windows 콘솔 <c>wmain</c>).</summary>
    public const string ModularWideLaunchSymbol = "RocksLaunchModularWideApplication";

    /// <summary>Launch가 export하는 Modular 창 실행 파일 진입 함수다(Windows <c>wWinMain</c>).</summary>
    public const string ModularWindowedLaunchSymbol = "RocksLaunchModularWindowedApplication";

    /// <summary>
    /// Modular 호스트 실행 파일의 진입 TU 내용이다(Docs/Design/ModuleLoader.ko.md 3.14절 ML4b). 헤더를 include하지 않고 Launch의 C 함수를
    /// 선언해 플랫폼 진입 함수에서 manifest 파일 이름과 함께 부른다: Windows 콘솔 <c>wmain</c>, Windows 창 <c>wWinMain</c>, POSIX <c>main</c>
    /// (창 subsystem도 콘솔과 같다 — Launch/EntryPoint.h와 같은 규칙). 호스트 경로를 담지 않아 같은 입력이면 같은 byte다.
    /// </summary>
    public static string LauncherSource(string executable, string manifestFile, NativePlatform platform, WindowsSubsystem subsystem)
    {
        if (manifestFile.Any(character => character is '"' or '\\' || char.IsControl(character)))
        {
            throw new ArgumentException($"Module manifest file name '{manifestFile}' cannot be written into a C string literal.");
        }

        var text = new StringBuilder();
        text.Append("// Generated by Rocks.Build for the Modular executable ").Append(executable).Append(". Do not edit.\n");
        text.Append("// The executable imports only Launch; Launch loads the module manifest and runs the host module ").Append(executable)
            .Append(" (Docs/Design/ModuleLoader.ko.md section 3.14).\n");
        if (platform != NativePlatform.Windows)
        {
            text.Append("extern \"C\" int ").Append(ModularLaunchSymbol).Append("(int argc, char** argv, const char* manifest) noexcept;\n\n");
            text.Append("int main(int argc, char** argv) {\n    return ").Append(ModularLaunchSymbol).Append("(argc, argv, \"")
                .Append(manifestFile).Append("\");\n}\n");
        }
        else if (subsystem == WindowsSubsystem.Windows)
        {
            text.Append("extern \"C\" __declspec(dllimport) int ").Append(ModularWindowedLaunchSymbol).Append("(const char* manifest) noexcept;\n\n");
            text.Append("extern \"C\" int __stdcall wWinMain(struct HINSTANCE__*, struct HINSTANCE__*, wchar_t*, int) {\n    return ")
                .Append(ModularWindowedLaunchSymbol).Append("(\"").Append(manifestFile).Append("\");\n}\n");
        }
        else
        {
            text.Append("extern \"C\" __declspec(dllimport) int ").Append(ModularWideLaunchSymbol)
                .Append("(int argc, wchar_t** argv, const char* manifest) noexcept;\n\n");
            text.Append("int wmain(int argc, wchar_t** argv) {\n    return ").Append(ModularWideLaunchSymbol).Append("(argc, argv, \"")
                .Append(manifestFile).Append("\");\n}\n");
        }

        return text.ToString();
    }

    /// <summary>빌드가 진입점 모듈의 소스에 정의하는 모듈 이름 매크로다. 규칙·명령줄은 정의할 수 없다(InputValidation).</summary>
    public const string ModuleNameMacro = "ROCKS_MODULE_NAME";

    /// <summary>
    /// 빌드가 진입점 모듈의 소스에 정의하는 자기 타입 표지 매크로다(Docs/Design/ModuleLoader.ko.md 3.10절). 리플렉션 생성 소스(<see
    /// cref="NativeModuleInput.ReflectionSources"/>)가 있으면 1이고, <c>ROCKS_IMPLEMENT_MODULE</c>이 진입 기술의 registerTypes에
    /// 메타 컴파일러가 모듈 생성 소스에 정의한 <c>RegisterModuleOwnTypes</c>를 싣는다. 없으면 0이다. 규칙·명령줄은 정의할 수 없다.
    /// </summary>
    public const string ModuleTypesMacro = "ROCKS_MODULE_TYPES";

    /// <summary>
    /// 빌드가 진입점 모듈의 소스에 정의하는 공유 라이브러리 표지 매크로다(Docs/Design/BuildTargets.ko.md 3.8절 BS8d1). Modular에서 공유
    /// 라이브러리로 컴파일하는 모듈이면 1이고 <c>ROCKS_IMPLEMENT_MODULE</c>이 export 진입점 <c>RocksModuleEntry()</c>를 더 정의한다. 실행
    /// 파일·Monolithic은 0이다. 규칙·명령줄은 정의할 수 없다.
    /// </summary>
    public const string SharedLibraryMacro = "ROCKS_MODULE_SHARED_LIBRARY";

    /// <summary>공유 라이브러리마다 하나뿐인 export 진입점 기호 이름이다(C 링크, Docs/Design/ModuleLoader.ko.md 3.2절).</summary>
    public const string ExportedEntrySymbol = "RocksModuleEntry";

    /// <summary>
    /// 진입점 매크로가 export 진입점과 같은 자리에 정의하는 export하지 않는 모듈별 C 기호의 접두사다(<c>RocksModuleEntryOf_&lt;이름&gt;</c>).
    /// 빌드는 공유 라이브러리 링크에 이 기호를 강제 참조로 넣는다. export 진입점 이름은 의존 모듈의 import 라이브러리도 내므로 그 이름의 강제
    /// 참조로는 매크로 빠짐을 잡지 못한다(Docs/Design/BuildTargets.ko.md 3.8절 BS8d1).
    /// </summary>
    public const string EntryAnchorPrefix = "RocksModuleEntryOf_";

    /// <summary>
    /// 진입점(<c>ROCKS_IMPLEMENT_MODULE</c>)을 가져야 하는 모듈 이름 집합이다(대소문자 무시 비교). 서드파티가 아니고, C++ 코드(소스·규칙
    /// 생성 소스·리플렉션 생성 소스·설치 SDK의 미리 빌드한 라이브러리)가 있으며, 도달 집합에 모듈 표 제공 모듈이 있는 모듈이다.
    /// header-only 모듈과 Core 아래 모듈(PlatformBase 등)은 빠진다(3.1절 면제). 이름을 모르는 의존은 건너뛴다(그 오류는 액션 그래프가 알린다).
    /// 손으로 쓴 소스 없이 리플렉션 헤더만 가진 메타데이터 모듈(ReflectionTestFixtures·CoreTypeBindings 등)도 진입점 모듈이다 — 모듈
    /// 로더가 그 모듈의 타입을 등록하려면 진입 기술이 있어야 한다(Docs/Design/ModuleLoader.ko.md 3.10절, GSD14 면제를 거둠). 그런 모듈의
    /// 진입점 TU는 메타데이터 배치(MetadataLayout)가 생성 소스로 더한다.
    /// </summary>
    public static HashSet<string> EntryModules(IReadOnlyDictionary<string, NativeModuleInput> modules)
    {
        var reachesProvider = new Dictionary<string, bool>(StringComparer.OrdinalIgnoreCase);
        var visiting = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        bool Reaches(string name)
        {
            if (reachesProvider.TryGetValue(name, out bool known))
            {
                return known;
            }

            // 순환은 액션 그래프가 거부한다. 여기서는 끝없이 돌지 않게만 한다.
            if (!modules.TryGetValue(name, out NativeModuleInput? module) || !visiting.Add(name))
            {
                return false;
            }

            bool reaches = module.ProvidesModuleTable;
            foreach (string dependency in module.AllDependencies)
            {
                reaches |= Reaches(dependency);
            }

            visiting.Remove(name);
            reachesProvider[name] = reaches;
            return reaches;
        }

        var entries = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (NativeModuleInput module in modules.Values)
        {
            bool hasCode = module.Sources.Count != 0 || module.GeneratedSources.Count != 0 ||
                module.ReflectionSources.Count != 0 || module.PrebuiltLibraries.Count != 0;
            if (!module.ThirdParty && hasCode && Reaches(module.Name))
            {
                entries.Add(module.Name);
            }
        }

        return entries;
    }

    /// <summary>
    /// 모듈 표가 필요한 실행 파일에 생성 TU를 더한 요청을 돌려준다. 대상(<see cref="NativeBuildRequest.Targets"/>, 비면 전부)에서 닿는
    /// 실행 파일만 본다. 진입점 모듈 이름이 C 식별자가 아니면 <see cref="ArgumentException"/>이다(기호 이름을 만든다).
    /// </summary>
    public static NativeBuildRequest Add(NativeBuildRequest request)
    {
        var modules = new Dictionary<string, NativeModuleInput>(StringComparer.OrdinalIgnoreCase);
        foreach (NativeModuleInput module in request.Modules)
        {
            // 이름 중복은 InputValidation·액션 그래프가 거부한다. 여기서는 첫 것만 쓴다.
            modules.TryAdd(module.Name, module);
        }

        if (!modules.Values.Any(module => module.ProvidesModuleTable))
        {
            return request;
        }

        HashSet<string> entries = EntryModules(modules);
        // 실행 중 적재 모듈은 로더가 Load(이름)로 찾으므로 모듈 표에 행이 있어야 한다(진입점 모듈). header-only·서드파티·Core 아래 모듈과
        // 표 제공 모듈에 닿지 않는 모듈은 행이 없어 적재할 수 없으므로 거부한다(Docs/Design/ModuleLoader.ko.md 3.8절).
        foreach (NativeModuleInput module in modules.Values)
        {
            foreach (string dynamic in module.DynamicModules)
            {
                if (modules.ContainsKey(dynamic) && !entries.Contains(dynamic))
                {
                    throw new ArgumentException($"Module {module.Name}, DynamicModules: '{dynamic}' cannot be loaded at run time because it has no " +
                        "module entry point (header-only, third-party, below the module table provider, or not reaching it).");
                }
            }
        }

        ValidateBootModules(modules, entries);
        var tables = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (string executable in TableExecutables(request, modules, entries))
        {
            // Modular는 표 TU 대신 같은 행을 manifest에 쓴다(Docs/Design/BuildTargets.ko.md 3.8절 BS8d1 — ModuleManifests). 행 검사(이름·
            // 단계 순서)는 같게 한다.
            if (request.LinkType == NativeLinkType.Modular)
            {
                _ = Rows(executable, modules, entries);
            }
            else
            {
                tables[executable] = Generate(executable, modules, entries);
            }
        }

        if (tables.Count == 0)
        {
            return request;
        }

        return request with
        {
            Modules = request.Modules.Select(module => tables.TryGetValue(module.Name, out string? content)
                ? module with { GeneratedSources = [.. module.GeneratedSources, new NativeGeneratedSource(module.Name + FileSuffix, content)] }
                : module).ToArray()
        };
    }

    /// <summary>
    /// 모듈 표(Monolithic TU·Modular manifest)를 가질 실행 파일 이름이다(요청 순서). 대상(<see cref="NativeBuildRequest.Targets"/>, 비면 전부)에서
    /// 닿는 실행 파일 가운데 진입점 모듈(모듈 표 제공 모듈에 닿는다)만이다. 동적 모듈은 실행 파일이 아니므로(입력 검사) 따라가도 늘지 않는다.
    /// </summary>
    internal static IEnumerable<string> TableExecutables(NativeBuildRequest request, IReadOnlyDictionary<string, NativeModuleInput> modules,
        HashSet<string> entries)
    {
        IEnumerable<string> roots = request.Targets.Count == 0 ? modules.Keys : request.Targets;
        HashSet<string> reachable = LinkClosure.Reachable(roots, modules);
        return request.Modules.Where(module => module.Kind == NativeModuleKind.Executable && entries.Contains(module.Name) &&
            reachable.Contains(module.Name)).Select(module => module.Name).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
    }

    /// <summary>
    /// 부트 모듈 검사다(Docs/Design/ModuleLoader.ko.md 3.11절, MD4). 공통 실행 진입점 표지(<see cref="NativeModuleInput.ProvidesLaunch"/>)를 켠
    /// 모듈의 링크 폐포에 든 진입점 모듈은 로더가 만들어진 직후 시작하므로 단계가 EarliestPossible이어야 한다. 빌드가 몰래 바꾸지 않고 규칙에
    /// 적게 하는 것은 단계 순서 검사(MD6)가 규칙 값으로 돌기 때문이다. 어기면 <see cref="ArgumentException"/>이다.
    /// </summary>
    internal static void ValidateBootModules(IReadOnlyDictionary<string, NativeModuleInput> modules, HashSet<string> entries)
    {
        foreach (NativeModuleInput launch in modules.Values.Where(module => module.ProvidesLaunch).OrderBy(module => module.Name, StringComparer.Ordinal))
        {
            List<string> closure = LinkClosure.Of(launch.Name, modules, out HashSet<string> onRequest);
            foreach (string name in closure.Append(launch.Name))
            {
                if (onRequest.Contains(name) || !modules.TryGetValue(name, out NativeModuleInput? module) || !entries.Contains(name))
                {
                    continue;
                }

                if (module.LoadingPhase != LoadingPhase.EarliestPossible)
                {
                    throw new ArgumentException($"Module {module.Name}: boot module (in the dependency closure of {launch.Name}) must use the " +
                        $"EarliestPossible loading phase, not {module.LoadingPhase} (Docs/Design/ModuleLoader.ko.md section 3.11).");
                }
            }
        }
    }

    /// <summary>
    /// 단계 순서 검사다(Docs/Design/ModuleLoader.ko.md MD6). 행의 의존(면제 모듈을 거친 대체 의존 포함)의 단계가 그 행보다 늦으면 단계
    /// 실행이 늦은 단계 모듈을 조용히 앞당기므로 거부한다. None 의존은 허용하고 None 행은 검사하지 않는다(코드가 Load로 시작한다).
    /// </summary>
    internal static void ValidatePhaseOrder(NativeModuleInput module, IReadOnlyDictionary<string, NativeModuleInput> modules, List<string> dependencies)
    {
        LoadingPhase phase = RowPhase(module);
        if (phase == LoadingPhase.None)
        {
            return;
        }

        foreach (string name in dependencies)
        {
            NativeModuleInput dependency = modules[name];
            LoadingPhase dependencyPhase = RowPhase(dependency);
            if (dependencyPhase != LoadingPhase.None && dependencyPhase > phase)
            {
                throw new ArgumentException($"Module {module.Name} (loading phase {phase}) depends on {dependency.Name} (loading phase " +
                    $"{dependencyPhase}); a dependency must not use a later loading phase (use the same or an earlier phase, None, or " +
                    "DynamicModules — Docs/Design/ModuleLoader.ko.md MD6).");
            }
        }
    }

    /// <summary>
    /// 모듈 표 행에 싣는 단계다. 실행 파일 모듈은 늘 None이다(Docs/Design/ModuleLoader.ko.md 3.11절): 본문은 이미 실행 중인 코드이고, 단계
    /// 실행이 실행 파일 행을 시작하면 그 의존(시험 fixture 같은 None 모듈 포함)을 모두 끌어 시작한다. UE에서도 Program의 주 모듈은 로딩 단계로
    /// 적재하지 않는다. 필요하면 본문이 Load(이름)로 시작한다.
    /// </summary>
    internal static LoadingPhase RowPhase(NativeModuleInput module) =>
        module.Kind == NativeModuleKind.Executable ? LoadingPhase.None : module.LoadingPhase;

    /// <summary>
    /// 실행 파일 <paramref name="executable"/>의 모듈 표 TU 내용이다. 행은 의존 우선 깊이 탐색의 후위 순서(의존 목록 순서대로)에서 진입점
    /// 모듈만 고른 것이고, 그 뒤에 실행 파일에 링크하는 켠 플러그인 모듈(PluginModules — 보통 행, Docs/Design/BuildTargets.ko.md 3.9절 BD36)과
    /// 실행 중 적재 모듈(DynamicModules) 쪽이 같은 규칙으로 붙으며 실행 파일이 마지막이다. 행의 의존은 직접
    /// 의존 가운데 진입점 모듈이며, 면제 모듈을 거치는 의존은 그 너머의 진입점 모듈로 바꿔 싣는다(중복 제거, 처음 만난 순서). 링크 폐포
    /// 밖에서 DynamicModules로만 든 행은 요청 시 적재 행(onRequest)이다 — 단계 실행이 건너뛴다(3.8·3.11절). 행마다 단계 순서를 검사한다(MD6).
    /// </summary>
    internal static string Generate(string executable, IReadOnlyDictionary<string, NativeModuleInput> modules, HashSet<string> entries)
    {
        IReadOnlyList<ModuleRow> rows = Rows(executable, modules, entries);
        var text = new StringBuilder();
        text.Append("// Generated by Rocks.Build. Do not edit.\n");
        text.Append(CultureInfo.InvariantCulture, $"// Module table of executable {executable} (Docs/Design/ModuleLoader.ko.md section 3.2): every C++ module\n");
        text.Append("// of the executable in dependency order with its direct dependencies, loading phase and on-request flag (a\n");
        text.Append("// module reached only through DynamicModules, skipped by phase start). Referencing every\n");
        text.Append("// RocksModuleEntry_<Name> makes a missing ROCKS_IMPLEMENT_MODULE a link error.\n");
        text.Append("#include <Core/Module/ModuleEntry.h>\n\n");
        foreach (ModuleRow row in rows)
        {
            text.Append(CultureInfo.InvariantCulture, $"const ::rocks::ModuleEntry& RocksModuleEntry_{row.Name}() noexcept;\n");
        }

        text.Append("\nnamespace {\n\n");
        foreach (ModuleRow row in rows.Where(row => row.Dependencies.Count != 0))
        {
            text.Append(CultureInfo.InvariantCulture, $"constexpr const char* RocksModuleDependencies_{row.Name}[] = {{");
            text.Append(string.Join(", ", row.Dependencies.Select(name => "\"" + name + "\"")));
            text.Append("};\n");
        }

        text.Append("\nconstexpr ::rocks::ModuleTableRow RocksModuleRows[] = {\n");
        foreach (ModuleRow row in rows)
        {
            string list = row.Dependencies.Count == 0 ? "nullptr" : "RocksModuleDependencies_" + row.Name;
            string requested = row.OnRequest ? "true" : "false";
            text.Append(CultureInfo.InvariantCulture,
                $"    {{\"{row.Name}\", &RocksModuleEntry_{row.Name}, {list}, {row.Dependencies.Count}, ::rocks::LoadingPhase::{row.Phase}, {requested}}},\n");
        }

        text.Append("};\n\n} // namespace\n\n");
        text.Append("::rocks::ModuleTable rocks::GeneratedModuleTable() noexcept {\n");
        text.Append("    return ::rocks::ModuleTable(RocksModuleRows);\n");
        text.Append("}\n");
        return text.ToString();
    }

    /// <summary>
    /// 실행 파일 <paramref name="executable"/>의 모듈 표 행이다(Monolithic 표 TU와 Modular manifest가 같은 행을 쓴다 — Docs/Design/BuildTargets.ko.md
    /// 3.8절 BS8d1). 실행 파일이 링크하는 모듈(링크 폐포 다음 동적 모듈 쪽 — LinkClosure)에서 진입점 모듈만 고르고 실행 파일을 끝에 둔다. 동적
    /// 모듈 행은 실행 파일 행 앞에 오며, 행의 의존은 링크 의존뿐이라 Load(실행 파일)가 동적 모듈을 시작하지 않는다(Docs/Design/ModuleLoader.ko.md
    /// 3.8절). 행 이름이 C 식별자가 아니거나 단계 순서(MD6)를 어기면 <see cref="ArgumentException"/>이다.
    /// </summary>
    internal static IReadOnlyList<ModuleRow> Rows(string executable, IReadOnlyDictionary<string, NativeModuleInput> modules, HashSet<string> entries)
    {
        var order = LinkClosure.Of(executable, modules, out HashSet<string> onRequest).Append(executable)
            .Where(name => modules.ContainsKey(name) && entries.Contains(name)).Select(name => modules[name]).ToList();
        foreach (NativeModuleInput module in order)
        {
            if (!IsIdentifier(module.Name))
            {
                throw new ArgumentException($"Module {module.Name}: a module with a module entry point (ROCKS_IMPLEMENT_MODULE) must have a C " +
                    "identifier name (letters, digits and '_', not starting with a digit).");
            }
        }

        var rows = new List<ModuleRow>();
        foreach (NativeModuleInput module in order)
        {
            List<string> direct = EntryDependencies(module, modules, entries);
            ValidatePhaseOrder(module, modules, direct);
            rows.Add(new(module.Name, direct, RowPhase(module), onRequest.Contains(module.Name), module.Kind == NativeModuleKind.Executable));
        }

        return rows;
    }

    // 직접 의존 가운데 진입점 모듈이다. 면제 모듈(header-only·서드파티·Core 아래)은 그 의존을 따라가 진입점 모듈로 바꾼다.
    private static List<string> EntryDependencies(NativeModuleInput module, IReadOnlyDictionary<string, NativeModuleInput> modules,
        HashSet<string> entries)
    {
        var result = new List<string>();
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        void Add(string name)
        {
            if (!modules.TryGetValue(name, out NativeModuleInput? dependency) || !seen.Add(name))
            {
                return;
            }

            if (entries.Contains(dependency.Name))
            {
                result.Add(dependency.Name);
                return;
            }

            foreach (string next in dependency.AllDependencies)
            {
                Add(next);
            }
        }

        foreach (string dependency in module.AllDependencies)
        {
            Add(dependency);
        }

        return result;
    }

    /// <summary>C 식별자(ASCII 영문자·숫자·'_', 숫자로 시작하지 않음)인지다.</summary>
    internal static bool IsIdentifier(string name) =>
        name.Length != 0 && !char.IsAsciiDigit(name[0]) && name.All(value => char.IsAsciiLetterOrDigit(value) || value == '_');
}

/// <summary>
/// 모듈 표 행 하나다(Docs/Design/ModuleLoader.ko.md 3.2·3.5절). Dependencies는 직접 의존 가운데 진입점 모듈(면제 모듈 너머 대체 포함),
/// OnRequest는 DynamicModules로만 든 행, Executable은 실행 파일 행이다.
/// </summary>
internal sealed record ModuleRow(string Name, IReadOnlyList<string> Dependencies, LoadingPhase Phase, bool OnRequest, bool Executable);
