using System.Text.Json;
using Rocks.Build;
using Rocks.Tooling.Common;

/// <summary>
/// 유니티 묶기(Docs/Design/UnityBuildPch.ko.md 6절, UB1)를 검사한다.
/// <list type="bullet">
/// <item>묶음 구성의 결정성: 같은 입력이면 같은 구성이고, 파일 추가·삭제·크기 변화가 그 구간만 바꾼다. 상한을 넘는 구간은 파일 수로
/// 균등 분할하고, 큰 파일·루트 밖 파일·구성원 하나는 단독 번역 단위다. 분리한 파일은 자기 묶음에서만 빠진다.</item>
/// <item>첫 <c>#include</c> 앞의 <c>#define</c> 판정(주석·문자열·raw 문자열·조건 지시문).</item>
/// <item>실제 빌드: 묶음 TU의 <c>__FILE__</c>이 단독 TU와 같고, C 소스·제외 지정·큰 파일·include 앞 <c>#define</c> 파일은 단독이며,
/// compile_commands.json은 원본 소스마다 논리 명령 하나다. 유니티 켬·끔의 도구 빌드 ID manifest가 같고, 변형 object 디렉터리가 서로를
/// 덮어쓰지 않으며, 이번 변형의 낡은 파일은 지워진다. 리플렉션 생성 소스는 기본으로 자기들끼리 묶인다.</item>
/// </list>
/// </summary>
internal static class UnityTests
{
    // 구성 시험의 후보 파일 수와 가짜 파일 크기(byte)다.
    private const int PlanFiles = 200;

    private const int PlanFileBytes = 12 * 1024;

    public static async Task RunAsync(NativeBuildRequest request, string root, Action<string> pass)
    {
        PlansAreDeterministicAndLocal(root);
        pass("unity batch planning: deterministic, local to one segment on add/remove/resize, even split above the byte limit, standalone rules");

        DetectsDefinesBeforeTheFirstInclude();
        pass("unity exclusion: #define before the first #include is detected through comments, strings and conditionals");

        await BuildsBatchesAsync(request, root);
        pass("unity build: __FILE__ as standalone, exclusions, logical compile commands, tool build ID independent of the mode, variant object directories, stale cleanup");

        await BatchesReflectionSourcesAsync(request, root);
        pass("unity build: reflection generated sources are batched among themselves by default");
    }

    private static void PlansAreDeterministicAndLocal(string root)
    {
        string source = Path.Combine(root, "unity-plan");
        string output = Path.Combine(source, "out");
        string[] files = Enumerable.Range(0, PlanFiles).Select(index => Path.Combine(source, "src", $"file_{index:000}.cpp")).ToArray();
        var sizes = files.ToDictionary(file => file, _ => (long)PlanFileBytes, StringComparer.Ordinal);
        Dictionary<string, string[]> Plan(IEnumerable<string> candidates, out string[] singles, int anchorFiles = UnityBuild.DefaultAnchorFiles,
            int batchBytes = UnityBuild.DefaultBatchBytes, IReadOnlySet<string>? separated = null)
        {
            UnityGroupPlan plan = UnityBuild.Plan("Probe", candidates.ToArray(), source, output, anchorFiles, batchBytes, file => sizes[file], separated);
            singles = plan.Singles.Order(StringComparer.Ordinal).ToArray();
            return plan.Batches.ToDictionary(batch => batch.File, batch => batch.Members.ToArray(), StringComparer.Ordinal);
        }

        int Differences(Dictionary<string, string[]> left, Dictionary<string, string[]> right) =>
            left.Count(pair => !right.TryGetValue(pair.Key, out string[]? members) || !members.SequenceEqual(pair.Value)) +
            right.Count(pair => !left.ContainsKey(pair.Key));

        Dictionary<string, string[]> baseline = Plan(files, out string[] baselineSingles);
        Check(baseline.Count > 1 && baseline.Values.Sum(members => members.Length) + baselineSingles.Length == PlanFiles,
            "every candidate must be in exactly one batch or standalone");
        Check(baseline.Values.All(members => members.Length >= 2 && members.Sum(member => sizes[member]) <= UnityBuild.DefaultBatchBytes),
            "batches have at least two members and stay under the byte limit");
        Check(Differences(baseline, Plan(files.Reverse(), out _)) == 0, "the composition must not depend on the candidate order");
        // 묶음 파일: 머리말과 루트 기준 include, 이름은 첫 구성원 경로 해시다(순번이 아니다).
        UnityBatch first = UnityBuild.Plan("Probe", files, source, output, UnityBuild.DefaultAnchorFiles, UnityBuild.DefaultBatchBytes, file => sizes[file]).Batches[0];
        Check(first.Content.StartsWith("// Generated by Rocks.Build. Do not edit.\n#include \"src/file_", StringComparison.Ordinal) &&
            !first.Content.Contains('\\') && !first.Content.Contains(source, StringComparison.Ordinal) &&
            first.Content.Split('\n', StringSplitOptions.RemoveEmptyEntries).Length == first.Members.Count + 1 &&
            first.IncludeRoots.SequenceEqual([source]) &&
            Path.GetDirectoryName(first.File) == Path.Combine(output, "Unity", "Probe") &&
            System.Text.RegularExpressions.Regex.IsMatch(Path.GetFileName(first.File), "^Probe\\.Unity\\.[0-9a-f]{12}\\.cpp$"),
            "unity batch file layout: " + first.File + "\n" + first.Content);

        // 파일 하나를 더하거나 빼면 그 파일이 속한 구간만(anchor면 두 구간) 바뀐다.
        string added = Path.Combine(source, "src", "file_077_added.cpp");
        sizes[added] = PlanFileBytes;
        int addedDifferences = Differences(baseline, Plan(files.Append(added), out _));
        Check(addedDifferences is >= 1 and <= 4, $"adding a file changed {addedDifferences} batch entries");
        int removedDifferences = Differences(baseline, Plan(files.Where(file => file != files[101]), out _));
        Check(removedDifferences is >= 1 and <= 4, $"removing a file changed {removedDifferences} batch entries");
        // 크기가 늘어도 분할 수가 바뀌기 전까지 구성은 그대로다.
        sizes[files[50]] = PlanFileBytes * 2;
        Check(Differences(baseline, Plan(files, out _)) == 0, "a size change below the split threshold must keep the composition");
        sizes[files[50]] = PlanFileBytes;

        // 상한을 넘는 구간은 ⌈합 ÷ 상한⌉개로 파일 수 기준 균등 분할한다(앞쪽 몫이 하나 많다). anchor를 없애 한 구간으로 만든다.
        const int noAnchors = int.MaxValue;
        string[] ten = files[..10];
        Dictionary<string, string[]> split = Plan(ten, out string[] splitSingles, noAnchors, PlanFileBytes * 4);
        int[] counts = split.Values.Select(members => members.Length).OrderDescending().ToArray();
        Check(splitSingles.Length == 0 && counts.SequenceEqual([4, 3, 3]), "even split by file count: " + string.Join(",", counts));
        Check(Plan(ten, out _, noAnchors).Count == 1, "a segment under the limit is one batch");
        // 상한보다 큰 파일, 루트·출력 밖 파일, 구성원 하나뿐인 구간은 단독이다.
        sizes[files[3]] = UnityBuild.DefaultBatchBytes + 1;
        string outside = Path.Combine(root, "unity-plan-outside", "x.cpp");
        sizes[outside] = PlanFileBytes;
        Plan(ten.Append(outside), out string[] standalone, noAnchors);
        Check(standalone.SequenceEqual(new[] { files[3], outside }.Order(StringComparer.Ordinal)), "oversized and out-of-root files must be standalone");
        sizes[files[3]] = PlanFileBytes;
        Plan([files[0]], out string[] lone, noAnchors);
        Check(lone.SequenceEqual([files[0]]), "a single-member batch must be a standalone translation unit");
        // 분리(작업 파일): 경계는 전체 목록으로 정하고 그 파일만 자기 묶음에서 뺀다.
        Dictionary<string, string[]> separated = Plan(files, out string[] separatedSingles, separated: new HashSet<string> { files[101] });
        Check(separatedSingles.Contains(files[101]) && separated.Values.All(members => !members.Contains(files[101])) &&
            Differences(baseline, separated) is 1 or 2, "a separated file must only leave its own batch");
        // 출력 디렉터리 아래 소스(리플렉션 생성 소스)는 출력 기준 철자다(출력 폴더 이름이 구성에 섞이지 않는다).
        string[] generated = Enumerable.Range(0, 3).Select(index => Path.Combine(output, "Generated", "Probe", "Source", $"T{index}.generated.cpp")).ToArray();
        foreach (string file in generated)
        {
            sizes[file] = PlanFileBytes;
        }

        UnityBatch generatedBatch = UnityBuild.Plan("Probe", generated, source, output, noAnchors, UnityBuild.DefaultBatchBytes, file => sizes[file]).Batches.Single();
        Check(generatedBatch.Content.Contains("#include \"Generated/Probe/Source/T0.generated.cpp\"\n", StringComparison.Ordinal) &&
            generatedBatch.IncludeRoots.SequenceEqual([output]), "sources under the output directory must use output-relative spellings");
    }

    private static void DetectsDefinesBeforeTheFirstInclude()
    {
        foreach ((string text, bool expected) in new[]
        {
            ("#define _HAS_EXCEPTIONS 0\n#include <vector>\n", true),
            ("// comment\n/* block */ #  define X 1\n#include \"a.h\"\n", true),
            ("#if defined(_MSC_VER)\n#define X 1\n#endif\n#include <a.h>\n", true),
            ("#pragma once\n#define LONG \\\n    1\n#include <a.h>\n", true),
            ("#include <a.h>\n#define X 1\n", false),
            ("// #define X 1\n#include <a.h>\n", false),
            ("/* \n#define X 1\n*/\n#include <a.h>\n", false),
            ("const char* text = \"\\\n#define X 1\";\n#include <a.h>\n", false),
            ("const char* text = R\"raw(\n#define X 1\n)raw\";\n#include <a.h>\n", false),
            ("#pragma once\n#ifndef GUARD\n#endif\n#include <a.h>\n#define X\n", false),
            ("int value = 1'000; // not a character literal\n#include <a.h>\n#define X\n", false),
            ("#define X 1\nint value = X;\n", false),
            ("", false)
        })
        {
            Check(UnityBuild.DefinesBeforeFirstInclude(text) == expected, $"define-before-include detection must be {expected} for:\n{text}");
        }
    }

    private static async Task BuildsBatchesAsync(NativeBuildRequest request, string root)
    {
        string fixture = Directory.CreateDirectory(Path.Combine(root, "unity fixture")).FullName;
        string Write(string relative, string content)
        {
            string path = Path.GetFullPath(Path.Combine(fixture, relative));
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, content);
            return path;
        }

        string include = Directory.CreateDirectory(Path.Combine(fixture, "include")).FullName;
        Write("include/files.h", "#pragma once\nconst char* FileOf(int index) noexcept;\nextern \"C\" int CValue(void);\n");
        string[] members = Enumerable.Range(0, 5).Select(index => Write($"src/member{index}.cpp",
            $"#include <files.h>\nconst char* File{index}() noexcept {{ return __FILE__; }}\n")).ToArray();
        string dispatch = Write("src/dispatch.cpp", "#include <files.h>\n" +
            string.Concat(Enumerable.Range(0, 5).Select(index => $"const char* File{index}() noexcept;\n")) +
            "const char* Defined() noexcept;\nconst char* Excluded() noexcept;\nconst char* Big() noexcept;\n" +
            "const char* FileOf(int index) noexcept {\n    switch (index) {\n" +
            string.Concat(Enumerable.Range(0, 5).Select(index => $"    case {index}: return File{index}();\n")) +
            "    case 5: return Defined();\n    case 6: return Excluded();\n    case 7: return Big();\n    default: return \"\";\n    }\n}\n");
        // 묶지 않는 것: C 소스, 제외 지정, 첫 include 앞의 #define, 상한보다 큰 파일.
        string cSource = Write("src/value.c", "int CValue(void) { return 7; }\n");
        string defined = Write("src/defined.cpp", "#define ROCKS_UNITY_FIXTURE_SETTING 1\n#include <files.h>\nconst char* Defined() noexcept { return __FILE__; }\n");
        string excluded = Write("src/excluded.cpp", "#include <files.h>\nconst char* Excluded() noexcept { return __FILE__; }\n");
        string big = Write("src/big.cpp", "#include <files.h>\nconst char* Big() noexcept { return __FILE__; }\n" +
            new string('/', 2) + new string('x', UnityBuild.DefaultBatchBytes) + "\n");
        string main = Write("app/main.cpp", "#include <files.h>\n#include <stdio.h>\nint main() {\n    for (int index = 0; index < 8; ++index) {\n" +
            "        printf(\"%s\\n\", FileOf(index));\n    }\n    return CValue() == 7 ? 0 : 9;\n}\n");
        string[] librarySources = [.. members, dispatch, cSource, defined, excluded, big];
        NativeModuleInput library = new()
        {
            Name = "UnityLib",
            Sources = librarySources,
            PublicIncludeDirectories = [include],
            Unity = UnityMode.On,
            UnityExclude = [excluded],
            // 경로 해시 anchor를 없애 묶을 수 있는 소스 전부를 한 구간에 둔다.
            UnityAnchorFiles = int.MaxValue
        };
        NativeModuleInput application = new() { Name = "UnityApp", Kind = NativeModuleKind.Executable, Sources = [main], PublicDependencies = ["UnityLib"] };
        NativeBuildRequest unity = request with
        {
            RootDirectory = fixture,
            OutputDirectory = Path.Combine(fixture, "out"),
            Modules = [library, application],
            Targets = ["UnityApp"]
        };
        NativeBuildRequest standalone = unity with { Unity = false };
        var builder = new NativeBuildEngine();
        async Task<NativeBuildResult> Build(NativeBuildRequest input)
        {
            NativeBuildResult result = await builder.BuildAsync(input);
            Check(result.Succeeded, "unity fixture build failed: " + result.Failure + "\n" +
                string.Join("\n", result.Actions.Where(action => !action.Succeeded).Select(action => action.StdOut + action.StdErr)));
            return result;
        }

        async Task<string> Run(NativeBuildResult result)
        {
            if (request.Toolchain.Platform == NativePlatform.Android)
            {
                return "";
            }

            ProcessResult run = await ProcessRunner.RunAsync(new(result.ModuleOutputs["UnityApp"], [], fixture, request.Toolchain.Environment));
            Check(run.ExitCode == 0, "unity fixture executable failed: " + run.StdErr);
            return run.StdOut.Replace("\r", "", StringComparison.Ordinal);
        }

        // 구성: 묶을 수 있는 여섯(member0–4, dispatch)이 묶음 하나, 나머지 넷과 실행 파일 소스는 단독이다.
        NativePlan plan = ActionGraph.Create(unity);
        NativeAction[] libraryCompiles = plan.Actions.Where(action => action.Kind == "Compile" && action.Module == "UnityLib").ToArray();
        NativeAction batch = libraryCompiles.Single(action => action.Members is not null);
        Check(plan.UnityBatches.Count == 1 && batch.Members!.Order(StringComparer.Ordinal).SequenceEqual(members.Append(dispatch).Order(StringComparer.Ordinal)) &&
            libraryCompiles.Length == 5 && plan.UnityDefineExcluded.SequenceEqual([defined]),
            "unity composition: " + string.Join(", ", libraryCompiles.Select(action => action.Source)));
        string rootInclude = (request.Toolchain.Platform == NativePlatform.Windows ? "/I" : "-I") + fixture;
        Check(batch.Arguments.Contains(rootInclude) && batch.Inputs.Contains(batch.Source!) && members.All(batch.Inputs.Contains) &&
            members.All(batch.Identity.Contains) && Fingerprints.IsUnder(batch.Outputs[0], Path.Combine(unity.OutputDirectory, "obj", "UnityLib", "u1p1")) &&
            libraryCompiles.Where(action => action.Members is null).All(action => !action.Arguments.Contains(rootInclude)),
            "the batch action must add the root include last, key its members and use the variant object directory");
        Check(ActionGraph.Create(standalone).UnityBatches.Count == 0, "--unity off must not batch");

        NativeBuildResult cold = await Build(unity);
        Check(cold.UnityBatches == 1 && cold.UnityDefineExcluded.SequenceEqual([defined]), "the build result must report the batches and the define exclusions");
        string batchFile = plan.UnityBatches[0].File;
        Check(File.ReadAllText(batchFile) == plan.UnityBatches[0].Content, "the batch file must be written with the planned content");
        Check((await Build(unity)).ExecutedActions == 0, "an unchanged unity build must execute zero actions");

        // compile_commands.json: 원본 소스마다 논리 명령 하나(묶음 파일·묶음 전용 include·depfile 인자가 없다).
        using (JsonDocument database = JsonDocument.Parse(File.ReadAllText(cold.CompilationDatabasePath)))
        {
            JsonElement[] records = database.RootElement.EnumerateArray().ToArray();
            string[] recordFiles = records.Select(record => record.GetProperty("file").GetString()!).Order(StringComparer.Ordinal).ToArray();
            Check(recordFiles.SequenceEqual(librarySources.Append(main).Order(StringComparer.Ordinal)),
                "compile_commands.json must list every original source once: " + string.Join(", ", recordFiles));
            Check(records.All(record => record.GetProperty("arguments").EnumerateArray().Select(item => item.GetString()!)
                    .All(argument => argument != rootInclude && !argument.Contains("-MF", StringComparison.Ordinal) && argument != batchFile)),
                "logical compile commands must not carry batch-only or execution-only arguments");
        }

        // __FILE__: 묶음 TU의 구성원도 단독 TU와 같은 루트 기준 경로다. 유니티를 끈 빌드(다른 변형 디렉터리)와 실행 결과가 같다.
        string unityOutput = await Run(cold);
        NativeBuildResult plain = await Build(standalone);
        Check(plain.UnityBatches == 0 && plain.Actions.Count(action => action.Kind == "Compile" && action.Executed) == librarySources.Length + 1,
            "the verification variant must compile every source as a standalone translation unit");
        string plainOutput = await Run(plain);
        Check(unityOutput == plainOutput && !unityOutput.Contains("Unity", StringComparison.Ordinal) &&
            (request.Toolchain.Platform == NativePlatform.Android || unityOutput.Replace('\\', '/').StartsWith("src/member0.cpp\nsrc/member1.cpp\n", StringComparison.Ordinal)),
            "__FILE__ in a unity batch must equal the standalone translation unit:\n" + unityOutput + "\n---\n" + plainOutput);

        // 변형 object 디렉터리: 두 변형이 서로의 object를 덮어쓰지 않는다 — 다시 유니티로 돌아가도 compile은 0이다.
        string unityObjects = Path.Combine(unity.OutputDirectory, "obj", "UnityLib", "u1p1");
        string plainObjects = Path.Combine(unity.OutputDirectory, "obj", "UnityLib", "u0p1");
        Check(Directory.GetFiles(unityObjects).Length == 10 && Directory.GetFiles(plainObjects).Length == librarySources.Length * 2,
            "each variant keeps its objects and dependency records in its own directory");
        NativeBuildResult back = await Build(unity);
        Check(back.Actions.Count(action => action.Kind == "Compile" && action.Executed) == 0, "switching back to the unity variant must not recompile");
        Check(File.Exists(batchFile), "the verification variant must not delete the unity variant's batch files");

        // 도구 빌드 ID manifest는 유니티 켬·끔에서 같다(compile 부분이 논리 명령이고 link의 object가 원본 소스 키 목록이다).
        NativeBuildRequest versioned = unity with { EngineVersion = new EngineVersion(1, 2, 3) };
        string unityManifest = BuildInfoGenerator.Manifest(versioned, ActionGraph.Create(versioned), "UnityApp", new string('0', 64), new FileDigests());
        NativeBuildRequest versionedStandalone = versioned with { Unity = false };
        string plainManifest = BuildInfoGenerator.Manifest(versionedStandalone, ActionGraph.Create(versionedStandalone), "UnityApp", new string('0', 64), new FileDigests());
        Check(unityManifest == plainManifest && unityManifest.Contains("arg: obj:src:src/member0.cpp\n", StringComparison.Ordinal) &&
            !unityManifest.Contains(".Unity.", StringComparison.Ordinal) && !unityManifest.Contains("-MF", StringComparison.Ordinal),
            "the tool build ID manifest must not depend on the unity mode:\n" + unityManifest + "\n---\n" + plainManifest);

        // 구성원 하나를 고치면 그 묶음만 다시 컴파일한다. 단독 TU를 고치면 그 TU만이다.
        File.AppendAllText(members[2], "// edited\n");
        NativeBuildResult edited = await Build(unity);
        string[] editedCompiles = edited.Actions.Where(action => action.Kind == "Compile" && action.Executed).Select(action => action.Id).ToArray();
        Check(editedCompiles.SequenceEqual([batch.Id]), "a member edit must recompile only its batch: " + string.Join(", ", editedCompiles));
        File.AppendAllText(excluded, "// edited\n");
        NativeBuildResult excludedEdited = await Build(unity);
        Check(excludedEdited.Actions.Count(action => action.Kind == "Compile" && action.Executed) == 1 &&
            excludedEdited.Actions.Single(action => action.Kind == "Compile" && action.Executed).Id != batch.Id,
            "a standalone source edit must not recompile the batch");

        // 정리: 이번 변형 디렉터리와 묶음 디렉터리의 낡은 파일은 성공한 빌드가 지운다. 다른 변형 디렉터리는 건드리지 않는다.
        string staleObject = Path.Combine(unityObjects, "stale.obj");
        string staleBatch = Path.Combine(Path.GetDirectoryName(batchFile)!, "UnityLib.Unity.000000000000.cpp");
        string staleFlat = Path.Combine(unity.OutputDirectory, "obj", "UnityLib", "flat.obj");
        string otherVariant = Path.Combine(plainObjects, "kept.obj");
        foreach (string stale in new[] { staleObject, staleBatch, staleFlat, otherVariant })
        {
            File.WriteAllText(stale, "stale");
        }

        Check((await Build(unity)).ExecutedActions == 0, "stale files must not invalidate the build");
        Check(!File.Exists(staleObject) && !File.Exists(staleBatch) && !File.Exists(staleFlat) && File.Exists(otherVariant),
            "a successful build must delete stale files of its variant only");
        File.Delete(otherVariant);
    }

    private static async Task BatchesReflectionSourcesAsync(NativeBuildRequest request, string root)
    {
        string fixture = Directory.CreateDirectory(Path.Combine(root, "unity-reflection")).FullName;
        string Write(string relative, string content)
        {
            string path = Path.GetFullPath(Path.Combine(fixture, relative));
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, content);
            return path;
        }

        string output = Path.Combine(fixture, "out");
        string[] generated = Enumerable.Range(0, 3).Select(index => Write($"out/Generated/Reflected/Source/Public/Type{index}.generated.cpp",
            $"int Generated{index}() noexcept;\nint Generated{index}() noexcept {{ return {index + 1}; }}\n")).ToArray();
        string hand = Write("src/hand.cpp", "int Hand() noexcept;\nint Hand() noexcept { return 10; }\n");
        string main = Write("app/main.cpp", "int Generated0() noexcept;\nint Generated1() noexcept;\nint Generated2() noexcept;\nint Hand() noexcept;\n" +
            "int main() { return Generated0() + Generated1() + Generated2() + Hand() == 16 ? 0 : 9; }\n");
        NativeModuleInput reflected = new()
        {
            Name = "Reflected",
            Sources = [hand],
            ReflectionSources = generated,
            UnityAnchorFiles = int.MaxValue,
            ReflectionSourceFailureNote = "note: RMC3000: fixture"
        };
        NativeBuildRequest build = request with
        {
            RootDirectory = fixture,
            OutputDirectory = output,
            Modules = [reflected, new() { Name = "ReflectedApp", Kind = NativeModuleKind.Executable, Sources = [main], PublicDependencies = ["Reflected"] }],
            Targets = ["ReflectedApp"]
        };
        // 손으로 쓴 소스는 모듈의 Unity 기본값(끔)을 따르고, 리플렉션 생성 소스는 기본으로 자기들끼리 묶인다.
        NativePlan plan = ActionGraph.Create(build);
        UnityBatch batch = plan.UnityBatches.Single();
        NativeAction batchAction = plan.Actions.Single(action => action.Members is not null);
        Check(batch.Members.Order(StringComparer.Ordinal).SequenceEqual(generated.Order(StringComparer.Ordinal)) && batch.IncludeRoots.SequenceEqual([output]) &&
            batch.Content.Contains("#include \"Generated/Reflected/Source/Public/Type0.generated.cpp\"\n", StringComparison.Ordinal) &&
            batchAction.FailureNote == reflected.ReflectionSourceFailureNote &&
            plan.Actions.Single(action => action.Source == hand).Members is null,
            "reflection generated sources must be batched among themselves with output-relative spellings");
        Check(ActionGraph.Create(build with { Modules = [reflected with { ReflectionUnity = false }, build.Modules[1]] }).UnityBatches.Count == 0 &&
            ActionGraph.Create(build with { Unity = false }).UnityBatches.Count == 0, "ReflectionUnity = false and --unity off must not batch");
        var builder = new NativeBuildEngine();
        NativeBuildResult result = await builder.BuildAsync(build);
        Check(result.Succeeded && result.UnityBatches == 1, "reflection unity fixture build failed: " + result.Failure + "\n" +
            string.Join("\n", result.Actions.Where(action => !action.Succeeded).Select(action => action.StdOut + action.StdErr)));
        if (request.Toolchain.Platform != NativePlatform.Android)
        {
            ProcessResult run = await ProcessRunner.RunAsync(new(result.ModuleOutputs["ReflectedApp"], [], fixture, request.Toolchain.Environment));
            Check(run.ExitCode == 0, "the batched reflection sources did not link into the executable");
        }

        Check((await builder.BuildAsync(build)).ExecutedActions == 0, "an unchanged reflection unity build must execute zero actions");
    }

    private static void Check(bool condition, string message)
    {
        if (!condition)
        {
            throw new InvalidOperationException(message);
        }
    }
