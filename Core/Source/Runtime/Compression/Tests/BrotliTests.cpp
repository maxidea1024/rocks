// 4096byte마다 위치 번호(index / 4096)의 하위 byte 하나, 나머지는 0이다.
bool MakeSparse(Array<uint8>& data, usize size) {
    if (!data.TryResize(size)) {
        return false;
    }

    for (usize index = 0; index < size; ++index) {
        data[index] = 0;
    }

    for (usize index = 0; index < size; index += 4096) {
        data[index] = static_cast<uint8>((index / 4096) & 0xFF);
    }

    return true;
}

bool MakeExpected(Content content, Array<uint8>& data) {
    data.Clear();
    switch (content) {
    case Content::Empty:
        return true;
    case Content::Golden:
        return data.TryAppend(Text(GoldenText)).IsOk();
    case Content::Random512:
        Fill(data, 512, Pattern::Random, 77);
        return data.Size() == 512;
    case Content::Text1500:
        Fill(data, 1500, Pattern::Text, 78);
        return data.Size() == 1500;
    case Content::Sparse256KiB:
        return MakeSparse(data, (usize{256} << 10) + 5);
    case Content::Sparse3MiB:
        return MakeSparse(data, (usize{3} << 20) + 7);
    }

    return false;
}

const Sample& SampleOf(const uint8* data) {
    for (const Sample& sample : Samples) {
        if (sample.data == data) {
            return sample;
        }
    }

    return Samples[0];
}

bool DecompressInChunks(DecompressStream& stream, Span<const uint8> input, usize chunk,
                        Array<uint8>& output) {
    for (usize offset = 0; offset < input.Size(); offset += chunk) {
        if (!stream.TryWriteAppend(Slice(input, offset, Smaller(chunk, input.Size() - offset)),
                                   output)) {
            return false;
        }
    }

    return true;
}

// TryProcess만으로 해제한다. 한 호출의 출력은 window를 넘지 않아야 한다(역압).
bool DecompressWithBackpressure(DecompressStream& stream, Span<const uint8> input, usize inputChunk,
                                usize window, Array<uint8>& output) {
    Array<uint8> scratch(output.GetAllocator());
    if (!scratch.TryResize(window)) {
        return false;
    }

    usize offset = 0;
    while (true) {
        auto step = stream.TryProcess(
            Slice(input, offset, Smaller(inputChunk, input.Size() - offset)), Whole(scratch));
        if (!step || step.Value().produced > window ||
            !output.TryAppend(Span<const uint8>(scratch.Data(), step.Value().produced))) {
            return false;
        }

        offset += step.Value().consumed;
        if (offset == input.Size() && step.Value().complete) {
            return true;
        }

        if (step.Value().consumed == 0 && step.Value().produced == 0) {
            return false;
        }
    }
}

// 손상 입력의 결과로 허용하는 오류다. Brotli에는 checksum이 없어 성공(다른 내용)도 있을 수 있다.
bool IsCorruptionOutcome(ErrorCode error) {
    return error == ErrorCode::None || error == ErrorCode::InvalidArgument ||
           error == ErrorCode::CapacityExceeded || error == ErrorCode::Unsupported;
}

// N번째 확인부터 취소를 보고하는 probe다. 확인 횟수도 센다.
struct CountdownProbe {
    uint32 remaining;
    uint32 checks = 0;

    static bool Check(void* raw) noexcept {
        auto& self = *static_cast<CountdownProbe*>(raw);
        ++self.checks;
        if (self.remaining == 0) {
            return true;
        }

        --self.remaining;
        return false;
    }
};

