// Brotli stream은 이어 붙일 수 없다. 끝난 뒤 남은 byte(쓰레기·두 번째 stream)는 모든 경로에서
// InvalidArgument다. 해제기는 입력을 넘겨 읽지 않으므로 1byte도 검출한다.
TEST(Brotli_TrailingBytesAndConcatenationAreRejected) {
    SystemAllocator allocator;
    {
        static constexpr uint8 Junk[] = {0x00};
        const uint8* const Picks[] = {EmptyQ11W22, GoldenQ5W10, Random512Q11W22,
                                      Text1500FontQ11W22};
        for (const uint8* pick : Picks) {
            const Sample& sample = SampleOf(pick);
            Array<uint8> expected(allocator);
            REQUIRE(MakeExpected(sample.content, expected));
            const usize size = expected.Size();

            Array<uint8> trailing(allocator);
            REQUIRE(trailing.TryAppend(sample.Encoded()));
            REQUIRE(trailing.TryAppend(Bytes(Junk)));
            Array<uint8> twice(allocator);
            REQUIRE(twice.TryAppend(sample.Encoded()));
            REQUIRE(twice.TryAppend(sample.Encoded()));
            const Span<const uint8> Inputs[] = {View(trailing), View(twice)};
            for (Span<const uint8> input : Inputs) {
                Array<uint8> fixed(allocator);
                REQUIRE(fixed.TryResize(size * 2 + 1));
                CHECK(TryDecompress(Format, input, Whole(fixed), allocator).Error() ==
                      ErrorCode::InvalidArgument);
                Array<uint8> output(allocator);
                REQUIRE(output.TryAppend(Text("keep")));
                CHECK(TryDecompressAppend(Format, input, size * 2 + 1, output).Error() ==
                      ErrorCode::InvalidArgument);
                CHECK(output.Size() == 4);

                auto stream = DecompressStream::TryCreate(Format, Limits(size * 2 + 1), allocator);
                REQUIRE(stream);
                Array<uint8> streamed(allocator);
                CHECK(stream.Value().TryWriteAppend(input, streamed).Error() ==
                      ErrorCode::InvalidArgument);
                CHECK(stream.Value().TryFinish().Error() == ErrorCode::InvalidArgument);

                // 조각으로 나눠도 같다(조각 7은 stream 끝과 뒤 byte가 한 조각에 오는 경우를
                // 포함한다).
                const usize Chunks[] = {1, 7};
                for (usize chunk : Chunks) {
                    stream.Value().Reset();
                    streamed.Clear();
                    CHECK(!DecompressInChunks(stream.Value(), input, chunk, streamed));
                    CHECK(stream.Value().TryFinish().Error() == ErrorCode::InvalidArgument);
                }
            }

            // 경계에 닿은 뒤 받은 byte는 그 호출에서 거부한다. 실패는 Reset 전까지 유지한다.
            auto stream = DecompressStream::TryCreate(Format, Limits(size * 2 + 1), allocator);
            REQUIRE(stream);
            Array<uint8> streamed(allocator);
            REQUIRE(stream.Value().TryWriteAppend(sample.Encoded(), streamed));
            CHECK(stream.Value().IsAtStreamBoundary());
            CHECK(stream.Value().TryWriteAppend(Bytes(Junk), streamed).Error() ==
                  ErrorCode::InvalidArgument);
            CHECK(!stream.Value().IsAtStreamBoundary());
            CHECK(stream.Value().TryWriteAppend(Span<const uint8>(), streamed).Error() ==
                  ErrorCode::InvalidArgument);
            stream.Value().Reset();
            streamed.Clear();
            CHECK(stream.Value().TryWriteAppend(sample.Encoded(), streamed));
            CHECK(stream.Value().TryFinish() && Same(streamed, View(expected)));
        }
    }

    CHECK(allocator.Stats().liveAllocations == 0);
}

