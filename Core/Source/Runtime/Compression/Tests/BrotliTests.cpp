//
// 벡터는 저장소 밖의 참조 encoder가 만들었다: Python 3 + `pip install brotli==1.1.0`(google/brotli
// 1.1.0 encoder의 공식 binding). 저장소에는 encoder가 없고 decoder(1.1.1)만 있으므로 독립 자료다.
// 생성 방법(같은 byte가 다시 나온다):
//   payload = brotli.compress(data, mode=MODE, quality=Q, lgwin=W)   # MODE 기본은 MODE_GENERIC
//   assert brotli.decompress(payload) == data
// - data는 각 벡터 주석의 입력이다. Fill은 CompressionTestSupport.h의 Fill(xorshift64, Words
