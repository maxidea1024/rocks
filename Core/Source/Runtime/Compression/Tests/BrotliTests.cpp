// bit 하나를 뒤집은 입력은 손상 오류 또는(checksum이 없어) 다른 내용의 성공이다. 어느 쪽이든 출력
// 범위·상한 밖에 쓰지 않고 누수가 없다(ASan 구성이 범위 밖 접근을 잡는다).
TEST(Brotli_BitFlipsStayWithinBounds) {
    SystemAllocator allocator;
    {
        const uint8* const Picks[] = {GoldenQ11W22, Random512Q11W22, Text1500FontQ11W22};
        for (const uint8* pick : Picks) {
            const Sample& sample = SampleOf(pick);
            Array<uint8> expected(allocator);
            REQUIRE(MakeExpected(sample.content, expected));
            const usize limit = expected.Size() * 2;
            Array<uint8> corrupt(allocator);
            REQUIRE(corrupt.TryAppend(sample.Encoded()));
            Array<uint8> fixed(allocator);
            REQUIRE(fixed.TryResize(limit));
            usize detected = 0;
            for (usize index = 0; index < corrupt.Size(); ++index) {
                for (uint32 bit = 0; bit < 8; ++bit) {
                    corrupt[index] = static_cast<uint8>(corrupt[index] ^ (1u << bit));
                    auto written = TryDecompress(Format, View(corrupt), Whole(fixed), allocator);
                    CHECK(IsCorruptionOutcome(written.Error()));
                    CHECK(!written || written.Value() <= limit);
                    detected += written ? 0 : 1;

                    Array<uint8> output(allocator);
                    auto appended = TryDecompressAppend(Format, View(corrupt), limit, output);
                    CHECK(IsCorruptionOutcome(appended.Error()));
                    CHECK(appended ? output.Size() == appended.Value() && output.Size() <= limit
                                   : output.Size() == 0);

                    if (bit == index % 8) {
                        auto stream = DecompressStream::TryCreate(Format, Limits(limit), allocator);
                        REQUIRE(stream);
                        Array<uint8> streamed(allocator);
                        auto step = stream.Value().TryWriteAppend(View(corrupt), streamed);
                        CHECK(IsCorruptionOutcome(step.Error()));
                        CHECK(streamed.Size() <= limit);
                    }

                    corrupt[index] = static_cast<uint8>(corrupt[index] ^ (1u << bit));
                }
            }

            // 헤더·Huffman 부호의 bit 오류는 형식 오류로 드러난다(비압축 metablock의 내용 byte는
            // 검출할 수 없다).
            CHECK(detected > 0);
        }
    }

    CHECK(allocator.Stats().liveAllocations == 0);
}

// 압축 폭탄(54byte → 64MiB)도 상한까지만 출력하고, 작업 메모리는 출력 크기가 아니라 window로
// 묶인다(이 폭탄은 16MiB metablock이라 ring buffer가 처음부터 window 크기다. ring buffer를 늘리는
// 경우의 최고값은 Brotli_AllocationsGoThroughInjectedAllocator). 스트림은 window를 maxWindowLog로
// 먼저 거른다.
TEST(Brotli_DecompressionBombsStayBounded) {
    SystemAllocator system;
    CountingAllocator counting(system);
    constexpr usize Limit = usize{1} << 20;
    constexpr usize Window = usize{16} << 20;
    constexpr usize Tables = usize{3} << 20;
    const Span<const uint8> bomb = Bytes(ZerosBombQ11W24);
    {
        counting.ResetPeak();
        {
            Array<uint8> output(counting);
            CHECK(TryDecompressAppend(Format, bomb, Limit, output).Error() ==
                  ErrorCode::CapacityExceeded);
            CHECK(output.Size() == 0);
        }

        CHECK(counting.Peak() < Window + Limit * 2 + Tables);

        counting.ResetPeak();
        {
            auto decoder = DecompressStream::TryCreate(Format, Limits(Limit), counting);
            REQUIRE(decoder);
            Array<uint8> streamed(counting);
            CHECK(decoder.Value().TryWriteAppend(bomb, streamed).Error() ==
                  ErrorCode::CapacityExceeded);
            CHECK(streamed.Size() == 0);
        }

        CHECK(counting.Peak() < Window + Limit * 2 + Tables);

        // window 상한 22: 첫 byte(WBITS 24)에서 거부하므로 ring buffer를 잡지 않는다(해제기 상태
        // 약 7KiB만 남는다. 출력은 따로 센다).
        counting.ResetPeak();
        {
            auto decoder =
                DecompressStream::TryCreate(Format, Limits(usize{64} << 20, 22), counting);
            REQUIRE(decoder);
            Array<uint8> streamed(system);
            CHECK(decoder.Value().TryWriteAppend(bomb, streamed).Error() ==
                  ErrorCode::CapacityExceeded);
        }

        CHECK(counting.Peak() < (usize{64} << 10));

        // 상한이 충분하면 64KiB 출력 창으로 끝까지 풀린다(전체를 한 번에 잡지 않는다).
        auto decoder = DecompressStream::TryCreate(Format, Limits(usize{64} << 20), counting);
        REQUIRE(decoder);
        Array<uint8> window(system);
        REQUIRE(window.TryResize(usize{64} << 10));
        usize consumed = 0;
        usize total = 0;
        bool zeros = true;
        bool complete = false;
        for (uint32 call = 0; call < 4096 && !complete; ++call) {
            auto step = decoder.Value().TryProcess(Slice(bomb, consumed, bomb.Size() - consumed),
                                                   Whole(window));
            REQUIRE(step);
            consumed += step.Value().consumed;
            for (usize index = 0; index < step.Value().produced; ++index) {
                zeros = zeros && window[index] == 0;
            }

            total += step.Value().produced;
            complete = step.Value().complete;
        }

        CHECK(complete && zeros && consumed == bomb.Size() && total == (usize{64} << 20));
        CHECK(decoder.Value().TryFinish());
    }

    CHECK(counting.Current() == 0);
}

// 스트림의 maxWindowLog는 stream 첫 byte의 WBITS와 비교한다. large window 확장 stream은 모든
// 경로에서 Unsupported이고, 일회성 경로는 해제기를 만들기 전에 거부한다.
TEST(Brotli_WindowLimitAndLargeWindowMarker) {
    SystemAllocator system;
    CountingAllocator counting(system);
    {
        for (const Sample& sample : Samples) {
            Array<uint8> expected(system);
            REQUIRE(MakeExpected(sample.content, expected));
            const usize limit = expected.Size() == 0 ? 1 : expected.Size();

            auto fits =
                DecompressStream::TryCreate(Format, Limits(limit, sample.windowBits), counting);
            REQUIRE(fits);
            Array<uint8> output(system);
            CHECK(fits.Value().TryWriteAppend(sample.Encoded(), output));
            CHECK(fits.Value().TryFinish() && Same(output, View(expected)));

            if (sample.windowBits > MinZstdWindowLog) {
                auto narrow = DecompressStream::TryCreate(
                    Format, Limits(limit, sample.windowBits - 1), counting);
                REQUIRE(narrow);
                Array<uint8> rejected(system);
                CHECK(narrow.Value()
                          .TryWriteAppend(Slice(sample.Encoded(), 0, 1), rejected)
                          .Error() == ErrorCode::CapacityExceeded);
                CHECK(narrow.Value().TryFinish().Error() == ErrorCode::CapacityExceeded);
            }
        }

        const Span<const uint8> marker = Bytes(LargeWindowMarker);
        const uint64 before = counting.Allocations();
        Array<uint8> fixed(system);
        REQUIRE(fixed.TryResize(64));
        CHECK(TryDecompress(Format, marker, Whole(fixed), counting).Error() ==
              ErrorCode::Unsupported);
        CHECK(counting.Allocations() == before);
        Array<uint8> output(counting);
        CHECK(TryDecompressAppend(Format, marker, 64, output, counting).Error() ==
              ErrorCode::Unsupported);
        CHECK(counting.Allocations() == before && output.Capacity() == 0);
        auto decompressor = Decompressor::TryCreate(Format, counting);
        REQUIRE(decompressor);
        CHECK(decompressor.Value().TryDecompress(marker, Whole(fixed)).Error() ==
              ErrorCode::Unsupported);
        auto stream = DecompressStream::TryCreate(Format, Limits(64, MaxZstdWindowLog), counting);
        REQUIRE(stream);
        CHECK(stream.Value().TryWriteAppend(Slice(marker, 0, 1), output).Error() ==
              ErrorCode::Unsupported);

        // 첫 byte 256개 전부: Unsupported는 large window 표지(0x11)뿐이다. 표지 다음 bit가 1인
        // 0x91은 어느 모드에서도 예약 값이라 손상(InvalidArgument)이다.
        for (uint32 first = 0; first < 256; ++first) {
            const uint8 single[] = {static_cast<uint8>(first)};
            auto once = TryDecompress(Format, Bytes(single), Whole(fixed), counting);
            CHECK(IsCorruptionOutcome(once.Error()));
            CHECK((once.Error() == ErrorCode::Unsupported) == (first == 0x11));
            stream.Value().Reset();
            Array<uint8> sink(system);
            auto step = stream.Value().TryWriteAppend(Bytes(single), sink);
            CHECK((step.Error() == ErrorCode::Unsupported) == (first == 0x11));
        }

        static constexpr uint8 ReservedWindow[] = {0x91, 0x00, 0x00, 0x00};
        CHECK(TryDecompress(Format, Bytes(ReservedWindow), Whole(fixed), counting).Error() ==
              ErrorCode::InvalidArgument);
        stream.Value().Reset();
        CHECK(stream.Value().TryWriteAppend(Bytes(ReservedWindow), output).Error() ==
              ErrorCode::InvalidArgument);
    }

    CHECK(counting.Current() == 0);
}

// 스트림 실패(손상)는 Reset 전까지 유지한다. Reset은 진행 중·끝난·실패한 어느 상태에서도 새
// stream을 시작한다(해제기 상태를 새로 만든다).
TEST(Brotli_StreamResetAndStickyFailure) {
    SystemAllocator allocator;
    {
        Array<uint8> text(allocator);
        REQUIRE(MakeExpected(Content::Text1500, text));
        Array<uint8> sparse(allocator);
        REQUIRE(MakeExpected(Content::Sparse256KiB, sparse));

        auto stream = DecompressStream::TryCreate(Format, Limits(usize{1} << 20), allocator);
        REQUIRE(stream);
        CHECK(!stream.Value().IsAtStreamBoundary());
        CHECK(stream.Value().TryFinish().Error() == ErrorCode::InvalidArgument);

        Array<uint8> output(allocator);
        CHECK(stream.Value().TryWriteAppend(Bytes(BadPaddingStream), output).Error() ==
              ErrorCode::InvalidArgument);
        CHECK(stream.Value().TryWriteAppend(Bytes(Text1500Q9W18), output).Error() ==
              ErrorCode::InvalidArgument);
        CHECK(stream.Value().TryFinish().Error() == ErrorCode::InvalidArgument);
        CHECK(output.Size() == 0);

        stream.Value().Reset();
        CHECK(stream.Value().TryWriteAppend(Bytes(Text1500Q9W18), output));
        CHECK(stream.Value().TryFinish() && Same(output, View(text)));

        // 진행 중 Reset: 앞 stream(window 22)의 상태를 버리고 다른 window(18)의 stream을 푼다.
        stream.Value().Reset();
        output.Clear();
        REQUIRE(stream.Value().TryWriteAppend(Slice(Bytes(Text1500FontQ11W22), 0, 300), output));
        stream.Value().Reset();
        output.Clear();
        CHECK(stream.Value().TryWriteAppend(Bytes(Sparse256KiBQ1W18), output));
        CHECK(stream.Value().TryFinish() && Same(output, View(sparse)));

        // 끝난 뒤 Reset: 같은 객체로 다음 stream을 푼다.
        for (uint32 round = 0; round < 3; ++round) {
            stream.Value().Reset();
            output.Clear();
            CHECK(DecompressInChunks(stream.Value(), Bytes(Text1500FontQ11W22), 64, output));
            CHECK(stream.Value().TryFinish() && Same(output, View(text)));
        }
    }

    CHECK(allocator.Stats().liveAllocations == 0);
}

// 모든 할당 시도 위치에서 실패시킨다: OutOfMemory, 누수 0, Append 길이 복원. 스트림 실패(Reset의
// 해제기 재생성 실패 포함)는 다음 Reset까지 유지하고, Reset 뒤에는 다시 성공한다.
TEST(Brotli_OutOfMemoryAtEveryAllocationRollsBack) {
    SystemAllocator system;
    NFailAllocator failing(system);
    const uint8* const Picks[] = {Text1500FontQ11W22, Sparse256KiBQ1W18};
    for (const uint8* pick : Picks) {
        const Sample& sample = SampleOf(pick);
        const Span<const uint8> encoded = sample.Encoded();
        Array<uint8> expected(system);
        REQUIRE(MakeExpected(sample.content, expected));
        const uint64 baseline = system.Stats().liveAllocations;

        // Append: 해제기 상태·ring buffer·Huffman 표·출력 성장(64KiB부터 두 배씩).
        bool succeeded = false;
        uint64 failures = 0;
        for (uint64 attempt = 1; attempt <= 64 && !succeeded; ++attempt) {
            {
                Array<uint8> output(failing);
                failing.DisableFailure();
                REQUIRE(output.TryAppend(Text("base")));
                failing.FailOnAttempt(attempt);
                auto result = TryDecompressAppend(Format, encoded, expected.Size(), output);
                succeeded = result.IsOk();
                failures += succeeded ? 0 : 1;
                CHECK(!succeeded || failing.Attempts() < attempt);
                CHECK(succeeded || result.Error() == ErrorCode::OutOfMemory);
                CHECK(succeeded ? Same(Slice(View(output), 4, output.Size() - 4), View(expected))
                                : output.Size() == 4);
            }

            CHECK(system.Stats().liveAllocations == baseline);
        }

        CHECK(succeeded && failures >= 3);

        // Span: 작업 메모리만 할당한다.
        Array<uint8> fixed(system);
        REQUIRE(fixed.TryResize(expected.Size()));
        succeeded = false;
        for (uint64 attempt = 1; attempt <= 32 && !succeeded; ++attempt) {
            failing.FailOnAttempt(attempt);
            auto result = TryDecompress(Format, encoded, Whole(fixed), failing);
            succeeded = result.IsOk();
            CHECK(!succeeded || failing.Attempts() < attempt);
            CHECK(succeeded || result.Error() == ErrorCode::OutOfMemory);
            CHECK(system.Stats().liveAllocations == baseline + 1);
        }

        CHECK(succeeded && Same(fixed, View(expected)));

        // 문맥: 문맥 생성은 상태 블록 하나다. 해제마다 해제기 상태를 새로 만든다.
        succeeded = false;
        for (uint64 attempt = 1; attempt <= 32 && !succeeded; ++attempt) {
            failing.FailOnAttempt(attempt);
            auto decompressor = Decompressor::TryCreate(Format, failing);
            auto result = decompressor ? decompressor.Value().TryDecompress(encoded, Whole(fixed))
                                       : Result<usize>::Failure(decompressor.Error());
            succeeded = result.IsOk();
            CHECK(succeeded || result.Error() == ErrorCode::OutOfMemory);
        }

        CHECK(succeeded);
        CHECK(system.Stats().liveAllocations == baseline + 1);

        // 스트림 생성·해제.
        succeeded = false;
        for (uint64 attempt = 1; attempt <= 64 && !succeeded; ++attempt) {
            {
                failing.FailOnAttempt(attempt);
                auto decoder =
                    DecompressStream::TryCreate(Format, Limits(expected.Size()), failing);
                if (!decoder) {
                    CHECK(decoder.Error() == ErrorCode::OutOfMemory);
                    continue;
                }

                Array<uint8> output(failing);
                auto written = decoder.Value().TryWriteAppend(encoded, output);
                succeeded = written.IsOk();
                CHECK(!succeeded || failing.Attempts() < attempt);
                if (!succeeded) {
                    CHECK(written.Error() == ErrorCode::OutOfMemory);
                    CHECK(output.Size() == 0);
                    CHECK(decoder.Value().TryFinish().Error() == ErrorCode::OutOfMemory);
                    failing.DisableFailure();
                    decoder.Value().Reset();
                    REQUIRE(decoder.Value().TryWriteAppend(encoded, output));
                }

                CHECK(decoder.Value().TryFinish() && Same(output, View(expected)));
            }

            CHECK(system.Stats().liveAllocations == baseline + 1);
        }

        CHECK(succeeded);

        // Reset의 해제기 재생성 실패(상태·shared dictionary 상태): 실패 상태가 다음 Reset까지
        // 남는다.
        for (uint64 attempt = 1; attempt <= 2; ++attempt) {
            failing.DisableFailure();
            auto decoder = DecompressStream::TryCreate(Format, Limits(expected.Size()), failing);
            REQUIRE(decoder);
            Array<uint8> output(system);
            REQUIRE(decoder.Value().TryWriteAppend(encoded, output));
            failing.FailOnAttempt(attempt);
            decoder.Value().Reset();
            CHECK(failing.Attempts() == attempt);
            CHECK(decoder.Value().TryFinish().Error() == ErrorCode::OutOfMemory);
            CHECK(!decoder.Value().IsAtStreamBoundary());
            CHECK(decoder.Value().TryWriteAppend(encoded, output).Error() ==
                  ErrorCode::OutOfMemory);
            failing.DisableFailure();
            decoder.Value().Reset();
            output.Clear();
            CHECK(decoder.Value().TryWriteAppend(encoded, output));
            CHECK(decoder.Value().TryFinish() && Same(output, View(expected)));
        }

        CHECK(system.Stats().liveAllocations == baseline + 1);
    }
}

// 해제기 상태·ring buffer·Huffman 표가 모두 주입한 할당기를 거친다(CRT 직접 할당 없음). 일회성
// 해제는 호출 안에서 모두 반환하고, 문맥은 해제기 상태를 들고 있지 않으며, 스트림은 Reset이 이전
// 해제기 메모리를 반환한다. ring buffer는 window가 커도 출력에 필요한 만큼만 잡는다.
TEST(Brotli_AllocationsGoThroughInjectedAllocator) {
    SystemAllocator system;
    CountingAllocator counting(system);
    {
        Array<uint8> sparse(system);
        REQUIRE(MakeExpected(Content::Sparse3MiB, sparse));
        Array<uint8> fixed(system);
        REQUIRE(fixed.TryResize(sparse.Size()));

        uint64 before = counting.Allocations();
        counting.ResetPeak();
        REQUIRE(TryDecompress(Format, Bytes(Sparse3MiBQ11W24), Whole(fixed), counting));
        CHECK(Same(fixed, View(sparse)));
        CHECK(counting.Allocations() >= before + 3);
        CHECK(counting.Current() == 0);
        // ring buffer(출력 3MiB를 담는 4MiB)가 주입한 할당기를 거쳤다. window(16MiB)보다 작다.
        CHECK(counting.Peak() >= sparse.Size());
        CHECK(counting.Peak() < (usize{8} << 20));

        // window 16MiB stream이라도 64byte 출력이면 ring buffer가 작다.
        Array<uint8> golden(system);
        REQUIRE(golden.TryResize(64));
        counting.ResetPeak();
        REQUIRE(TryDecompress(Format, Bytes(GoldenQ11W24), Whole(golden), counting));
        CHECK(counting.Peak() < (usize{64} << 10));
        CHECK(counting.Current() == 0);

        // ring buffer는 출력에 필요한 크기 이상의 2의 거듭제곱으로 늘고, 늘리는 순간 이전 ring과
        // 함께 있다. 여러 metablock으로 window(1MiB)만큼 출력하면 최고 사용량이 1.25 × window를
        // 넘지만(512KiB ring + 1MiB ring) 1.5 × window + 표를 넘지 않는다.
        Array<uint8> zeros(system);
        Fill(zeros, usize{1} << 20, Pattern::Zeros);
        Array<uint8> grown(system);
        REQUIRE(grown.TryResize(zeros.Size()));
        counting.ResetPeak();
        REQUIRE(TryDecompress(Format, Bytes(ZerosGrowQ1W20), Whole(grown), counting));
        CHECK(Same(grown, View(zeros)));
        CHECK(counting.Peak() > (usize{5} << 18));
        CHECK(counting.Peak() < (usize{3} << 19) + (usize{64} << 10));
        CHECK(counting.Current() == 0);

        auto decompressor = Decompressor::TryCreate(Format, counting);
        REQUIRE(decompressor);
        const usize idle = counting.Current();
        CHECK(idle < 1024);
        for (uint32 round = 0; round < 3; ++round) {
            before = counting.Allocations();
            REQUIRE(decompressor.Value().TryDecompress(Bytes(Sparse3MiBQ11W24), Whole(fixed)));
            CHECK(counting.Allocations() > before);
            CHECK(counting.Current() == idle);
        }

        auto stream = DecompressStream::TryCreate(Format, Limits(sparse.Size()), counting);
        REQUIRE(stream);
        const usize created = counting.Current();
        CHECK(created < (usize{16} << 10));
        Array<uint8> streamed(system);
        REQUIRE(stream.Value().TryWriteAppend(Bytes(Sparse3MiBQ11W24), streamed));
        CHECK(Same(streamed, View(sparse)));
        CHECK(counting.Current() >= sparse.Size());
        stream.Value().Reset();
        CHECK(counting.Current() == created);
    }

    CHECK(counting.Current() == 0);
}

// 분할 루프의 취소 지점: 해제는 입력 소비나 출력 생성 1MiB마다 확인하고, 취소되면 Append 출력
// 길이를 호출 전으로 되돌린다. 압축률이 높은 입력(1KiB → 3MiB)도 출력 1MiB마다 확인한다.
TEST(Brotli_CancellationProbeStopsAtSlices) {
    SystemAllocator allocator;
    {
        Array<uint8> sparse(allocator);
        REQUIRE(MakeExpected(Content::Sparse3MiB, sparse));
        const Span<const uint8> packed = Bytes(Sparse3MiBQ11W24);
        static constexpr uint8 Base[] = {'k', 'e', 'e', 'p'};
        for (uint32 checks = 0; checks < 3; ++checks) {
            CountdownProbe countdown{checks};
            detail::CompressionProbe probe{&CountdownProbe::Check, &countdown};
            Array<uint8> restored(allocator);
            REQUIRE(restored.TryAppend(Bytes(Base)));
            CHECK(detail::DecompressAppendOnce(Format, packed, sparse.Size(), restored, allocator,
                                               probe)
                      .Error() == ErrorCode::Cancelled);
            CHECK(Same(restored, Bytes(Base)));
            CHECK(countdown.checks == checks + 1);

            countdown = CountdownProbe{checks};
            Array<uint8> fixed(allocator);
            REQUIRE(fixed.TryResize(sparse.Size()));
            CHECK(detail::DecompressIntoOnce(Format, packed, Whole(fixed), allocator, probe)
                      .Error() == ErrorCode::Cancelled);
            CHECK(countdown.checks == checks + 1);
        }

        CountdownProbe untouched{1000};
        detail::CompressionProbe probe{&CountdownProbe::Check, &untouched};
        Array<uint8> fixed(allocator);
        REQUIRE(fixed.TryResize(sparse.Size()));
        REQUIRE(detail::DecompressIntoOnce(Format, packed, Whole(fixed), allocator, probe));
        CHECK(untouched.checks >= 4);
        CHECK(Same(fixed, View(sparse)));
    }

    CHECK(allocator.Stats().liveAllocations == 0);
}

// 비동기 해제는 동기 API와 같은 결과를 낸다. 의존 연결·오류 결과(large window·뒤 byte)도 같다.
TEST(Brotli_AsyncMatchesSync) {
    SystemAllocator allocator;
    {
        WorkerScheduler scheduler(allocator);
        REQUIRE(scheduler.Start({.workerCount = 4, .maxInFlight = 64}));
        {
            constexpr uint32 Jobs = 4;
            const uint8* const Picks[Jobs] = {GoldenQ5W10, Random512Q11W22, Text1500FontQ11W22,
                                              Sparse3MiBQ11W24};
            Array<uint8> expected[Jobs] = {Array<uint8>(allocator), Array<uint8>(allocator),
                                           Array<uint8>(allocator), Array<uint8>(allocator)};
            Array<uint8> appended[Jobs] = {Array<uint8>(allocator), Array<uint8>(allocator),
                                           Array<uint8>(allocator), Array<uint8>(allocator)};
            Array<uint8> fixed[Jobs] = {Array<uint8>(allocator), Array<uint8>(allocator),
                                        Array<uint8>(allocator), Array<uint8>(allocator)};
            CompressionTask appendTasks[Jobs];
            CompressionTask fixedTasks[Jobs];
            for (uint32 job = 0; job < Jobs; ++job) {
                const Sample& sample = SampleOf(Picks[job]);
                REQUIRE(MakeExpected(sample.content, expected[job]));
                REQUIRE(fixed[job].TryResize(expected[job].Size()));
                REQUIRE(TrySubmitDecompress(scheduler, appendTasks[job], Format, sample.Encoded(),
                                            expected[job].Size(), appended[job]));
                // Span 해제는 Append 해제 뒤에 실행한다(의존 연결).
                const Span<const WorkerTaskHandle> after(&appendTasks[job].Handle(), 1);
                REQUIRE(TrySubmitDecompress(scheduler, fixedTasks[job], Format, sample.Encoded(),
                                            Whole(fixed[job]), allocator, after));
            }

            for (uint32 job = 0; job < Jobs; ++job) {
                auto bytes = appendTasks[job].TryWaitResult();
                CHECK(bytes && bytes.Value() == expected[job].Size() &&
                      Same(appended[job], View(expected[job])));
                auto fixedBytes = fixedTasks[job].TryWaitResult();
                CHECK(fixedBytes && fixedBytes.Value() == expected[job].Size() &&
                      Same(fixed[job], View(expected[job])));
            }

            // 실패 결과도 동기와 같다. 실패한 Append는 output 길이를 되돌린다.
            Array<uint8> trailing(allocator);
            REQUIRE(trailing.TryAppend(Bytes(GoldenQ11W22)));
            REQUIRE(trailing.TryAppend(Bytes(GoldenQ11W22)));
            CompressionTask largeTask;
            CompressionTask trailingTask;
            Array<uint8> largeOutput(allocator);
            REQUIRE(largeOutput.TryAppend(Text("keep")));
            Array<uint8> trailingOutput(allocator);
            REQUIRE(TrySubmitDecompress(scheduler, largeTask, Format, Bytes(LargeWindowMarker), 64,
                                        largeOutput));
            REQUIRE(TrySubmitDecompress(scheduler, trailingTask, Format, View(trailing), 1024,
                                        trailingOutput));
            CHECK(largeTask.TryWaitResult().Error() == ErrorCode::Unsupported);
            CHECK(largeOutput.Size() == 4);
            CHECK(trailingTask.TryWaitResult().Error() == ErrorCode::InvalidArgument);
            CHECK(trailingOutput.Size() == 0);

            // 빈 해제 입력과 모르는 형식은 제출 시점에 거부한다.
            CompressionTask empty;
            CompressionTask unknown;
            Array<uint8> output(allocator);
            CHECK(TrySubmitDecompress(scheduler, empty, Format, Span<const uint8>(), 1, output)
                      .Error() == ErrorCode::InvalidArgument);
            CHECK(TrySubmitDecompress(scheduler, unknown, UnknownFormat, Bytes(GoldenQ11W22), 64,
                                      output)
                      .Error() == ErrorCode::InvalidArgument);
        }

        REQUIRE(scheduler.Shutdown());
    }

    CHECK(allocator.Stats().liveAllocations == 0);
}

// WOFF2(W3C WOFF File Format 2.0) 방식의 사용: 글꼴 표 전체가 Brotli stream 하나이고, 읽는 쪽은 표
// 디렉터리에 기록된 표 길이(변환 뒤)의 합만큼 버퍼를 잡아 크기를 아는 TryDecompress로 한 번에 푼다.
// 결과 크기가 합과 다르면 상위 포맷 오류로 처리한다. 참조 구현(google/woff2)은 quality 11,
// window 22, MODE_FONT로 압축하며 이 벡터도 같은 설정이다. WOFF2 표 변환(glyf·loca·hmtx 복원)은
// 이 모듈 밖의 글꼴 importer 몫이다.
TEST(Brotli_Woff2StyleKnownSizeDecode) {
    SystemAllocator allocator;
    {
        Array<uint8> tables(allocator);
        REQUIRE(MakeExpected(Content::Text1500, tables));
        const usize totalSize = tables.Size();
        const Span<const uint8> fontData = Bytes(Text1500FontQ11W22);

        auto decompressor = Decompressor::TryCreate(Format, allocator);
        REQUIRE(decompressor);
        Array<uint8> buffer(allocator);
        REQUIRE(buffer.TryResize(totalSize));
        auto written = decompressor.Value().TryDecompress(fontData, Whole(buffer));
        CHECK(written && written.Value() == totalSize && Same(buffer, View(tables)));

        // 헤더가 더 큰 크기를 선언하면 결과가 작게 나와 호출자가 불일치를 본다.
        REQUIRE(buffer.TryResize(totalSize + 16));
        written = decompressor.Value().TryDecompress(fontData, Whole(buffer));
        CHECK(written && written.Value() == totalSize);

        // 더 작은 크기를 선언하면 CapacityExceeded다.
        REQUIRE(buffer.TryResize(totalSize - 1));
        CHECK(decompressor.Value().TryDecompress(fontData, Whole(buffer)).Error() ==
              ErrorCode::CapacityExceeded);
    }

    CHECK(allocator.Stats().liveAllocations == 0);
}

