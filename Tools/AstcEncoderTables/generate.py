"""Generates astcenc_rocks_angular_tables.h and astcenc_rocks_log10_table.h for ThirdParty AstcEncoder (Rocks.patch).

astc-encoder 5.1.0 computes the angular sin/cos tables and log10 of the block texel count with the platform libm (sinf,
cosf, logf), so its output can differ between C runtimes. The headers replace those values with the correctly rounded
float results of the same float expressions (Docs/Design/AssetSystem section 12.17.8): a correctly rounding libm gives
upstream bytes, and every platform gets the same tables.

Usage: python Tools/AstcEncoderTables/generate.py Engine/Source/ThirdParty/AstcEncoder/astc-encoder-5.1.0/Source
Requires mpmath (pip install mpmath).
"""
import struct
import sys

import mpmath

mpmath.mp.prec = 200


def f32(x):
    """Rounds a double to the nearest float (ties to even)."""
    return struct.unpack("<f", struct.pack("<f", float(x)))[0]


def f32_exact(x):
    """Rounds an mpmath value to the nearest float without a double rounding error."""
    d = float(x)
    f = f32(d)
    bits = struct.unpack("<I", struct.pack("<f", abs(f)))[0]
    for other_bits in (bits - 1, bits + 1):
        if other_bits < 0:
            continue
        other = struct.unpack("<f", struct.pack("<I", other_bits))[0]
        other = other if f >= 0 else -other
        if mpmath.mpf(d) == (mpmath.mpf(f) + mpmath.mpf(other)) / 2:
            raise SystemExit("double rounding tie at %r: decide with the exact value" % x)
    return f


def hexf(v):
    if v == 0.0:
        return "-0.0f" if struct.pack("<f", v) == struct.pack("<f", -0.0) else "0.0f"
    mantissa, exponent = float.hex(v).split("p")
    return mantissa.rstrip("0").rstrip(".") + "p" + exponent + "f"


PI = f32(3.14159265358979323846)
SINCOS_STEPS = 64
ANGULAR_STEPS = 32

# (2.0f * astc::PI / (SINCOS_STEPS - 1.0f)) * angle_step * static_cast<float>(j), evaluated in float left to right. Double
# products of two floats are exact, and double division then float rounding equals float division (53 >= 2 * 24 + 2).
step = f32(f32(2.0 * PI) / 63.0)
sin_rows = []
cos_rows = []
for j in range(SINCOS_STEPS):
    srow = []
    crow = []
    for i in range(ANGULAR_STEPS):
        arg = f32(f32(step * float(i + 1)) * float(j))
        srow.append(f32_exact(mpmath.sin(mpmath.mpf(arg))))
        crow.append(f32_exact(mpmath.cos(mpmath.mpf(arg))))
    sin_rows.append(srow)
    cos_rows.append(crow)

# logf(texels) / logf(10.0f) for every texel count of a valid 2D or 3D block size.
SIZES_2D = [(4, 4), (5, 4), (5, 5), (6, 5), (6, 6), (8, 5), (8, 6), (10, 5), (10, 6), (8, 8), (10, 8), (10, 10), (12, 10),
            (12, 12)]
SIZES_3D = [(3, 3, 3), (4, 3, 3), (4, 4, 3), (4, 4, 4), (5, 4, 4), (5, 5, 4), (5, 5, 5), (6, 5, 5), (6, 6, 5), (6, 6, 6)]
counts = sorted({x * y for x, y in SIZES_2D} | {x * y * z for x, y, z in SIZES_3D})
ln10 = f32_exact(mpmath.log(10))
logs = [(t, f32_exact(mpmath.mpf(f32_exact(mpmath.log(t))) / mpmath.mpf(ln10))) for t in counts]

NEWLINE = chr(10)
TAB = chr(9)


def header(guard, description, body):
    lines = ["// SPDX-License-Identifier: Apache-2.0",
             "// Rocks: generated by Tools/AstcEncoderTables/generate.py (do not edit).",
             "//"]
    lines += ["// " + line if line else "//" for line in description]
    lines += ["", "#ifndef " + guard, "#define " + guard, ""]
    lines += body
    lines += ["#endif"]
    return NEWLINE.join(lines) + NEWLINE


COMMON = ["Constant replacement for values astc-encoder computes with the platform libm, so the encoder output does not depend",
          "on the C runtime (Docs/Design/AssetSystem section 12.17.8). Each value is the correctly rounded float result of the",
          "upstream float expression."]

log_body = ["/**",
            " * @brief Return logf(texels) / logf(10.0f) for the texel count of a valid block size, or -1 for any other count.",
            " */",
            "static inline float rocks_log10_texel_count(unsigned int texels)",
            "{",
            TAB + "switch (texels)",
            TAB + "{"]
for t, v in logs:
    log_body.append(TAB + "case %d: return %s;" % (t, hexf(v)))
log_body += [TAB + "default: return -1.0f;", TAB + "}", "}", ""]

angular_body = []
for name, rows in (("rocks_sin_table", sin_rows), ("rocks_cos_table", cos_rows)):
    angular_body.append("ASTCENC_ALIGNAS static const float %s[%d][%d] {" % (name, SINCOS_STEPS, ANGULAR_STEPS))
    for row in rows:
        angular_body.append(TAB + "{")
        for k in range(0, ANGULAR_STEPS, 4):
            angular_body.append(TAB + TAB + ", ".join(hexf(v) for v in row[k:k + 4]) + ",")
        angular_body.append(TAB + "},")
    angular_body += ["};", ""]

out_dir = sys.argv[1]
with open(out_dir + "/astcenc_rocks_log10_table.h", "w", encoding="utf-8", newline=NEWLINE) as f:
    f.write(header("ASTCENC_ROCKS_LOG10_TABLE_H_INCLUDED",
                   COMMON + ["", "log10 of the block texel count that astcenc_config_init uses to interpolate the presets."],
                   log_body))
with open(out_dir + "/astcenc_rocks_angular_tables.h", "w", encoding="utf-8", newline=NEWLINE) as f:
    f.write(header("ASTCENC_ROCKS_ANGULAR_TABLES_H_INCLUDED",
                   COMMON + ["", "The angular tables of prepare_angular_tables: sinf and cosf of (2 * PI / 63) * (i + 1) * j for",
                             "weight sample j and angular step i. Constant, so concurrent contexts no longer rewrite shared",
                             "tables."],
                   angular_body))
print("ok", len(logs), logs[0], logs[-1])
