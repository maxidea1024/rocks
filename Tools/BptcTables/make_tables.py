"""BC6H·BC7 기준 디코더 표(TextureBlockBptcTables.h)를 DirectXTex BC6HBC7.cpp에서 뽑는다.

사용(생성 뒤 저장소 clang-format으로 서식을 맞춘다 — clang-format -i <출력>): python Tools/BptcTables/make_tables.py <UE 클론>/Engine/Source/ThirdParty/Intel/ISPCTexComp/ISPCTextureCompressor-14d998c/"ISPC Texture Compressor"/DirectXTex/DirectXTex/BC6HBC7.cpp Engine/Source/Developer/TextureTools/Private/TextureBlockBptcTables.h
"""
import re
import sys

source = open(sys.argv[1], encoding="utf-8", errors="replace").read()
out_path = sys.argv[2]


def block(name):
    start = source.index(name)
    brace = source.index("{", start)
    depth = 0
    for i in range(brace, len(source)):
        if source[i] == "{":
            depth += 1
        elif source[i] == "}":
            depth -= 1
            if depth == 0:
                return source[brace:i + 1]
    raise ValueError(name)


def strip_comments(text):
    text = re.sub(r"//[^\n]*", "", text)
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


partition = [int(v) for v in re.findall(r"\d+", strip_comments(block("g_aPartitionTable[3][64][16] =")))]
assert len(partition) == 3 * 64 * 16, len(partition)
fixup = [int(v) for v in re.findall(r"\d+", strip_comments(block("g_aFixUp[3][64][3] =")))]
assert len(fixup) == 3 * 64 * 3, len(fixup)
fields = ["NA", "M", "D", "RW", "RX", "RY", "RZ", "GW", "GX", "GY", "GZ", "BW", "BX", "BY", "BZ"]
desc_text = strip_comments(block("D3DX_BC6H::ms_aDesc[14][82] ="))
modes = []
for mode_text in re.findall(r"\{((?:\s*\{\s*\w+\s*,\s*\d+\s*\}\s*,?)+)\s*\}", desc_text):
    pairs = re.findall(r"\{\s*(\w+)\s*,\s*(\d+)\s*\}", mode_text)
    modes.append([(fields.index(f), int(b)) for f, b in pairs])
assert len(modes) == 14, len(modes)
for m in modes:
    assert len(m) in (65, 82), len(m)


def rows(values, per_row, indent="    "):
    lines = []
    for i in range(0, len(values), per_row):
        lines.append(indent + ", ".join(str(v) for v in values[i:i + per_row]) + ",")
    return "\n".join(lines)


text = []
text.append("#pragma once")
text.append("")
text.append("#include <Base/Types.h>")
text.append("")
text.append("// Generated by Tools/BptcTables/make_tables.py. Do not edit.")
text.append("// Format tables of the BC6H and BC7 reference decoders (Docs/Design/AssetSystem section 12.17.6 item 9): the values the")
text.append("// D3D11 BC6H and BC7 formats define, extracted from g_aPartitionTable, g_aFixUp and D3DX_BC6H::ms_aDesc of Microsoft")
text.append("// DirectXTex BC6HBC7.cpp (MIT, the copy in the ISPC Texture Compressor sample of the UE clone). The encoder (ISPC kernel)")
text.append("// tables are not used, so the reference decoder stays independent of the encoder under test.")
text.append("namespace rocks::texture_block_detail {")
text.append("")
text.append("// Partition table: [subset count - 2][shape][texel] = subset of the texel (64 shapes each for 2 and 3 subsets).")
text.append("inline constexpr uint8 BptcPartitions[2][64][16] = {")
for subset in (1, 2):
    text.append("    {")
    for shape in range(64):
        base = (subset * 64 + shape) * 16
        text.append("        {" + ", ".join(str(v) for v in partition[base:base + 16]) + "},")
    text.append("    },")
text.append("};")
text.append("")
text.append("// Anchor texel table: [subset count - 2][shape][subset - 1] (the anchor of subset 0 is texel 0). The index of an")
text.append("// anchor texel is stored with one bit less (its top bit is 0).")
text.append("inline constexpr uint8 BptcAnchors[2][64][2] = {")
for subset in (1, 2):
    text.append("    {")
    for shape in range(64):
        base = (subset * 64 + shape) * 3
        text.append("        {" + ", ".join(str(v) for v in fixup[base + 1:base + 3]) + "},")
    text.append("    },")
text.append("};")
text.append("")
text.append("// Meaning of a BC6H header bit: the field and the bit number inside that field.")
text.append("enum class Bc6hField : uint8 {")
text.append("    None,")
text.append("    Mode,")
text.append("    Shape,")
for c in "RGB":
    for e in "WXYZ":
        text.append(f"    {c}{e},")
text.append("};")
text.append("")
text.append("struct Bc6hHeaderBit {")
text.append("    Bc6hField field;")
text.append("    uint8 bit;")
text.append("};")
text.append("")
text.append("// Header bit layout of the 14 modes (82 bits for two-subset modes, 65 for one-subset modes; the rest are None).")
text.append("inline constexpr Bc6hHeaderBit Bc6hHeaders[14][82] = {")
names = ["None", "Mode", "Shape"] + [f"{c}{e}" for c in "RGB" for e in "WXYZ"]
for m in modes:
    text.append("    {")
    entries = [f"{{Bc6hField::{names[f]}, {b}}}" for f, b in m]
    for i in range(0, len(entries), 6):
        text.append("        " + ", ".join(entries[i:i + 6]) + ",")
    text.append("    },")
text.append("};")
text.append("")
text.append("} // namespace rocks::texture_block_detail")
text.append("")
open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(text))
print("ok", len(modes))
